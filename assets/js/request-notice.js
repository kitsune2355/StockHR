/* ============================================================
 *  assets/js/request-notice.js
 *  ประกาศของฝ่ายธุรการ บนหน้าทำรายการเบิก
 *
 *  ขึ้นทุกครั้งที่เข้าหน้านี้ ไม่จำว่าเคยอ่านแล้ว
 *  เพราะเป็นเงื่อนไขที่ต้องทำตาม "ทุกครั้งที่เบิก" ไม่ใช่ความรู้ที่เรียนครั้งเดียวจบ
 *  รอบส่งใบเบิกกับเวลารับของเป็นสิ่งที่ลืมง่าย และลืมแล้วเสียหายจริง
 *  (ส่งผิดรอบ = ได้ของช้าไปครึ่งเดือน)
 *
 *  ต่างจากคู่มือการใช้งาน (app-guide.js) ที่เด้งครั้งแรกครั้งเดียวแล้วจำไว้
 *
 *  ---------------------------------------------------------------
 *  ลำดับการขึ้นกล่อง
 *  ---------------------------------------------------------------
 *  หน้านี้มีทั้งประกาศและคู่มือที่อาจเด้งพร้อมกัน ถ้าปล่อยให้ชนกัน
 *  กล่องหนึ่งจะปิดอีกกล่องทิ้งโดยที่ผู้ใช้ยังไม่ได้อ่าน
 *
 *  ประกาศขึ้นก่อนเสมอ เพราะเป็นเงื่อนไขทางธุรกิจที่มีผลกับของที่จะได้รับ
 *  ส่วนคู่มือเป็นเรื่องวิธีใช้หน้าจอ ซึ่งรอได้ — app-guide.js หน่วงไว้ 900ms
 *  อยู่แล้ว และจะไม่เปิดถ้ามีกล่อง SweetAlert2 ค้างอยู่
 *
 *  เขียนแบบ ES5 ให้ตรงกับไฟล์อื่นในโปรเจกต์
 * ============================================================ */

(function () {
    'use strict';

    var CFG = window.REQUEST_NOTICE;
    if (!CFG || !CFG.lines || CFG.lines.length === 0) { return; }


    function escapeHtml(text) {
        return String(text === null || text === undefined ? '' : text)
            .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
    }


    /* ---------- ประกอบเนื้อหา ----------
     * แต่ละบรรทัดขึ้นต้นด้วย * ในข้อมูลต้นทาง ตัดออกแล้ววาดจุดนำเป็น HTML แทน
     * เพื่อให้เว้นวรรคย่อหน้าตรงกันทุกบรรทัด แม้บรรทัดนั้นจะยาวจนตัดขึ้นบรรทัดใหม่
     * (ถ้าปล่อย * ไว้เป็นข้อความ บรรทัดที่สองจะไหลไปชิดขอบซ้ายจนอ่านยาก)
     */
    function buildHtml() {
        var html = '<ul class="rn-list">';

        for (var i = 0; i < CFG.lines.length; i++) {
            var line = String(CFG.lines[i]).replace(/^\s*[*•\-]\s*/, '').trim();
            if (line === '') { continue; }

            html += '<li>' + escapeHtml(line) + '</li>';
        }

        return html + '</ul>';
    }


    function show() {
        if (!window.Swal) { return; }

        window.Swal.fire({
            title:             CFG.title || 'ประกาศ',
            html:              buildHtml(),
            icon:              'info',
            confirmButtonText: 'รับทราบ',

            /* ต้องใส่ app-swal และ app-swal-confirm ให้ตรงกับกล่องอื่นทั้งระบบ
               ไม่งั้นจะได้พื้นขาวทับหน้าจอโหมดมืด และปุ่มสีม่วงค่าเริ่มต้นของไลบรารี
               ซึ่งไม่ใช่สีของระบบเลยสักที่เดียว */
            buttonsStyling: false,
            heightAuto:     false,
            customClass: {
                popup:         'app-swal rn-popup',
                confirmButton: 'app-swal-confirm'
            },

            /* ต้องกดปุ่มรับทราบเท่านั้น กดนอกกล่องหรือ Esc ปิดไม่ได้
               ประกาศที่ปิดได้ด้วยการกดพลาดหนึ่งครั้ง เท่ากับไม่มีประกาศ */
            allowOutsideClick: false,
            allowEscapeKey:    false
        });
    }


    /* หน่วงเล็กน้อยให้ฟอร์มวาดเสร็จก่อน กล่องจะได้ไม่เด้งทับหน้าจอที่ยังเป็นช่องว่าง
       ซึ่งทำให้รู้สึกเหมือนหน้ายังโหลดไม่เสร็จแล้วมีอะไรมาขวาง */
    function start() {
        window.setTimeout(show, 350);
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', start);
    } else {
        start();
    }
})();
