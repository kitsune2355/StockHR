       'ขนาดที่ตั้งไว้ถูกจำไว้ที่เบราว์เซอร์ของเครื่องที่กำลังใช้อยู่ ผู้ใช้คนอื่นไม่ได้รับผลกระทบแม้แต่คนเดียว และถ้าเปิดระบบจากอีกเครื่องหรืออีกเบราว์เซอร์ ก็ต้องตั้งใหม่ที่นั่น ตั้งใจให้เป็นแบบนี้ เพราะจอคอมกับมือถือเหมาะกับขนาดคนละแบบอยู่แล้ว',
       'over', 'center', NOW() FROM `tb_guide` WHERE `page_key` = 'font_size';


