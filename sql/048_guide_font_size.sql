-- ============================================================
--  048_guide_font_size.sql
--  คู่มือการใช้งานของหน้า "ขนาดตัวอักษร"
--
--  ทุกหน้าในระบบมีคู่มือของตัวเอง หน้าที่เพิ่มใหม่จึงต้องมีด้วย
--  ไม่งั้นปุ่มเครื่องหมายคำถามบนแถบบนจะหายไปเฉพาะหน้านี้
--  ซึ่งดูเหมือนระบบทำงานไม่สม่ำเสมอมากกว่าดูเหมือนตั้งใจ
--
--  ---------------------------------------------------------------
--  เนื้อหาเน้นสองเรื่องที่คนเข้าใจผิดได้ง่ายที่สุด
--  ---------------------------------------------------------------
--  1. ค่านี้เป็นของ "เครื่องที่ใช้อยู่" ไม่ใช่ของบัญชี
--     ปรับที่จอคอมแล้วเปิดจากมือถือจะยังเป็นขนาดเดิม และไม่ไปกระทบใครทั้งนั้น
--     ถ้าไม่บอก จะมีคนคิดว่าตัวเองไปเปลี่ยนขนาดให้ทั้งบริษัท
--
--  2. ปรับแล้วเห็นผลทันทีทั่วทั้งหน้า แต่ยังไม่ถือว่าบันทึก
--     ถ้าเปลี่ยนหน้าไปโดยไม่กดบันทึก ทุกอย่างกลับเป็นขนาดเดิม
--     คนที่ปรับจนพอใจแล้วกดเมนูอื่นต่อเลยจะงงว่าทำไมค่าไม่อยู่
--
--  ---------------------------------------------------------------
--  selector ที่ชี้
--  ---------------------------------------------------------------
--  ใช้ id ที่ตั้งไว้ให้คู่มือโดยเฉพาะใน pages/font_size.php
--  (fsCurrent / fsLevels / fsFine / fsPreview / fsSave)
--  ไม่ชี้ด้วยคลาสหรือลำดับ ซึ่งพังทันทีที่มีคนจัดหน้าใหม่
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hr < sql/048_guide_font_size.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/048_guide_font_size_rollback.sql
-- ============================================================

SET NAMES utf8;

/* ---------- ตัวคู่มือ ----------
   WHERE NOT EXISTS กันรันซ้ำแล้วได้คู่มือซ้อนสองอันของหน้าเดียวกัน */
INSERT INTO `tb_guide` (`page_key`, `title`, `description`, `auto_start`, `is_active`, `created_at`)
SELECT 'font_size', 'ขนาดตัวอักษร',
       'ปรับขนาดตัวอักษรของทั้งระบบให้อ่านสบายตาที่สุดสำหรับคุณ', 1, 1, NOW()
FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM `tb_guide` WHERE `page_key` = 'font_size');


