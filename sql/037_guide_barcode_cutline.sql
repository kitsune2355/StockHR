SET NAMES utf8;

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ฉลากที่เห็นตรงนี้คือฉลากจริงที่จะออกมาบนกระดาษ ขนาดเท่าของจริงทุกมิลลิเมตร เส้นประรอบดวงคือรอยตัด ใช้ดูว่าเนื้อหาชิดขอบเกินไปหรือเปล่า และจะถูกพิมพ์ลงกระดาษไปด้วยเพื่อให้ตัดตามได้ตรง ถ้าพิมพ์ลงแผ่นสติกเกอร์ที่ปรุรอยตัดมาแล้ว ให้เอาติ๊ก "พิมพ์เส้นตัดประ" ในแผงขวาออก ไม่งั้นเส้นจะไปโผล่บนดวงสติกเกอร์จริง แผ่นตัวอย่างอยู่บนจอพร้อมกับแผงตั้งค่าเสมอ ปรับอะไรก็เห็นผลตรงนี้ทันที ถ้าชื่อสินค้ายาวเกินดวง ระบบจะตัดเหลือสองบรรทัดแล้วเติมจุดไข่ปลาให้ ส่วนรหัสกับตัวบาร์โค้ดหรือ QR จะไม่ถูกย่อไม่ว่ากรณีใด ตอนนี้คู่มือเลือกสินค้าตัวอย่างให้ดูสี่รายการ พอปิดคู่มือจะกลับไปเป็นรายการที่คุณเลือกไว้เดิม'
WHERE g.`page_key` = 'product_barcode' AND s.`target_selector` = '#bcSheet';
