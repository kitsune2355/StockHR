-- ============================================================
--  019_sign_link.sql
--  ลิงก์เซ็นรับของแบบไม่ต้องล็อกอิน
--
--  ที่มา: เมลแจ้ง "ของพร้อมให้รับแล้ว" ส่งไปหาผู้ขอเบิก พร้อมปุ่มที่ชี้ไป
--  main.php?page=issue_history&doc=... ซึ่งเป็นหน้าที่อยู่หลังหน้าล็อกอิน
--  แต่ผู้ขอเบิกส่วนใหญ่ไม่มีบัญชีในระบบ หรือมีแต่ไม่มีสิทธิ์เข้าหน้านั้น
--  กดปุ่มในเมลแล้วจึงไปโผล่หน้าล็อกอินหรือหน้า "ไม่มีสิทธิ์เข้าถึง"
--  งานเลยค้างอยู่ตรงนั้น คลังต้องโทรตามให้มาเซ็นเอง
--
--  ---------------------------------------------------------------
--  ทำไมเป็นคอลัมน์ใน tb_doc_header ไม่ใช่ตารางใหม่
--  ---------------------------------------------------------------
--  กุญแจหนึ่งดอกผูกกับเอกสารหนึ่งใบเสมอ เป็นความสัมพันธ์ 1:1 ไม่มีวันเป็น 1:N
--  ถ้าแยกตารางจะต้อง JOIN ทุกครั้งที่อ่านใบจ่าย เพื่อได้ข้อมูลสองคอลัมน์
--  และเปิดช่องให้มีแถวกำพร้าค้างไว้ตอนลบเอกสาร
--
--  ---------------------------------------------------------------
--  ทำไมต้องมีวันหมดอายุ
--  ---------------------------------------------------------------
--  ลิงก์นี้เปิดได้โดยไม่ต้องล็อกอิน ใครถือลิงก์ก็เซ็นแทนได้
--  เมลถูกส่งต่อ ถูกวางในแชตกลุ่ม หรือค้างในกล่องจดหมายเก่าได้ทั้งนั้น
--  กุญแจที่ไม่มีวันหมดอายุแปลว่าลายเซ็นของใบนั้นถูกปลอมได้ตลอดกาล
--
--  ตั้งไว้ 7 วันนับจากวันที่ส่งเมล ซึ่งยาวพอสำหรับคนที่ลาหยุดทั้งสัปดาห์
--  ถ้าเลยกำหนดแล้ว ผู้ดูแลกดส่งเมลซ้ำหรือคัดลอกลิงก์ใหม่ได้ ระบบจะออกกุญแจใหม่ให้
--
--  ---------------------------------------------------------------
--  กุญแจเก่าถูกยกเลิกทันทีที่ออกดอกใหม่
--  ---------------------------------------------------------------
--  เพราะเก็บไว้คอลัมน์เดียว การเขียนทับคือการเพิกถอนไปในตัว
--  เป็นผลข้างเคียงที่ตั้งใจ: กดส่งเมลซ้ำ = ลิงก์ในเมลฉบับเก่าใช้ไม่ได้อีก
--
--  ---------------------------------------------------------------
--  ของเดิมไม่กระทบ
--  ---------------------------------------------------------------
--  ทั้งสองคอลัมน์เป็น NULL ได้ ใบจ่ายที่มีอยู่แล้วจึงยังไม่มีกุญแจ
--  และยังเซ็นผ่านหน้าเว็บแบบเดิมได้เหมือนเดิมทุกอย่าง
--  กุญแจจะถูกออกให้ตอนส่งเมลหรือตอนกดคัดลอกลิงก์ครั้งแรกเท่านั้น
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hl < sql/019_sign_link.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/019_sign_link_rollback.sql
--
--  รองรับ MySQL 5.0.51b
-- ============================================================

ALTER TABLE `tb_doc_header`
    ADD COLUMN `sign_token` CHAR(40) NULL DEFAULT NULL COMMENT 'กุญแจลิงก์เซ็นรับของ ว่าง = ยังไม่เคยออกลิงก์' AFTER `receiver_sign`,
    ADD COLUMN `sign_token_exp` DATETIME NULL DEFAULT NULL COMMENT 'ลิงก์หมดอายุเมื่อไหร่ เลยแล้วต้องออกใหม่' AFTER `sign_token`;

-- ค้นด้วยกุญแจอย่างเดียวทุกครั้งที่เปิดหน้าเซ็น จึงต้องมี index
-- ใช้ UNIQUE เพื่อกันกุญแจซ้ำในระดับฐานข้อมูล ไม่ใช่แค่หวังว่าตัวสุ่มจะไม่ชน
-- MySQL ยอมให้มีหลายแถวที่เป็น NULL ในคอลัมน์ UNIQUE ได้
-- ใบจ่ายเก่าที่ยังไม่มีกุญแจจึงอยู่ร่วมกันได้ทั้งหมด
ALTER TABLE `tb_doc_header`
    ADD UNIQUE INDEX `uq_doc_sign_token` (`sign_token`);
