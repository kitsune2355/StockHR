-- ============================================================
--  053_guide_report_cost_v2.sql
--  เพิ่มคู่มือของตารางใหม่ในหน้า "ค่าใช้จ่ายรายเดือน"
--
--  หน้านี้เพิ่งได้ตารางใหม่มาเป็นตารางแรกของหน้า
--  "สรุปค่าใช้จ่ายการสั่งซื้อ - เบิกใช้ แยกตามหมวดหมู่และหน่วยงาน"
--  คู่มือชุดเดิม 9 ขั้นยังไม่พูดถึงเลย ทั้งที่เป็นตารางที่ผู้ใช้เห็นก่อนใคร
--
--  ---------------------------------------------------------------
--  ทำไมต้องใช้ถึงสองขั้น
--  ---------------------------------------------------------------
--  ตารางนี้มีกับดักที่อ่านผิดได้ง่ายมาก และเป็นคนละเรื่องกับวิธีอ่าน
--  จึงแยกเป็นสองขั้น ไม่ยัดรวมกันจนคนอ่านข้ามความสำคัญไป
--
--    ขั้นที่ 3  ตารางนี้คืออะไร อ่านยังไง
--    ขั้นที่ 4  กับดัก: คอลัมน์ซื้อกับคอลัมน์หน่วยงานอยู่คนละฝั่ง
--
--  กับดักที่ว่าคือ "ยอดรวมสั่งซื้อทั้งหมด" เป็นเงินซื้อเข้าคลัง
--  ส่วนคอลัมน์หน่วยงานเป็นมูลค่าของที่เบิกออกไป ตัวเลขในแถวเดียวกัน
--  จึงไม่ต้องบวกกันลงตัว ข้อมูลจริงเดือน ส.ค. 2569 ต่างกันสามเท่า
--      วัสดุสิ้นเปลือง  ซื้อเข้า 131,872.10  แต่เบิกออกแค่ 40,332.60
--  ถ้าไม่บอกไว้ จะมีคนคิดว่ารายงานคำนวณผิดแล้วตามหาส่วนต่างที่ไม่มีอยู่จริง
--
--  ---------------------------------------------------------------
--  ลำดับใหม่ 11 ขั้น
--  ---------------------------------------------------------------
--    1  เลือกเดือน                     (เดิม)
--    2  สามตัวเลขที่ต้องแยกให้ออก        (เดิม)
--    3  ตารางเดียวตอบสองคำถาม           (ใหม่)
--    4  ยอดซื้อกับยอดเบิกอยู่คนละฝั่ง      (ใหม่)
--    5  แยกตามบริษัท                   (เดิม 3)
--    6  แยกตามหน่วยงานที่เบิก            (เดิม 4)
--    7  แยกตามหมวดหมู่สินค้า             (เดิม 5)
--    8  ของที่รับเข้ามาในเดือนนี้          (เดิม 6)
--    9  ลงลึกถึงรายตัวสินค้า             (เดิม 7)
--   10  ส่งออก Excel                   (เดิม 8 แก้ข้อความ)
--   11  พิมพ์ส่งบัญชี                    (เดิม 9)
--
--  ---------------------------------------------------------------
--  selector ที่ชี้
--  ---------------------------------------------------------------
--  #tblCatDept ตั้งไว้ใน pages/report_cost.php บรรทัด 111
--  อยู่ใน #rcBody ซึ่งซ่อนอยู่จนกว่าข้อมูลจะมา เหมือนขั้นเดิมทุกขั้น
--  จึงต้องเปิดคู่มือหลังหน้าโหลดเสร็จ ซึ่งเป็นพฤติกรรมปกติอยู่แล้ว
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/053_guide_report_cost_v2.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/053_guide_report_cost_v2_rollback.sql
-- ============================================================

SET NAMES utf8;

-- ------------------------------------------------------------
--  0) กันรันซ้ำ
-- ------------------------------------------------------------
--  ลำพัง NOT EXISTS ที่ INSERT กันไม่พอ เพราะบล็อกเลื่อนลำดับข้างล่าง
--  ทำงานก่อนเสมอ พอรันรอบสองมันจะเลื่อนขั้นใหม่ 3,4 ออกไปเป็น 5,6
--  แล้วเว้นช่อง 3,4 ว่างไว้ให้ INSERT ลงซ้ำได้อีก ผลคือได้ 13 ขั้น
--  ลำดับซ้ำกันเป็นคู่ ๆ (เจอจากการทดลองรันสองรอบใน transaction)
--
--  MySQL 5.0 ห้าม subquery ตารางเดียวกับที่กำลัง UPDATE อยู่ (error 1093)
--  จึงต้องอ่านสถานะเก็บใส่ตัวแปรไว้ก่อน แล้วให้ทุกคำสั่งเช็คตัวแปรแทน
SELECT COUNT(*) INTO @rc_has_new
FROM `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'report_cost' AND s.`target_selector` = '#tblCatDept';


-- ------------------------------------------------------------
--  1) เลื่อนลำดับของขั้นเดิมออกไปก่อน เว้นที่สองช่องให้ขั้นใหม่
--     ทำจากท้ายมาหน้า ไม่งั้นจะไปทับลำดับที่ยังไม่ได้ย้าย
-- ------------------------------------------------------------
UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 11 WHERE g.`page_key` = 'report_cost' AND s.`step_order` = 9 AND @rc_has_new = 0;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 10 WHERE g.`page_key` = 'report_cost' AND s.`step_order` = 8 AND @rc_has_new = 0;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 9  WHERE g.`page_key` = 'report_cost' AND s.`step_order` = 7 AND @rc_has_new = 0;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 8  WHERE g.`page_key` = 'report_cost' AND s.`step_order` = 6 AND @rc_has_new = 0;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 7  WHERE g.`page_key` = 'report_cost' AND s.`step_order` = 5 AND @rc_has_new = 0;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 6  WHERE g.`page_key` = 'report_cost' AND s.`step_order` = 4 AND @rc_has_new = 0;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 5  WHERE g.`page_key` = 'report_cost' AND s.`step_order` = 3 AND @rc_has_new = 0;


-- ------------------------------------------------------------
--  2) ขั้นใหม่
--     WHERE NOT EXISTS กันรันซ้ำแล้วได้ขั้นซ้อนกันสองอัน
-- ------------------------------------------------------------
INSERT INTO `tb_guide_step`
  (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT g.`guide_id`, 3, '#tblCatDept', 'ตารางเดียวตอบสองคำถาม',
       'ตารางแรกของหน้าเอาสองมุมที่บัญชีถามคู่กันเสมอมาไขว้กันไว้ในใบเดียว หนึ่งแถวคือหมวดหมู่หลักหนึ่งหมวด คอลัมน์กลางคือหน่วยงานที่เบิกของหมวดนั้นไป อ่านตามแนวนอนได้ว่าหมวดนี้ใครเบิกไปคนละเท่าไร อ่านตามแนวตั้งได้ว่าหน่วยงานนี้ใช้ของหมวดไหนบ้าง เดิมต้องเปิดตารางที่ 3 กับที่ 4 แล้วไล่จับคู่เอง คอลัมน์หน่วยงานกางเฉพาะหน่วยที่เบิกจริงในเดือนนั้น เดือนที่ไม่ได้เบิกก็ไม่มีคอลัมน์ ไม่ได้หายไปจากระบบ ชื่อหน่วยงานซ้ำกันข้ามบริษัทได้ จึงมีชื่อบริษัทตัวเล็กกำกับไว้ใต้ชื่อทุกคอลัมน์ ตารางกว้างกว่าจอ ให้เลื่อนซ้ายขวาในกรอบของตัวเอง สองคอลัมน์ซ้ายมือถูกตรึงไว้ เลื่อนไปดูหน่วยงานที่อยู่ขวาสุดแค่ไหน ก็ยังเห็นว่ากำลังดูหมวดไหนและหมวดนั้นซื้อเข้ามาเท่าไร',
       'top', 'center', NOW()
FROM `tb_guide` g
WHERE g.`page_key` = 'report_cost'
  AND @rc_has_new = 0
  AND NOT EXISTS (SELECT 1 FROM `tb_guide_step` x
                  WHERE x.`guide_id` = g.`guide_id` AND x.`step_order` = 3);

INSERT INTO `tb_guide_step`
  (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT g.`guide_id`, 4, '#tblCatDept', 'ยอดซื้อกับยอดเบิกอยู่คนละฝั่ง',
       'จุดเดียวที่ต้องระวังในตารางนี้ คอลัมน์ "ยอดรวมสั่งซื้อทั้งหมด" คือเงินที่จ่ายซื้อของหมวดนั้นเข้าคลัง ส่วนคอลัมน์หน่วยงานกับ "รวมเบิกทั้งหมด" คือมูลค่าของที่เบิกออกไปใช้ สองฝั่งนี้ไม่เกี่ยวกัน ตัวเลขในแถวเดียวกันจึงไม่ต้องบวกกันลงตัว และไม่ได้แปลว่ารายงานคำนวณผิด ของที่ซื้อเดือนนี้อาจยังไม่มีใครเบิกจนถึงเดือนหน้า ที่บวกกันลงตัวจริงมีสองอย่างเท่านั้น คือคอลัมน์หน่วยงานทั้งแถวรวมกันได้เท่ากับ "รวมเบิกทั้งหมด" ของแถวนั้น และแถวล่างสุดคือยอดรวมของแต่ละหน่วยงานจากทุกหมวดรวมกัน',
       'top', 'center', NOW()
FROM `tb_guide` g
WHERE g.`page_key` = 'report_cost'
  AND @rc_has_new = 0
  AND NOT EXISTS (SELECT 1 FROM `tb_guide_step` x
                  WHERE x.`guide_id` = g.`guide_id` AND x.`step_order` = 4);


-- ------------------------------------------------------------
--  3) แก้ข้อความขั้นส่งออก ให้บอกว่ามีชีตใหม่เพิ่มมาแล้ว
--     ชีตแรกในไฟล์คือตารางใหม่ ไม่ใช่ตารางบริษัทเหมือนเดิม
--     คนที่เคยเปิดไฟล์นี้อยู่ประจำจะได้ไม่งงว่าเปิดผิดไฟล์
-- ------------------------------------------------------------
UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ได้ทุกตารางในหน้านี้เป็นไฟล์เดียว แยกเป็นชีตละตาราง ชีตแรกคือตารางหมวดหมู่ไขว้หน่วยงาน เอาไปทำ pivot หรือรวมกับข้อมูลอื่นต่อได้ ตัวเลขในไฟล์เป็นตัวเลขจริง ไม่ใช่ข้อความ จึงคำนวณต่อได้ทันที'
WHERE g.`page_key` = 'report_cost' AND s.`step_order` = 10;


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์ — ต้องได้ 11 ขั้น เรียง 1 ถึง 11 ไม่ซ้ำไม่ขาด
-- ------------------------------------------------------------
SELECT s.`step_order`, s.`target_selector`, s.`title`
FROM `tb_guide_step` s
JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'report_cost'
ORDER BY s.`step_order`;
