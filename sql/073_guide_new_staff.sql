SET NAMES utf8;

DELETE FROM `tb_guide` WHERE `page_key` IN ('new_staff_request', 'new_staff_list', 'new_staff_kit');

/* รันซ้ำ: ถ้าขั้นไทล์มีอยู่แล้ว (ขั้น 3) ให้เลื่อนขั้นที่ตามมากลับขึ้นก่อนลบ
   ไม่งั้นข้อ 4 ด้านล่างจะเลื่อนลงซ้ำอีกรอบจนเลขขั้นโดดเป็นช่องว่าง
   ตารางนับต้องอยู่ใน derived table — MySQL ห้าม UPDATE ตารางที่ subquery อ่านอยู่ตรง ๆ (1093) */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
INNER JOIN (
    SELECT COUNT(*) AS `c`
    FROM `tb_guide_step` s2
    INNER JOIN `tb_guide` g2 ON g2.`guide_id` = s2.`guide_id`
    WHERE g2.`page_key` = 'dashboard' AND s2.`target_selector` = '#bnNewStaff'
) x
SET s.`step_order` = s.`step_order` - 1
WHERE g.`page_key` = 'dashboard' AND s.`step_order` >= 4 AND x.`c` > 0;

DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'dashboard' AND s.`target_selector` = '#bnNewStaff';


