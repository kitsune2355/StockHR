-- ============================================================
--  015_form_code_signature.sql
--  รหัสแบบฟอร์มประจำบริษัท + ลายเซ็นผู้รับของ
--
--  สองเรื่องในไฟล์เดียวเพราะทั้งคู่เป็นข้อมูลที่ต้องไปโผล่บนเอกสารที่พิมพ์
--
--  ---------------------------------------------------------------
--  1) tb_company.form_code — รหัสแบบฟอร์มมุมขวาล่างของกระดาษ
--  ---------------------------------------------------------------
--  เอกสารควบคุมของแต่ละบริษัทมีรหัสและรอบแก้ไขของตัวเอง เช่น
--      บริษัท คลีนนิ่ง โซลูชั่น จำกัด      -> FM-AD-01 : Rev 00 : 01/10/64
--      บริษัท โปรแอ็คทีฟ แมเนจเม้นท์ จำกัด -> FM-AD-01 : Rev 01 : 18/10/64
--
--  เก็บเป็นข้อความก้อนเดียว ไม่แยกเป็น 3 คอลัมน์ (รหัส/รอบ/วันที่)
--  เพราะระบบไม่เคยต้องค้นหรือเรียงด้วยค่าพวกนี้เลย มีหน้าที่เดียวคือพิมพ์ออกมาตามตัว
--  แยกคอลัมน์จะกลายเป็นสามช่องที่ต้องกรอกให้ครบทุกครั้งโดยไม่ได้อะไรกลับมา
--
--  ---------------------------------------------------------------
--  2) tb_doc_header.receiver_sign — ลายเซ็นผู้รับของ
--  ---------------------------------------------------------------
--  เดิมการเซ็นรับเก็บแค่ "ชื่อที่พิมพ์" ซึ่งใครพิมพ์ก็ได้
--  เก็บลายเซ็นที่วาดจริงเพิ่ม เพื่อให้ใบจ่ายที่พิมพ์ออกมาใช้เป็นหลักฐานได้
--
--  เก็บเป็น data URL (base64 ของ PNG) ใน MEDIUMTEXT ไม่ใช่ไฟล์แยก
--  ต่างจากโลโก้บริษัทที่เก็บเป็นไฟล์ เพราะเหตุผลคนละเรื่องกัน:
--    โลโก้    10 รูป ใช้ซ้ำทุกหน้า ทุกคนเห็น — ควรให้เบราว์เซอร์แคชไฟล์
--    ลายเซ็น  1 รูปต่อ 1 เอกสาร เปิดดูไม่กี่ครั้งตลอดอายุ และต้องถูกลบ
--             พร้อมเอกสารถ้าวันหนึ่งต้องลบ การผูกติดกับแถวจึงถูกกว่า
--             การมีไฟล์นับหมื่นไฟล์ที่ไม่มีใครรู้ว่าอันไหนกำพร้าแล้ว
--
--  MEDIUMTEXT รับได้ 16 MB ลายเซ็นที่วาดบนผืน 600x200 px หนักราว 10-30 KB
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hr < sql/015_form_code_signature.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/015_form_code_signature_rollback.sql
-- ============================================================

SET NAMES utf8;

ALTER TABLE `tb_company`
  ADD COLUMN `form_code` VARCHAR(120) NOT NULL DEFAULT ''
  COMMENT 'รหัสแบบฟอร์มมุมขวาล่างของเอกสาร เช่น FM-AD-01 : Rev 00 : 01/10/64'
  AFTER `logo_file`;

ALTER TABLE `tb_doc_header`
  ADD COLUMN `receiver_sign` MEDIUMTEXT NULL DEFAULT NULL
  COMMENT 'ลายเซ็นผู้รับของ เก็บเป็น data URL ของ PNG'
  AFTER `receiver_name`;


-- ------------------------------------------------------------
--  เติมรหัสแบบฟอร์มของสองบริษัทที่แจ้งมา
--  อ้างด้วยชื่อบริษัท ไม่ใช่ company_id เพราะ id ต่างกันได้ในแต่ละเครื่อง
--  ใช้ LIKE เพราะชื่อในฐานข้อมูลบางแถวมีช่องว่างซ้อนกันหลายตัว
-- ------------------------------------------------------------
UPDATE `tb_company` SET `form_code` = 'FM-AD-01 : Rev 00 : 01/10/64'
WHERE `company_name` LIKE '%คลีนนิ่ง%โซลูชั่น%';

UPDATE `tb_company` SET `form_code` = 'FM-AD-01 : Rev 01 : 18/10/64'
WHERE `company_name` LIKE '%โปรแอ็คทีฟ%';


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT `company_id`, `company_name`,
       IF(`form_code` = '', '(ยังไม่ได้ตั้ง)', `form_code`) AS `รหัสแบบฟอร์ม`
FROM `tb_company`
ORDER BY `company_id`;

SHOW COLUMNS FROM `tb_doc_header` LIKE 'receiver_sign';
