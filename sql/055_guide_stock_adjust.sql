-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT g.`page_key`, g.`title`, COUNT(s.`step_id`) AS `จำนวนขั้นตอน`
FROM `tb_guide` g
LEFT JOIN `tb_guide_step` s ON s.`guide_id` = g.`guide_id`
WHERE g.`page_key` IN ('adjust_new', 'adjust_history')
GROUP BY g.`guide_id`, g.`page_key`, g.`title`;

