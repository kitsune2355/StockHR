-- ============================================================
--  055_guide_stock_adjust.sql
--  คู่มือการใช้งานของหน้า "บันทึกปรับยอด" และ "ประวัติการปรับยอด"
--
--  หน้าปรับยอดสินค้าเพิ่มเข้ามาใหม่ (ดู includes/menu.php key = stock_adjust)
--  ทุกหน้าในระบบมีคู่มือของตัวเอง หน้าใหม่จึงต้องมีด้วย ไม่งั้นปุ่มเครื่องหมาย
--  คำถามบนแถบบนจะหายไปเฉพาะสองหน้านี้ ดูเหมือนระบบทำไม่สม่ำเสมอ
--
--  ---------------------------------------------------------------
--  ไม่มีการแก้โครงสร้างฐานข้อมูลสำหรับฟีเจอร์นี้
--  ---------------------------------------------------------------
--    - การปรับยอดไม่ผ่านเอกสาร (tb_doc_header) เขียนตรงลง tb_stock_movement
--    - move_type = 'adjust' มีอยู่ใน ENUM ของ tb_stock_movement ตั้งแต่ไฟล์ 008 แล้ว
--    - ไม่มีตารางใหม่ ไม่มีคอลัมน์ใหม่
--    - สิทธิ์เมนู (adjust_new / adjust_history) ใช้ค่าตั้งต้นในโค้ด
--      ($ROLE_ADMIN ที่ includes/menu.php) เมนูที่ไม่มีแถวใน tb_menu_permission
--      ใช้ค่าโค้ดอยู่แล้ว จึงไม่ต้อง INSERT อะไรล่วงหน้า
--  ไฟล์นี้จึงเพิ่มแค่ "เนื้อหาคู่มือ" อย่างเดียว
--
--  ---------------------------------------------------------------
--  เนื้อหาเน้นสามเรื่องที่พลาดได้ง่ายที่สุด
--  ---------------------------------------------------------------
--  1. กรอก "จำนวนที่นับได้จริง" ไม่ใช่ผลต่าง — ระบบคิดผลต่างให้เอง
--  2. บันทึกแล้วยอดคงเหลือเปลี่ยนทันที ไม่มีขั้นอนุมัติ และยกเลิกทั้งใบไม่ได้
--     ปรับผิดต้องปรับกลับเป็นอีกรายการ
--  3. บรรทัดที่ยอดตรงกับระบบอยู่แล้ว ระบบข้ามให้เอง ไม่นับเป็นการปรับ
--
--  ---------------------------------------------------------------
--  selector ที่ชี้ — ใช้ id ที่มีจริงและ "มองเห็นได้" บนหน้า
--    บันทึกปรับยอด : #docDate #docNote #adjPickBox #btnSave
--    ประวัติ       : #fpToggle #btnReload (ช่องวันที่/ค้นหาอยู่ในแถบขวาที่จอแคบซ่อน)
--
--  ชี้ที่ #adjPickBox (กรอบครอบช่องเลือกสินค้า) ไม่ใช่ #prodPick ตรง ๆ
--  เพราะ select-search.js ซ่อน <select> จริงด้วย opacity:0 ซึ่ง app-guide.js
--  ถือว่ามองไม่เห็นแล้วข้ามขั้นนั้นทิ้ง
--  ขั้นที่ target ไม่เจอหรือถูกซ่อน app-guide.js ข้ามให้เงียบ ๆ อยู่แล้ว
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/055_guide_stock_adjust.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/055_guide_stock_adjust_rollback.sql
-- ============================================================

