--  สร้างยอดคงเหลือตั้งต้น (0) ให้สินค้าทุกตัวหลังนำเข้าทะเบียนใหม่
--
--  backend/stock.php สร้างแถวให้เองอยู่แล้วเมื่อมีการเคลื่อนไหวครั้งแรก
--  แต่หน้ารายการสินค้า/แดชบอร์ดอ่านยอดคงเหลือแบบตรง ๆ การมีแถวครบตั้งแต่
--  ต้นทำให้ตัวเลขขึ้น 0 แทนที่จะว่าง และตรงกับสภาพเดิมของระบบ (1 สินค้า 1 แถว)
--
--  รันหลัง 006 เสมอ ไม่งั้นจะได้แถวไม่ครบ
--  รันซ้ำได้ INSERT IGNORE จะข้ามตัวที่มีอยู่แล้ว ไม่ทับยอดที่เดินไปแล้ว
-- ============================================================

SET NAMES utf8;

INSERT IGNORE INTO `tb_stock_balance` (`product_id`, `qty`, `created_at`)
SELECT `product_id`, 0, NOW() FROM `tb_product`;
-- created_by ปล่อยว่าง เพราะมี foreign key ไป tb_user.username ใส่ชื่อสมมติไม่ได้

SELECT COUNT(*) AS สินค้าทั้งหมด FROM `tb_product`;
SELECT COUNT(*) AS แถวยอดคงเหลือ FROM `tb_stock_balance`;
SELECT COUNT(*) AS ยอดที่ไม่เป็นศูนย์ FROM `tb_stock_balance` WHERE `qty` <> 0;
