-- ============================================================
--  027_guide_barcode_scan.sql
--  คู่มือของช่องยิงบาร์โค้ดในฟอร์มเอกสารทั้งสามหน้า
--
--  ---------------------------------------------------------------
--  ทำไมต้องอธิบาย ทั้งที่มันก็แค่ช่องหนึ่งช่อง
--  ---------------------------------------------------------------
--  สองเรื่องที่ผู้ใช้ไม่มีทางเดาได้เอง และเป็นเรื่องที่ทำให้เลิกใช้ถ้าไม่รู้:
--
--    1) ยิงได้ทั้งที่เปิดภาษาไทยค้างไว้
--       คนที่เคยเจอเครื่องอ่านยิงออกมาเป็นภาษาไทยมั่ว จะเข้าใจว่าต้องสลับเป็น
--       อังกฤษก่อนทุกครั้ง ซึ่งน่ารำคาญพอที่จะทำให้เลิกใช้เครื่องอ่านไปเลย
--       ระบบนี้อ่านจากตำแหน่งปุ่มบนแป้น จึงไม่ต้องสลับภาษา
--
--    2) ยิงซ้ำตัวเดิม = บวกจำนวน ไม่ใช่เพิ่มบรรทัดซ้ำ และไม่ใช่ยกเลิก
--       เป็นพฤติกรรมที่ตรงกับสิ่งที่มือทำอยู่ (หยิบทีละชิ้น) แต่เดาไม่ได้จากหน้าตา
--
--  ---------------------------------------------------------------
--  หน้าจ่ายออกทำงานคนละแบบ จึงอธิบายแยก
--  ---------------------------------------------------------------
--  อีกสองหน้ายิงเพื่อ "เพิ่มของ" แต่หน้าจ่ายออกเพิ่มบรรทัดเองไม่ได้
--  รายการต้องมาจากใบเบิกเท่านั้น การยิงจึงเป็นการ "นับของที่หยิบใส่กล่อง"
--  และเป็นการตรวจไปในตัวว่าหยิบผิดตัวหรือเปล่า ซึ่งเป็นประโยชน์หลักของหน้านั้น
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/027_guide_barcode_scan.sql
--
--  ไฟล์นี้ลบขั้นของตัวเองก่อนใส่ใหม่ทุกครั้ง รันซ้ำได้ปลอดภัย
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/027_guide_barcode_scan_rollback.sql
-- ============================================================

SET NAMES utf8;

-- ลบขั้นเดิมของช่องยิง (ถ้าเคยรันมาแล้ว) แล้วดันลำดับที่เหลือให้ชิดกัน
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` IN ('receive_new', 'issue_new', 'request_new')
  AND s.`target_selector` = '#scanInput';


-- ============================================================
--  บันทึกรับเข้า — แทรกเป็นขั้นที่ 3 ก่อนขั้นที่อธิบายตาราง
-- ============================================================

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'receive_new' AND s.`step_order` >= 3;

INSERT INTO `tb_guide_step` (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 3, '#scanInput', 'ยิงบาร์โค้ดแทนการค้นหา',
 'ถ้าของที่รับเข้ามามีฉลากบาร์โค้ดแปะอยู่ ให้คลิกที่ช่องนี้แล้วยิงได้เลย ระบบจะเพิ่มบรรทัดพร้อมสินค้าและราคาให้ทันที ยิงซ้ำสินค้าตัวเดิมจะบวกจำนวนขึ้นทีละหนึ่ง ไม่ได้สร้างบรรทัดซ้ำ จึงเดินยิงของทีละชิ้นได้เลยโดยไม่ต้องนับก่อน ยิงถูกจะได้ยินเสียงสูงสั้น ยิงไม่เจอจะได้เสียงต่ำยาว ฟังได้โดยไม่ต้องละสายตาจากของ ฉลากบาร์โค้ดพิมพ์ได้จากเมนู ข้อมูลสินค้า > บาร์โค้ดสินค้า',
 'bottom', 'start', NOW() FROM `tb_guide` WHERE `page_key`='receive_new';


-- ============================================================
--  ทำรายการเบิก — แทรกเป็นขั้นที่ 3 ก่อนขั้นค้นหาสินค้า
-- ============================================================

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'request_new' AND s.`step_order` >= 3;

INSERT INTO `tb_guide_step` (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 3, '#scanInput', 'ยิงบาร์โค้ดถ้ามีของอยู่ตรงหน้า',
 'ถ้ากำลังยืนอยู่หน้าชั้นวางและเห็นของจริง ยิงบาร์โค้ดที่ฉลากได้เลย เร็วกว่าไล่หาชื่อในรายการ ยิงแล้วสินค้าจะไปอยู่ฝั่งขวาทันที ยิงซ้ำตัวเดิมจะบวกจำนวนขึ้นทีละหนึ่ง ถ้ายิงแล้วขึ้นว่าไม่พบ ให้ดูก่อนว่าเลือกหน่วยงานถูกหรือยัง เพราะแต่ละหน่วยงานเบิกสินค้าได้ไม่เหมือนกัน สินค้าที่หน่วยงานนี้ไม่มีสิทธิ์เบิกจะยิงไม่ติด',
 'bottom', 'start', NOW() FROM `tb_guide` WHERE `page_key`='request_new';


-- ============================================================
--  บันทึกจ่ายออก — แทรกเป็นขั้นที่ 3 ก่อนขั้นที่อธิบายตาราง
-- ============================================================

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'issue_new' AND s.`step_order` >= 3;

INSERT INTO `tb_guide_step` (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 3, '#scanInput', 'ยิงเพื่อนับของที่หยิบ',
 'หน้านี้เพิ่มบรรทัดเองไม่ได้ รายการทั้งหมดมาจากใบเบิกที่เลือกไว้ การยิงตรงนี้จึงไม่ใช่การเพิ่มสินค้า แต่เป็นการนับของที่หยิบใส่กล่องไปแล้ว หยิบของหนึ่งชิ้นก็ยิงหนึ่งครั้ง ระบบจะบวกจำนวนในบรรทัดของสินค้านั้นให้ทีละหนึ่ง แล้วขึ้นข้อความบอกความคืบหน้า เช่น "หยิบแล้ว 2 จาก 5 ม้วน" หมายถึงหยิบไปแล้ว 2 ม้วน จากที่ใบเบิกขอมา 5 ม้วน เมื่อหยิบครบตามจำนวนที่ขอ ระบบจะเตือนว่าไม่ต้องหยิบเพิ่มแล้ว ประโยชน์ที่สำคัญที่สุดคือการจับว่าหยิบผิดตัว ถ้ายิงสินค้าที่ไม่มีอยู่ในใบเบิกใบนี้ ระบบจะเตือนพร้อมเสียงต่ำทันที ตอนที่ของยังอยู่ในมือ ไม่ใช่ตอนที่ส่งไปถึงหน่วยงานแล้ว',
 'bottom', 'start', NOW() FROM `tb_guide` WHERE `page_key`='issue_new';
