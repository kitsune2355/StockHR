SET NAMES utf8;

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ในการใช้งานจริงคอลัมน์นี้โชว์เฉพาะปุ่มที่ใช้บ่อย (ดูรายละเอียด / พิมพ์ / อนุมัติ / ไม่อนุมัติ) ปุ่มที่เหลือ — แก้ไขใบเบิก, ส่งกลับแก้ไข, คัดลอก/เปิดลิงก์อนุมัติ, ยกเลิก, ส่งอีเมลซ้ำ — รวมอยู่ในเมนู "จุดสามจุดแนวตั้ง" ท้ายแถว กดที่ไอคอนนั้นแล้วเลือกคำสั่งได้เลย แถวตัวอย่างด้านบนนี้กางปุ่มออกให้เห็นครบทุกอัน เพื่ออธิบายทีละอันในขั้นถัดไป'
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.cell-rowacts';
