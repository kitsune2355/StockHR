--  064_guide_request_actions_menu.sql
--  คู่มือหน้ารายการใบเบิก: เพิ่มขั้นอธิบาย "คอลัมน์จัดการ + เมนู ⋮"
--
--  ที่มา: คอลัมน์จัดการมีปุ่มได้ถึงสิบอันจนล้น จึงยุบเหลือเฉพาะปุ่มหลัก
--  (ดู/พิมพ์/อนุมัติ/ไม่อนุมัติ) ที่เหลือย้ายเข้าเมนูจุดสามจุดแนวตั้งท้ายแถว
--  (ดู rowActionHtml/openRowMenu ใน assets/js/doc-list.js)
--
--  แถวสาธิตของคู่มือยังกางปุ่มออกครบทุกอัน (ไม่ยุบ) เพื่อให้ชี้ทีละอันได้
--  ขั้นใหม่นี้บอกผู้ใช้ล่วงหน้าว่าในแถวจริงปุ่มที่เหลืออยู่ในเมนู ⋮
--
--  ---------------------------------------------------------------
--  เลขลำดับขั้น
--  ---------------------------------------------------------------
--  แทรกเป็นขั้นที่ 2 (ต่อจากภาพรวมสถานะ ก่อนไล่ไอคอนทีละอัน)
--  แล้วเลื่อนขั้น 2 เป็นต้นไปลงหนึ่งช่อง
--
--  รันซ้ำจะเลื่อนซ้ำและได้ขั้นซ้ำ จึงลบขั้นเดิมของ selector นี้ทิ้งก่อนเสมอ
--
--  หมายเหตุ: 042/044/045/062/063 ชี้ขั้นตอนด้วย step_order ตามผังก่อนไฟล์นี้
--  ถ้าจะรันไฟล์เหล่านั้นซ้ำหลังรันไฟล์นี้ ต้องเลื่อนเลขตามด้วย
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/064_guide_request_actions_menu.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/064_guide_request_actions_menu_rollback.sql
-- ============================================================

SET NAMES utf8;

/* ---------- ลบขั้นเดิมก่อน กันรันซ้ำแล้วได้ขั้นซ้ำ ---------- */
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.cell-rowacts';

/* ---------- เปิดช่องที่ 2 ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'request_list'
  AND s.`step_order` >= 2;

/* ---------- ขั้นใหม่: คอลัมน์จัดการ + เมนู ⋮ ---------- */
INSERT INTO `tb_guide_step`
    (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 2, '.cell-rowacts', 'คอลัมน์จัดการ — ปุ่มหลักกับเมนู ⋮',
 'ในการใช้งานจริงคอลัมน์นี้โชว์เฉพาะปุ่มที่ใช้บ่อย (ดูรายละเอียด / พิมพ์ / อนุมัติ / ไม่อนุมัติ) ปุ่มที่เหลือ — แก้ไขใบเบิก, ส่งกลับแก้ไข, คัดลอก/เปิดลิงก์อนุมัติ, ยกเลิก, ส่งอีเมลซ้ำ — รวมอยู่ในเมนู "จุดสามจุดแนวตั้ง" ท้ายแถว กดที่ไอคอนนั้นแล้วเลือกคำสั่งได้เลย แถวตัวอย่างด้านบนนี้กางปุ่มออกให้เห็นครบทุกอัน เพื่ออธิบายทีละอันในขั้นถัดไป',
 'left', 'center', NOW()
FROM `tb_guide` WHERE `page_key` = 'request_list';


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT s.`step_order`, s.`target_selector`, s.`title`
FROM `tb_guide_step` s
JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'request_list'
ORDER BY s.`step_order`;
