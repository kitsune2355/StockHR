-- ============================================================
--  051_drop_avg_cost_columns.sql
--  ถอดคอลัมน์ต้นทุนถัวเฉลี่ยที่ไม่มีใครเขียนแล้วออกจากตาราง
--
--  ⚠ ไฟล์นี้ลบข้อมูลถาวร — รันเมื่อแน่ใจแล้วว่าจะไม่กลับไปใช้วิธีถัวเฉลี่ยอีก
--    ระบบทำงานได้ปกติทั้งที่ยังไม่รันไฟล์นี้ (โค้ดเลิกแตะคอลัมน์พวกนี้ไปแล้ว)
--
--  ---------------------------------------------------------------
--  คอลัมน์ที่ถูกถอด
--  ---------------------------------------------------------------
--  tb_stock_balance.avg_cost        ต้นทุนเฉลี่ยปัจจุบันของสินค้าแต่ละตัว
--  tb_stock_movement.avg_cost_after ค่าเฉลี่ยหลังรายการนั้น (ไว้ตรวจย้อน)
--
--  ทั้งคู่เป็นค่าที่คำนวณมาจากวิธีที่เลิกใช้แล้ว (ดู 050 และ backend/stock.php)
--  ปล่อยค้างไว้จะกลายเป็นตัวเลขที่ไม่มีใครอัปเดตแต่ยังอ่านได้
--  ซึ่งอันตรายกว่าเอาออกไปเลย เพราะวันหนึ่งจะมีคนหยิบไปใช้โดยไม่รู้
--
--  ที่ที่เคยอ่านค่าพวกนี้ ย้ายไปใช้ราคาซื้อล่าสุด (tb_product.unit_cost) หมดแล้ว
--    มูลค่าคงคลังหน้าภาพรวม   backend/dashboard.php
--    มูลค่าคงคลังในรายงานเงิน backend/report_cost.php
--    ราคาประมาณการบนใบเบิก    backend/document.php
--
--  รายงานทุกตัวไม่ได้อ่านคอลัมน์พวกนี้อยู่แล้ว (อ่านจาก total_cost ที่แช่แข็งไว้)
--  ลบทิ้งจึงไม่มีตัวเลขไหนขยับ
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hl < sql/051_drop_avg_cost_columns.sql
--
--  ย้อนกลับ (ได้คืนแค่โครงสร้าง ค่าเดิมหายถาวร):
--      mysql -u root -p1234 stock_hl < sql/051_drop_avg_cost_columns_rollback.sql
-- ============================================================

SET NAMES utf8;

ALTER TABLE `tb_stock_balance`  DROP COLUMN `avg_cost`;
ALTER TABLE `tb_stock_movement` DROP COLUMN `avg_cost_after`;


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์ — ต้องไม่เหลือคอลัมน์ค่าเฉลี่ยแล้ว
-- ------------------------------------------------------------
SELECT COUNT(*) AS `คอลัมน์ค่าเฉลี่ยที่เหลือ`
FROM `information_schema`.`COLUMNS`
WHERE `TABLE_SCHEMA` = DATABASE()
  AND `COLUMN_NAME` IN ('avg_cost', 'avg_cost_after');
