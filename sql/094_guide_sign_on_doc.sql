SET NAMES utf8;

UPDATE `tb_guide_step` s INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title` = 'ไอคอนปากกา — เซ็นรับของ',
    s.`description` = 'เปิดหน้าเอกสารใบจ่ายในแท็บใหม่ ตรวจรายการบนตัวเอกสารให้ครบ แล้วเซ็นด้วยนิ้วหรือเมาส์ในแผงเซ็นที่กางอยู่ใต้ช่องลงนาม (ปิดไปแล้วกดปุ่ม "เซ็นรับของ" บนแถบบน หรือไอคอนปากกาในช่องผู้รับของเพื่อเปิดใหม่) กดยืนยันแล้วลายเซ็นลงช่อง "ผู้รับของ" บนเอกสารทันที พิมพ์เก็บเป็นหลักฐานได้เลย ไอคอนนี้ขึ้นเฉพาะผู้ขอเบิกของใบนั้นและผู้ดูแลระบบ (เซ็นแทนได้) ผู้รับที่ไม่มีบัญชีในระบบใช้ลิงก์เซ็นรับแทน'
WHERE s.`target_selector` = '.rowact[data-row-act="ack"]';

SELECT g.`page_key`, s.`step_order`, s.`title` FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE s.`target_selector` = '.rowact[data-row-act="ack"]';
