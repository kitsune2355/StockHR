--  (แผงเซ็นซ่อนไว้ กางเมื่อกดปุ่ม "เซ็นรับของ" หรือไอคอนปากกาในช่องผู้รับของ)
--  ปรับข้อความคู่มือขั้นไอคอนปากกาให้ตรง
--
--      mysql -u root -p1234 --default-character-set=utf8 stock_hr < sql/094_guide_sign_on_doc.sql
