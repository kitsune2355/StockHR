-- ============================================================
--  044_guide_approve_link.sql
--  คู่มือหน้ารายการใบเบิก: เพิ่มขั้นของลิงก์อนุมัติ และแก้ขั้นที่ข้อมูลเก่าแล้ว
--
--  ที่มา: เพิ่มการอนุมัติผ่านลิงก์ในอีเมลโดยไม่ต้องล็อกอิน (ดู approve.php)
--  ซึ่งเปลี่ยนสองอย่างที่คู่มือเดิมยังไม่ได้บอก:
--
--    1. มีปุ่มใหม่ในคอลัมน์จัดการ — คัดลอกลิงก์อนุมัติ (เฉพาะผู้ดูแลระบบ)
--    2. ผู้อนุมัติไม่จำเป็นต้องเข้าระบบอีกต่อไป กดจากเมลได้เลย
--       ซึ่งเป็นเรื่องที่ผู้อนุมัติควรรู้ตั้งแต่อ่านคู่มือ ไม่ใช่ไปเดาเอาจากเมล
--
--  ---------------------------------------------------------------
--  เรื่องที่ต้องเขียนให้ชัดในคู่มือ เพราะเดาเองไม่ได้
--  ---------------------------------------------------------------
--  ลิงก์อนุมัติออกให้ "รายคน" ไม่ใช่ดอกเดียวใช้ร่วมกัน ปุ่มคัดลอกจึงเปิด
--  รายชื่อผู้อนุมัติให้เลือกก่อน ต่างจากปุ่มคัดลอกลิงก์เซ็นรับที่คัดลอกทันที
--
--  และผู้ที่ถือลิงก์จะตัดสินใบนั้น "ในนามของคนที่ลิงก์ออกให้" ส่งผิดคน
--  แปลว่าประวัติการอนุมัติบันทึกชื่อผิดคน ซึ่งกู้คืนไม่ได้
--
--  ---------------------------------------------------------------
--  เลขลำดับขั้น
--  ---------------------------------------------------------------
--  แทรกเป็นขั้นที่ 3 ให้ตรงกับลำดับปุ่มที่เห็นบนหน้าจอ (ดู · พิมพ์ · ลิงก์ ·
--  อนุมัติ · ไม่อนุมัติ · ยกเลิก · เมล) แล้วเลื่อนขั้น 3 เป็นต้นไปลงหนึ่งช่อง
--
--  รันไฟล์นี้ซ้ำจะเลื่อนซ้ำและได้ขั้นซ้ำ จึงลบขั้นเดิมทิ้งก่อนเสมอ
--  (กันไว้ด้วย DELETE ที่หัวไฟล์ เหมือนที่ 036 ทำ)
--
--  หมายเหตุ: 042 ชี้ขั้นตอนด้วย step_order ตามผังก่อนไฟล์นี้ ถ้าจะรัน 042
--  ซ้ำอีกครั้งหลังรันไฟล์นี้ ต้องเลื่อนเลขในไฟล์นั้นตามด้วย
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hr < sql/044_guide_approve_link.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/044_guide_approve_link_rollback.sql
-- ============================================================

SET NAMES utf8;

/* ---------- ลบขั้นเดิมก่อน กันรันซ้ำแล้วได้ขั้นซ้ำ ---------- */
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[data-row-act="approvelink"]';

/* ---------- เปิดช่องที่ 3 ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'request_list'
  AND s.`step_order` >= 3;

/* ---------- ขั้นใหม่: ปุ่มคัดลอกลิงก์อนุมัติ ---------- */
INSERT INTO `tb_guide_step`
    (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 3, '.rowact[data-row-act="approvelink"]', 'ไอคอนโซ่ — คัดลอกลิงก์อนุมัติ',
 'ลิงก์ที่ผู้อนุมัติกดตัดสินได้เลยโดยไม่ต้องเข้าระบบ ใช้ตอนเขาหาเมลไม่เจอ ส่งทางไลน์ได้ ลิงก์ออกให้เป็นรายคน กดแล้วจึงขึ้นรายชื่อให้เลือกก่อนว่าจะส่งให้ใคร ส่งผิดคน = ประวัติจะบันทึกชื่อผิดคน ลิงก์ใช้ได้ 3 วันและกดได้ครั้งเดียว เห็นเฉพาะผู้ดูแลระบบและเฉพาะใบที่ยังรออนุมัติ',
 'bottom', 'start', NOW()
FROM `tb_guide` WHERE `page_key` = 'request_list';

/* ---------- ขั้นอนุมัติ: บอกว่าอนุมัติจากเมลได้แล้ว ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'อนุมัติแล้วใบจะไปรอที่คลังเพื่อทำใบจ่าย ยังไม่ตัดสต๊อกตอนนี้ ระบบแจ้งผู้ขอเบิกให้เองทั้งกระดิ่งและอีเมล ผู้อนุมัติอนุมัติใบของตัวเองไม่ได้ อีกทางหนึ่งคือกดจากปุ่มในอีเมลที่ระบบส่งให้ ซึ่งเปิดหน้าอนุมัติได้เลยไม่ต้องเข้าระบบ'
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[data-row-act="approve"]';

/* ---------- ขั้นส่งเมลซ้ำ: บอกว่าเมลที่ส่งมีลิงก์อนุมัติติดไปด้วย ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ส่งอีเมลแจ้งเรื่องตามสถานะปัจจุบันของใบนั้นอีกครั้ง ใช้ตอนที่ปลายทางหาเมลฉบับเดิมไม่เจอหรือลบไปแล้ว ใบที่ยังรออนุมัติจะมีปุ่มอนุมัติติดไปในเมลด้วย ลิงก์เดิมที่ยังไม่หมดอายุจะถูกส่งซ้ำ ไม่ได้ออกใหม่ ของที่ส่งไปก่อนหน้าจึงยังใช้ได้ เห็นเฉพาะผู้ดูแลระบบ'
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[data-row-act="mail"]';
