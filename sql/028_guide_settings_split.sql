-- ============================================================
--  028_guide_settings_split.sql
--  แยกคู่มือของหน้าตั้งค่า ตามที่แยกเมนูเป็นสองบรรทัด
--
--  ---------------------------------------------------------------
--  ที่มา
--  ---------------------------------------------------------------
--  เดิม "อีเมลแจ้งเตือน" กับ "คู่มือการใช้งาน" เป็นแท็บสองอันในหน้าเดียว
--  ตอนนี้แยกเป็นสองเมนูบนแถบซ้าย (page_key: settings และ settings_guide)
--
--  ผลกับคู่มือมีสองข้อ:
--
--    1) ขั้นที่ 5 ชี้ไปที่ #tabGuideBtn ซึ่งเป็นปุ่มแท็บที่ถูกถอดออกไปแล้ว
--       ตัวคู่มือจะข้ามขั้นที่หาเป้าหมายไม่เจอให้เองอยู่แล้ว จึงไม่พัง
--       แต่จะเหลือคู่มือที่ไม่พูดถึงคู่มือเลย ทั้งที่มันย้ายไปอยู่อีกเมนูหนึ่ง
--       เปลี่ยนเป็นขั้นที่บอกว่าไปหาได้ที่ไหน โดยไม่ต้องชี้ไปที่ปุ่มใด
--
--    2) หน้า settings_guide ยังไม่มีคู่มือของตัวเอง ต้องสร้างใหม่
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/028_guide_settings_split.sql
--
--  ไฟล์นี้ลบของตัวเองก่อนใส่ใหม่ทุกครั้ง รันซ้ำได้ปลอดภัย
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/028_guide_settings_split_rollback.sql
-- ============================================================

SET NAMES utf8;


-- ============================================================
--  1) หน้าอีเมลแจ้งเตือน (page_key เดิม: settings)
-- ============================================================

UPDATE `tb_guide`
SET `title` = 'อีเมลแจ้งเตือน',
    `description` = 'ค่าเชื่อมต่ออีเมล การทดสอบส่ง และคิวเมลขาออก'
WHERE `page_key` = 'settings';

-- ขั้นสุดท้ายเคยชี้ไปที่ปุ่มแท็บ "คู่มือการใช้งาน" ซึ่งถูกถอดออกจากหน้าไปแล้ว
-- ตัดทิ้งไปเลย ไม่เขียนใหม่เป็นขั้นที่บอกว่าของย้ายไปไหน
-- เพราะนั่นคือประกาศเรื่องการเปลี่ยนแปลง ไม่ใช่วิธีใช้หน้านี้
-- คนที่เข้ามาใช้ทีหลังจะไม่รู้ด้วยซ้ำว่าเคยมีแท็บอยู่ตรงไหน
-- ส่วนเมนู "คู่มือการใช้งาน" ก็อยู่บนแถบซ้ายให้เห็นอยู่แล้ว
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'settings'
  AND (s.`target_selector` = '#tabGuideBtn' OR s.`title` = 'คู่มือย้ายไปเมนูของตัวเองแล้ว');


-- ============================================================
--  2) หน้าคู่มือการใช้งาน (page_key ใหม่: settings_guide)
-- ============================================================

DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'settings_guide';

DELETE FROM `tb_guide` WHERE `page_key` = 'settings_guide';

