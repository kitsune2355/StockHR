--  ไฟล์นี้จะไปแก้ข้อความผิดขั้นทันทีที่ลำดับขยับอีกครั้ง
--  ส่วน selector ผูกกับปุ่มจริงบนหน้าจอ จึงไม่ขึ้นกับว่าขั้นนั้นอยู่ที่เท่าไร
