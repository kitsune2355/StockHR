SET NAMES utf8;

/* ---------- ประวัติการจ่ายออก: ไอคอนโซ่ ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title`       = 'ไอคอนโซ่ — ลิงก์เซ็นรับของ',
    s.`description` = 'เปิดกล่องที่มีลิงก์ให้ผู้เบิกเซ็นรับ กดปุ่มไอคอนท้ายช่องเพื่อคัดลอก หรือลากคลุมเองก็ได้ ลิงก์เปิดได้โดยไม่ต้องล็อกอิน ส่งทางไลน์ได้ ใช้ได้ 7 วัน และใครถือก็เซ็นแทนได้ จึงส่งให้เฉพาะผู้เบิก กดส่งเมลซ้ำเมื่อไร ลิงก์เดิมถูกยกเลิกทันที'
WHERE g.`page_key` = 'issue_history'
  AND s.`target_selector` = '.rowact[data-row-act="copylink"]';

/* ---------- รายการใบเบิก: ไอคอนโซ่ ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title`       = 'ไอคอนโซ่ — ลิงก์อนุมัติ',
    s.`description` = 'เปิดกล่องรายชื่อผู้อนุมัติ เพราะลิงก์ออกให้เป็นรายคน เลือกก่อนว่าจะส่งให้ใคร แล้วกดปุ่มไอคอนท้ายช่องเพื่อคัดลอก ส่งผิดคน = ประวัติจะบันทึกชื่อผิดคน ลิงก์ใช้ได้ 3 วัน กดได้ครั้งเดียว ผู้อนุมัติกดตัดสินได้เลยโดยไม่ต้องเข้าระบบ เห็นเฉพาะผู้ดูแลระบบและเฉพาะใบที่ยังรออนุมัติ'
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[data-row-act="approvelink"]';
