-- ============================================================
--  014_company_logo.sql
--  เก็บโลโก้ของแต่ละบริษัท ไว้ใช้เป็นหัวกระดาษบนเอกสารที่พิมพ์ออกมา
--
--  ที่มา: ใบเบิกที่พิมพ์ออกกระดาษต้องมีหัวกระดาษของบริษัทเจ้าของหน่วยงานนั้น
--  ระบบมีหลายบริษัทในฐานข้อมูลเดียว โลโก้จึงผูกกับ tb_company ไม่ใช่ค่าตั้งกลาง
--
--  ---------------------------------------------------------------
--  เก็บ "ชื่อไฟล์" ไม่ใช่ตัวรูป
--  ---------------------------------------------------------------
--  ทางเลือกคือเก็บรูปเป็น BLOB ในตาราง ซึ่งทำให้สำรองฐานข้อมูลบวมขึ้นหลายเท่า
--  ทุกครั้งที่ dump และทุกการ query ที่เผลอ SELECT * จะลากรูปมาด้วย
--
--  เก็บเป็นชื่อไฟล์แล้ววางไฟล์จริงไว้ที่ assets/img/company/ แทน
--  เบราว์เซอร์จะแคชรูปให้เอง และเว็บเซิร์ฟเวอร์ส่งไฟล์นิ่งได้เร็วกว่า PHP มาก
--
--  เก็บเฉพาะชื่อไฟล์ ไม่เก็บ path เต็ม เพราะย้ายโฟลเดอร์โปรเจกต์ทีหลัง
--  จะได้ไม่ต้องไล่แก้ข้อมูลทุกแถว
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hl < sql/014_company_logo.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/014_company_logo_rollback.sql
-- ============================================================

SET NAMES utf8;

ALTER TABLE `tb_company`
  ADD COLUMN `logo_file` VARCHAR(255) NOT NULL DEFAULT ''
  COMMENT 'ชื่อไฟล์โลโก้ใน assets/img/company/ (ว่าง = ยังไม่มี)'
  AFTER `company_name`;


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT `company_id`, `company_name`,
       IF(`logo_file` = '', 'ยังไม่มีโลโก้', `logo_file`) AS `โลโก้`
FROM `tb_company`
ORDER BY `company_id`;
