--  063_guide_request_openapprovelink.sql
--  คู่มือหน้ารายการใบเบิก: เพิ่มขั้นของไอคอน "เปิดลิงก์อนุมัติ" ที่ตกหล่น
--  และปรับข้อความขั้น "ส่งกลับแก้ไข" หลังทำให้ไอคอนโผล่บนแถวตัวอย่างได้แล้ว
--
--  ที่มา:
--    1. ไอคอน "เปิดลิงก์อนุมัติ" (openapprovelink) มีในคอลัมน์จัดการตั้งแต่
--       เพิ่มปุ่มเปิดลิงก์ แต่คู่มือหน้ารายการใบเบิกไม่เคยมีขั้นของมัน
--       (หน้าประวัติการปรับยอดมีแล้วใน sql/060) — คนเปิดคู่มือหน้านี้จึงถูกข้าม
--    2. sql/062 เขียนไว้ว่าไอคอน "ส่งกลับแก้ไข" ไม่โผล่บนแถวตัวอย่าง
--       ตอนนี้ actionsFor() ใน doc-list.js โชว์ให้บนแถว _demo แล้ว จึงตัดคำนั้นออก
--
--  ---------------------------------------------------------------
--  เลขลำดับขั้น (ให้ตรงกับลำดับไอคอนบนหน้าจอ)
--  ---------------------------------------------------------------
--  ผังปุ่ม: ดู · พิมพ์ · คัดลอกลิงก์ · เปิดลิงก์ · แก้ไข · อนุมัติ · ไม่อนุมัติ ·
--  ส่งกลับ · ยกเลิก · เมล
--
--  ก่อนรัน (สถานะหลัง sql/062):
--    4 คัดลอกลิงก์  5 แก้ไข  6 อนุมัติ  7 ไม่อนุมัติ  8 ส่งกลับ  9 ยกเลิก  10 เมล  11 ส่งออกรายบรรทัด
--
--  แทรก "เปิดลิงก์อนุมัติ" เป็นขั้นที่ 5 แล้วเลื่อนขั้น 5 เป็นต้นไปลงหนึ่งช่อง
--  รันซ้ำจะเลื่อนซ้ำและได้ขั้นซ้ำ จึงลบขั้นเดิมของ selector นี้ทิ้งก่อนเสมอ
--
--  หมายเหตุ: 042/044/045/062 ชี้ขั้นตอนด้วย step_order ตามผังก่อนไฟล์นี้
--  ถ้าจะรันไฟล์เหล่านั้นซ้ำหลังรันไฟล์นี้ ต้องเลื่อนเลขตามด้วย
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/063_guide_request_openapprovelink.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/063_guide_request_openapprovelink_rollback.sql
-- ============================================================

SET NAMES utf8;

/* ---------- ลบขั้นเดิมก่อน กันรันซ้ำแล้วได้ขั้นซ้ำ ---------- */
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[data-row-act="openapprovelink"]';

/* ---------- เปิดช่องที่ 5 ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'request_list'
  AND s.`step_order` >= 5;

/* ---------- ขั้นใหม่: ปุ่มเปิดลิงก์อนุมัติ ---------- */
INSERT INTO `tb_guide_step`
    (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 5, '.rowact[data-row-act="openapprovelink"]', 'ไอคอนลูกศรออก — เปิดลิงก์อนุมัติ',
 'เปิดหน้าอนุมัติในแท็บใหม่ทันที ใช้ตอนอยากอนุมัติเองเลยโดยไม่ต้องรออีเมล มีผู้อนุมัติคนเดียว = เปิดของคนนั้น หลายคน = เปิดกล่องให้เลือกก่อน (ลิงก์ออกให้เป็นรายคน เปิดผิดคน = คนนั้นตัดสินใบนี้ในนามคนที่ลิงก์ออกให้) เห็นเฉพาะผู้ดูแลระบบและเฉพาะใบที่ยังรออนุมัติ',
 'bottom', 'start', NOW()
FROM `tb_guide` WHERE `page_key` = 'request_list';

/* ---------- ปรับข้อความขั้น "ส่งกลับแก้ไข" — ไอคอนโผล่บนแถวตัวอย่างแล้ว ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ใช้ตอนใบผ่านอนุมัติแล้วแต่ผู้ทำเบิกแจ้งว่าเบิกของผิด กดถอยใบกลับไปให้ผู้ทำเบิกแก้ สถานะกลับเป็น "รออนุมัติ" ต้องระบุสิ่งที่ต้องแก้เพื่อให้ผู้ทำเบิกรู้ ส่งกลับใบของตัวเองไม่ได้ และถ้าคลังจ่ายของใบนี้ไปบางส่วนแล้วจะส่งกลับไม่ได้ ต้องยกเลิกใบจ่ายก่อน ในการใช้งานจริงไอคอนนี้ขึ้นเฉพาะบนใบที่อนุมัติแล้วและเฉพาะผู้อนุมัติ'
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[data-row-act="sendback"]';


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT s.`step_order`, s.`target_selector`, s.`title`
FROM `tb_guide_step` s
JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'request_list'
ORDER BY s.`step_order`;
