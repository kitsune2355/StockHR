--
--  ---------------------------------------------------------------
--  2) หน้าบาร์โค้ดสินค้า (คู่มือใหม่ทั้งชุด)
--  ---------------------------------------------------------------
--  เรื่องที่ต้องอธิบายมากที่สุดไม่ใช่วิธีกดปุ่ม แต่เป็น "ความกว้างแท่ง"
--  เพราะเป็นตัวเดียวที่ตัดสินว่าฉลากที่พิมพ์ไปแล้วจะยิงติดหรือเปล่า
--  และเป็นสิ่งที่ผู้ใช้ไม่มีทางเดาได้เองว่าต้องดู
--
--  หน้านี้มี window.GuideDemo เลือกสินค้าให้ 4 รายการตอนเปิดคู่มือ
--  ขั้นที่ชี้ไปที่แผ่นตัวอย่างกับปุ่มพิมพ์จึงมีของให้ดูจริง ไม่ใช่หน้าจอว่าง ๆ
--
--  *** อ่านก่อนรัน ***
--  ส่วนที่ 1 ของไฟล์นี้เป็นการ "แทรก" ขั้นเข้าไปในคู่มือเดิม จึงรันได้ครั้งเดียว
--  รันซ้ำจะได้ขั้นซ้ำและลำดับเลื่อน ถ้าต้องติดตั้งใหม่หรือไม่แน่ใจว่าเคยรันไปแล้ว
--  ให้ใช้ sql/026b_guide_category_rebuild.sql แทนส่วนที่ 1 และ 3
--  (ไฟล์นั้นลบทิ้งแล้วใส่ใหม่ทั้งชุด รันกี่รอบก็ได้ผลเหมือนเดิม)
--  ส่วนที่ 2 (หน้าบาร์โค้ด) ลบก่อนใส่อยู่แล้ว รันซ้ำได้ปลอดภัย
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/026_guide_unit_and_barcode.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/026_guide_unit_and_barcode_rollback.sql
