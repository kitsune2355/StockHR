SET NAMES utf8;

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ทั้งสองแบบเก็บรหัสสินค้าตัวเดียวกันเป๊ะ ต่างกันแค่ใครอ่านได้ บาร์โค้ดใช้กับเครื่องยิงที่เสียบกับคอมพิวเตอร์ ซึ่งเป็นวิธีที่เร็วที่สุดตอนรับเข้าหรือจ่ายของทีละหลายรายการ ส่วน QR ส่องด้วยกล้องมือถือธรรมดาได้ เหมาะกับคนที่ไม่มีเครื่องยิงติดตัว เช่นตอนไปนับของที่ชั้นวางหรือหน้างานนอกห้องคลัง ข้อควรรู้: เครื่องยิงเลเซอร์แบบเส้นตรงส่วนใหญ่อ่าน QR ไม่ได้ ต้องเป็นรุ่นที่เป็นกล้อง (2D imager) เท่านั้น ถ้าไม่แน่ใจว่าเครื่องที่มีอยู่เป็นแบบไหน ให้ลองยิงดูจากตัวอย่างบนหน้าจอนี้ได้เลย เมื่อเลือก QR จะมีตัวเลือกการจัดวางโผล่ขึ้นมาใต้ปุ่มนี้ ให้เลือกได้ว่าจะเอา QR ไว้ทางซ้ายแล้ววางข้อความไว้ทางขวา (แนวนอน) หรือเอา QR ไว้ด้านบนแล้ววางข้อความไว้ด้านล่าง (แนวตั้ง) แนวนอนได้ QR ใหญ่กว่าเพราะกินความสูงเต็มดวง จึงส่องติดง่ายกว่า ส่วนแนวตั้งเหมาะกับสินค้าที่ชื่อยาว เพราะข้อความได้ความกว้างเต็มดวงเลยอ่านง่ายกว่า แลกกับ QR ที่เล็กลง ถ้าเลือกแนวตั้งแล้วมีกล่องเตือนสีเหลืองขึ้นมา แปลว่าเล็กเกินไปแล้ว ให้กลับไปใช้แนวนอนหรือเลือกดวงสติกเกอร์ที่ใหญ่ขึ้น'
WHERE g.`page_key` = 'product_barcode' AND s.`target_selector` = '#bcType';

/* ขั้นของแผ่นตัวอย่าง — เดิมเขียนว่าอยู่ "ด้านล่าง" ของหน้า
   ตอนนี้ผังหน้าเปลี่ยนเป็นเต็มจอ แผ่นตัวอย่างอยู่บนจอพร้อมแผงตั้งค่าตลอด
   ข้อความเดิมไม่ได้ผิดจนอ่านไม่รู้เรื่อง แต่พลาดโอกาสบอกสิ่งที่มีประโยชน์
   คือปรับค่าแล้วเห็นผลทันทีโดยไม่ต้องเลื่อนหน้า */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ฉลากที่เห็นตรงนี้คือฉลากจริงที่จะออกมาบนกระดาษ ขนาดเท่าของจริงทุกมิลลิเมตร เส้นประรอบดวงเป็นแค่รอยตัดสมมติให้ดูว่าเนื้อหาชิดขอบเกินไปหรือเปล่า ไม่ถูกพิมพ์ลงกระดาษจริง แผ่นตัวอย่างอยู่บนจอพร้อมกับแผงตั้งค่าทางขวาเสมอ ปรับค่าอะไรก็เห็นผลตรงนี้ทันทีโดยไม่ต้องเลื่อนหน้าไปมา ถ้าชื่อสินค้ายาวเกินดวง ระบบจะตัดเหลือสองบรรทัดแล้วเติมจุดไข่ปลาให้ ส่วนรหัสกับตัวบาร์โค้ดหรือ QR จะไม่ถูกย่อไม่ว่ากรณีใด ตอนนี้คู่มือเลือกสินค้าตัวอย่างให้ดูสี่รายการ พอปิดคู่มือจะกลับไปเป็นรายการที่คุณเลือกไว้เดิม'
WHERE g.`page_key` = 'product_barcode' AND s.`target_selector` = '#bcSheet';
