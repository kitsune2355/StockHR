SET NAMES utf8;

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title`       = 'ไอคอนโซ่ — คัดลอกลิงก์เซ็นรับ',
    s.`description` = 'คัดลอกลิงก์ให้ผู้เบิกเซ็นรับ เปิดได้โดยไม่ต้องล็อกอิน ส่งทางไลน์ได้ ลิงก์ใช้ได้ 7 วัน และใครถือก็เซ็นแทนได้ จึงส่งให้เฉพาะผู้เบิก กดส่งเมลซ้ำเมื่อไร ลิงก์เดิมถูกยกเลิกทันที'
WHERE g.`page_key` = 'issue_history'
  AND s.`target_selector` = '.rowact[data-row-act="copylink"]';

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title`       = 'ไอคอนโซ่ — คัดลอกลิงก์อนุมัติ',
    s.`description` = 'ลิงก์ที่ผู้อนุมัติกดตัดสินได้เลยโดยไม่ต้องเข้าระบบ ใช้ตอนเขาหาเมลไม่เจอ ส่งทางไลน์ได้ ลิงก์ออกให้เป็นรายคน กดแล้วจึงขึ้นรายชื่อให้เลือกก่อนว่าจะส่งให้ใคร ส่งผิดคน = ประวัติจะบันทึกชื่อผิดคน ลิงก์ใช้ได้ 3 วันและกดได้ครั้งเดียว เห็นเฉพาะผู้ดูแลระบบและเฉพาะใบที่ยังรออนุมัติ'
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[data-row-act="approvelink"]';
