INSERT INTO `tb_category` (`category_code`, `category_name`, `is_active`, `created_at`)
SELECT CONCAT('C', LPAD((SELECT COUNT(*) FROM `tb_category` c2) + 1, 3, '0')), x.`cat`, 1, NOW()
FROM (SELECT DISTINCT `cat` FROM `tmp_import`) x
WHERE NOT EXISTS (SELECT 1 FROM `tb_category` c WHERE c.`category_name` = x.`cat`);

INSERT INTO `tb_sub_category` (`category_id`, `sub_category_code`, `sub_category_name`, `is_active`, `created_at`)
SELECT (SELECT c.`category_id` FROM `tb_category` c WHERE c.`category_name` = x.`cat` LIMIT 1),
       s.`code`, x.`sub`, 1, NOW()
FROM (SELECT `sub`, MIN(`cat`) AS `cat` FROM `tmp_import` GROUP BY `sub`) x
INNER JOIN `tmp_subcode` s ON s.`sub` = x.`sub`
WHERE NOT EXISTS (SELECT 1 FROM `tb_sub_category` sc WHERE sc.`sub_category_name` = x.`sub`);

INSERT IGNORE INTO `tb_unit` (`unit_name`, `is_active`, `created_at`)
