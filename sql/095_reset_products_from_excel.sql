INSERT INTO `tb_product`
  (`product_code`, `product_name`, `sub_category_id`, `unit_id`, `unit_cost`, `min_qty`, `max_qty`,
   `is_active`, `created_at`)
SELECT t.`code`, t.`name`,
       (SELECT sc.`sub_category_id` FROM `tb_sub_category` sc WHERE sc.`sub_category_name` = t.`sub` LIMIT 1),
       (SELECT u.`unit_id` FROM `tb_unit` u WHERE u.`unit_name` = t.`unit` LIMIT 1),
       t.`cost`, t.`minq`, 0, 1, NOW()
FROM `tmp_import` t
ON DUPLICATE KEY UPDATE
  `product_name`    = VALUES(`product_name`),
  `sub_category_id` = VALUES(`sub_category_id`),
  `unit_id`         = VALUES(`unit_id`),
  `unit_cost`       = VALUES(`unit_cost`),
  `min_qty`         = VALUES(`min_qty`),
  `is_active`       = 1;


