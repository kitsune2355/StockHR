--  095_reset_products_from_excel.sql
--  เริ่มระบบใหม่ด้วยรายการสินค้าจาก "สต็อคชุดฟอร์ม.xlsx" (103 รายการ, สร้างไฟล์ 23/11/2569)
--
--  ⚠ ลบข้อมูลถาวร — ล้างเอกสารทั้งหมด (ใบรับเข้า/ใบเบิก/ใบจ่าย/ใบปรับยอด) และประวัติสต๊อก
--    แล้วตั้งยอดคงเหลือใหม่ตาม Excel เป็น "ยอดยกมา"
--    สำรองฐานก่อนรันเสมอ (mysqldump หรือ phpMyAdmin > Export)
--
--  ทำอะไรบ้าง
--    1) ล้างเอกสารทั้งหมด + ของที่ผูกกับเอกสาร: ไฟล์แนบ (แถวในตาราง), ประวัติเอกสาร, ลิงก์อนุมัติ,
--       ข้อมูลพนักงานใหม่/สวัสดิการของใบ, แจ้งเตือนและเมลที่อ้างเอกสาร
--       (ตัวไฟล์ใบบิลใน storage/doc_attach/ ต้องลบเองด้วยมือ)
--    2) ล้างประวัติสต๊อก (tb_stock_movement) และยอดคงเหลือ (tb_stock_balance)
--    3) หมวดหลัก/หมวดย่อย: เพิ่มที่ยังไม่มี (จับคู่ด้วยชื่อ) — ไม่ลบของเดิม
--       แถวที่หมวดหลักว่างใน Excel (เสื้อฟอร์ม MEA, เสื้อช่าง PRO) ใส่ใต้ "เสื้อฟอร์มพนักงาน"
--    4) สินค้า: จับคู่ด้วยรหัส — มีอยู่แล้ว = อัปเดตชื่อ/หมวด/หน่วย/ราคา/ขั้นต่ำ (product_id เดิม)
--       ไม่มี = เพิ่มใหม่ · รหัสที่ไม่อยู่ใน Excel = ลบทิ้ง
--       ใช้ product_id เดิม การจับคู่ชุดฟอร์มกับระบบสวัสดิการ / สินค้าของหน่วยงาน จึงไม่พัง
--    5) ยอดคงเหลือ = "จำนวนที่มี" ใน Excel + บันทึกประวัติ "ยอดยกมา" (ปรับยอด) ให้รายงานย้อนหลังตรง
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u USER -p --default-character-set=utf8 <ฐาน> < sql/095_reset_products_from_excel.sql
--  รันซ้ำได้ (ผลลัพธ์เหมือนเดิม — แต่จะล้างเอกสารที่เกิดขึ้นหลังรันครั้งก่อนด้วย)
--  ไม่มีไฟล์ rollback — ย้อนได้จากไฟล์สำรองเท่านั้น
-- ============================================================

