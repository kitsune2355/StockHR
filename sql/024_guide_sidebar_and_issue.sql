--  เพิ่มขั้นอธิบายเมนูซ้าย และขยายคู่มือหน้าบันทึกจ่ายออก
--
--  ---------------------------------------------------------------
--  1. ภาพรวมระบบ: อธิบายเมนูซ้ายด้วย
--  ---------------------------------------------------------------
--  เมนูซ้ายเป็นสิ่งที่ผู้ใช้ต้องใช้ทุกครั้งที่จะไปไหนก็ตาม แต่คู่มือไม่เคยพูดถึงเลย
--  โดยเฉพาะสองเรื่องที่มองไม่ออกเอง: รายการที่เห็นเปลี่ยนตามสิทธิ์ และปุ่มย่อเมนู
--
--  วางไว้เป็นขั้นที่ 2 ต่อจาก "งานที่รอคุณ" เพราะเป็นลำดับที่คนใช้จริง —
--  ดูว่ามีงานอะไรค้าง แล้วเดินไปที่หน้านั้น
--
--  ---------------------------------------------------------------
--  2. บันทึกจ่ายออก: มีชุดข้อมูลสาธิตแล้ว
--  ---------------------------------------------------------------
--  หน้านั้นเปิดมาแล้วว่างเปล่าเสมอ และถ้าไม่มีใบเบิกที่อนุมัติแล้วรออยู่
--  จะขึ้นแค่ "ไม่มีใบเบิกรอจ่าย" คู่มือเดิมจึงอธิบายกับหน้าจอที่ไม่มีอะไรให้ดู
--
--  ตอนนี้ระบบใส่ใบเบิกสมมติให้ระหว่างเปิดคู่มือ แล้วเรียกเส้นทางเลือกใบเบิก
--  ตัวจริง หน้าจอที่เห็นจึงเหมือนตอนใช้งานจริงทุกอย่าง
--  (ดู window.GuideDemo ใน assets/js/doc-form.js)
--
--  เพิ่มขั้นที่อธิบายแถบข้อมูลใบเบิกกับช่องชื่อผู้รับ ซึ่งของเดิมข้ามไป
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hr < sql/024_guide_sidebar_and_issue.sql
--
--  ย้อนกลับ:
--      รัน sql/022 แล้วตามด้วย sql/023 จะได้คู่มือชุดก่อนหน้าไฟล์นี้กลับมา
-- ============================================================

SET NAMES utf8;


-- ============================================================
--  ภาพรวมระบบ — แทรกขั้นเมนูซ้ายเป็นขั้นที่ 2
-- ============================================================
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'dashboard' AND s.`step_order` >= 2;

INSERT INTO `tb_guide_step` (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 2, '#sidebar', 'เมนูซ้าย — ทางไปทุกหน้า',
 'หัวข้อที่มีลูกศรกดแล้วกางเมนูย่อยออกมา รายการที่คุณเห็นไม่เท่ากับของคนอื่น เพราะขึ้นกับสิทธิ์ที่ผู้ดูแลระบบตั้งไว้ ถ้าหาเมนูที่เพื่อนบอกไม่เจอ แปลว่าสิทธิ์ของคุณยังไม่เปิดหน้านั้น ไม่ใช่ระบบเสีย · ปุ่มลูกศรที่หัวเมนูใช้ย่อให้เหลือแต่ไอคอน เอาไว้ตอนอยากได้พื้นที่อ่านตารางกว้าง ๆ ระบบจำสถานะที่ย่อไว้ให้ในเครื่องนี้',
 'right', 'start', NOW() FROM `tb_guide` WHERE `page_key`='dashboard';


