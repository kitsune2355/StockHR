SET NAMES utf8;

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title` = 'ยิงบาร์โค้ดแทนการค้นหา',
    s.`description` = 'ถ้าของที่รับเข้ามามีฉลากบาร์โค้ดแปะอยู่ ให้คลิกที่ช่องนี้แล้วยิงได้เลย ระบบจะเพิ่มบรรทัดพร้อมสินค้าและราคาให้ทันที ยิงซ้ำสินค้าตัวเดิมจะบวกจำนวนขึ้นทีละหนึ่ง ไม่ได้สร้างบรรทัดซ้ำ จึงเดินยิงของทีละชิ้นได้เลยโดยไม่ต้องนับก่อน ยิงถูกจะได้ยินเสียงสูงสั้น ยิงไม่เจอจะได้เสียงต่ำยาว ฟังได้โดยไม่ต้องละสายตาจากของ ฉลากบาร์โค้ดพิมพ์ได้จากเมนู ข้อมูลสินค้า > บาร์โค้ดสินค้า'
WHERE g.`page_key` = 'receive_new' AND s.`target_selector` = '#scanInput';

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title` = 'ยิงบาร์โค้ดถ้ามีของอยู่ตรงหน้า',
    s.`description` = 'ถ้ากำลังยืนอยู่หน้าชั้นวางและเห็นของจริง ยิงบาร์โค้ดที่ฉลากได้เลย เร็วกว่าไล่หาชื่อในรายการ ยิงแล้วสินค้าจะไปอยู่ฝั่งขวาทันที ยิงซ้ำตัวเดิมจะบวกจำนวนขึ้นทีละหนึ่ง ถ้ายิงแล้วขึ้นว่าไม่พบ ให้ดูก่อนว่าเลือกหน่วยงานถูกหรือยัง เพราะแต่ละหน่วยงานเบิกสินค้าได้ไม่เหมือนกัน สินค้าที่หน่วยงานนี้ไม่มีสิทธิ์เบิกจะยิงไม่ติด'
WHERE g.`page_key` = 'request_new' AND s.`target_selector` = '#scanInput';

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'หน้านี้เพิ่มบรรทัดเองไม่ได้ รายการทั้งหมดมาจากใบเบิกที่เลือกไว้ การยิงตรงนี้จึงไม่ใช่การเพิ่มสินค้า แต่เป็นการนับของที่หยิบใส่กล่องไปแล้ว หยิบของหนึ่งชิ้นก็ยิงหนึ่งครั้ง ระบบจะบวกจำนวนในบรรทัดของสินค้านั้นให้ทีละหนึ่ง แล้วขึ้นข้อความบอกความคืบหน้า เช่น "หยิบแล้ว 2 จาก 5 ม้วน" หมายถึงหยิบไปแล้ว 2 ม้วน จากที่ใบเบิกขอมา 5 ม้วน เมื่อหยิบครบตามจำนวนที่ขอ ระบบจะเตือนว่าไม่ต้องหยิบเพิ่มแล้ว ประโยชน์ที่สำคัญที่สุดคือการจับว่าหยิบผิดตัว ถ้ายิงสินค้าที่ไม่มีอยู่ในใบเบิกใบนี้ ระบบจะเตือนพร้อมเสียงต่ำทันที ตอนที่ของยังอยู่ในมือ ไม่ใช่ตอนที่ส่งไปถึงหน่วยงานแล้ว'
WHERE g.`page_key` = 'issue_new' AND s.`target_selector` = '#scanInput';
