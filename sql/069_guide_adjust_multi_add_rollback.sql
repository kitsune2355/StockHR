SET NAMES utf8;

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title` = 'กดเพิ่มรายการ แล้วเลือกสินค้าในบรรทัด',
    s.`description` = 'กดปุ่มนี้เพื่อเพิ่มบรรทัดว่าง แล้วเลือกสินค้าในช่องแรกของบรรทัด (พิมพ์รหัสหรือชื่อค้นได้) ช่อง "นับได้จริง" จะตั้งค่าเริ่มไว้เท่ากับยอดในระบบให้ แก้เฉพาะตัวที่นับได้ไม่ตรง ระบบคำนวณส่วนต่างให้เอง (เขียว = เกิน แดง = ขาด)'
WHERE g.`page_key` = 'adjust_new'
  AND s.`target_selector` = '#btnAddRow';
