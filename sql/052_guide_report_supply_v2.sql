-- ============================================================
--  052_guide_report_supply_v2.sql
--  ปรับคู่มือหน้า "สั่งซื้อ-เบิกใช้รายเดือน" ให้ตรงกับหน้าที่เปลี่ยนไปแล้ว
--
--  คู่มือชุดเดิม (ไฟล์ 049) เขียนตอนที่หน้ายังมีแค่ตารางเปล่า ๆ
--  หลังจากนั้นหน้าได้ของใหม่มาสี่อย่างที่คู่มือยังไม่พูดถึงเลย
--
--    1. ช่องราคา/หน่วย ที่กดแล้วกางเป็นแถวย่อยรายราคาใต้สินค้า
--    2. การจัดกลุ่มลงถึงหมวดหมู่ย่อย พร้อมยอดรวมสามชั้น
--    3. ปุ่มเลือกคอลัมน์เอง
--    4. ตัวเลือกตอนส่งออกว่าจะใส่รายละเอียดราคาหรือไม่
--
--  และมีอีกสองข้อที่ "พูดผิดไปแล้ว" ต้องแก้
--    ขั้นที่ 4 บอกว่าตรึงสี่คอลัมน์แรก ตอนนี้ตรึงเก้าคอลัมน์
--    ขั้นที่ 7 บอกว่าไฟล์เหมือนบนจอทุกอย่าง ตอนนี้เลือกได้ว่าจะใส่อะไรบ้าง
--
--  ---------------------------------------------------------------
--  ลำดับใหม่ 11 ขั้น
--  ---------------------------------------------------------------
--    1  อ่านทีละแถว                (เดิม)
--    2  เลือกเดือน                  (เดิม)
--    3  เดือนนี้มีอะไรขยับบ้าง        (เดิม)
--    4  คอลัมน์หน่วยงาน + คอลัมน์ที่ตรึง  (แก้ข้อความ)
--    5  ยอดยกมาไม่ใช่ยอดที่เดินไปนับ  (เดิม)
--    6  ราคา/หน่วย และแถวย่อยรายราคา  (ใหม่)
--    7  หมวดหมู่และยอดรวมสามชั้น      (ใหม่)
--    8  ดูเฉพาะรายการที่ขยับ         (เดิม เลื่อนลำดับ)
--    9  เลือกคอลัมน์เอง              (ใหม่)
--   10  ส่งออก Excel                (แก้ข้อความ เลื่อนลำดับ)
--   11  พิมพ์ลงกระดาษ               (เดิม เลื่อนลำดับ)
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hr < sql/052_guide_report_supply_v2.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/052_guide_report_supply_v2_rollback.sql
-- ============================================================

SET NAMES utf8;

-- ------------------------------------------------------------
--  1) เลื่อนลำดับของขั้นเดิมออกไปก่อน เว้นที่ให้ขั้นใหม่
--     ทำจากท้ายมาหน้า ไม่งั้นจะไปทับลำดับที่ยังไม่ได้ย้าย
-- ------------------------------------------------------------
UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 11 WHERE g.`page_key` = 'report_supply' AND s.`step_order` = 8;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 10 WHERE g.`page_key` = 'report_supply' AND s.`step_order` = 7;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = 8  WHERE g.`page_key` = 'report_supply' AND s.`step_order` = 6;


-- ------------------------------------------------------------
--  2) แก้ข้อความที่พูดผิดไปแล้ว
-- ------------------------------------------------------------
UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ตรงกลางตารางจะกางคอลัมน์ให้เฉพาะหน่วยงานที่มีการเบิกจริงในเดือนนั้น หน่วยงานที่เดือนนี้ไม่ได้เบิกอะไรเลยจะไม่มีคอลัมน์ ไม่ได้หายไปจากระบบ ระบบมีหน่วยงานหกสิบกว่าหน่วย ถ้ากางครบทุกเดือนจะได้ตารางกว้างร้อยกว่าคอลัมน์ที่ว่างเปล่าเกือบหมด ชื่อหน่วยงานซ้ำกันข้ามบริษัทได้ จึงมีชื่อบริษัทกำกับไว้ใต้ชื่อหน่วยงานทุกคอลัมน์ ส่วนคอลัมน์ซ้ายมือตั้งแต่ลำดับจนถึงกลุ่มซื้อเข้าถูกตรึงไว้ให้ เลื่อนไปทางขวาไกลแค่ไหนก็ยังเห็นว่ากำลังดูสินค้าตัวไหน ยกมาเท่าไร และเดือนนี้ซื้อเข้ามาเท่าไร'
WHERE g.`page_key` = 'report_supply' AND s.`step_order` = 4;

UPDATE `tb_guide_step` s JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ได้ไฟล์หน้าตาเหมือนที่เห็นบนจอ ทั้งหัวตารางสองชั้น คอลัมน์หน่วยงาน แถวคั่นหมวด และยอดรวมทุกชั้น ตัวเลขส่งออกเป็นตัวเลขจริง เอาไปบวกต่อใน Excel ได้เลย ถ้ากรองหรือปิดคอลัมน์ไว้อยู่ ไฟล์ที่ได้จะมีเฉพาะที่เห็นอยู่เท่านั้น ช่องติ๊กข้าง ๆ ปุ่มเลือกได้ว่าจะใส่แถวย่อยรายราคาลงไฟล์ด้วยไหม ใส่แล้ว Excel จะมีปุ่มยุบ/กางที่ขอบซ้ายให้กดเหมือนบนจอ ไม่ใส่ก็ได้ไฟล์แบนราบเอาไปทำ pivot ต่อได้สะดวกกว่า'
WHERE g.`page_key` = 'report_supply' AND s.`step_order` = 10;


-- ------------------------------------------------------------
--  3) ขั้นใหม่
--     WHERE NOT EXISTS กันรันซ้ำแล้วได้ขั้นซ้อนกันสองอัน
-- ------------------------------------------------------------
INSERT INTO `tb_guide_step`
  (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT g.`guide_id`, 6, '#spWrap', 'ซื้อมาคนละราคา กดดูได้ว่าราคาไหนบ้าง',
       'ของตัวเดียวกันในเดือนเดียวซื้อมาคนละราคาได้ ช่องราคา/หน่วยจึงขึ้นว่า "2 ราคา" แทนที่จะยัดทุกราคาไว้ในช่องเดียว กดปุ่มนั้นแล้วจะกางเป็นแถวย่อยใต้สินค้า หนึ่งราคาหนึ่งแถว ตรงคอลัมน์กับแถวหลักทุกช่อง อ่านลงมาตามแนวตั้งได้เลยว่าราคานั้นซื้อมาเท่าไร แล้วหน่วยงานไหนเบิกของราคานั้นไปเท่าไร ช่องยกมากับคงเหลือเว้นว่างในแถวย่อย เพราะของที่ยกมาจากเดือนก่อนไม่มีใครรู้แล้วว่าตอนนั้นซื้อมาล็อตละเท่าไร',
       'top', 'center', NOW()
FROM `tb_guide` g
WHERE g.`page_key` = 'report_supply'
  AND NOT EXISTS (SELECT 1 FROM `tb_guide_step` x
                  WHERE x.`guide_id` = g.`guide_id` AND x.`step_order` = 6);

INSERT INTO `tb_guide_step`
  (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT g.`guide_id`, 7, '#spWrap', 'จัดกลุ่มตามหมวดหมู่ พร้อมยอดรวมสามชั้น',
       'รายการเรียงตามหมวดหมู่หลักแล้วลงไปถึงหมวดหมู่ย่อย ปิดท้ายแต่ละกลุ่มด้วยยอดรวมของกลุ่มนั้น แล้วรวมอีกทีที่หมวดหมู่หลัก และรวมทั้งใบที่แถวล่างสุด ยอดทั้งสามชั้นบวกกันขึ้นไปได้ลงตัวเสมอ ใช้ตอบคำถามว่า "เดือนนี้หมดไปกับของกลุ่มไหนมากที่สุด" ได้โดยไม่ต้องเอาไปคิดต่อใน Excel หัวหมวดกับยอดรวมถูกตรึงไว้ เลื่อนไปทางไหนก็ยังอ่านออกว่าอยู่กลุ่มไหน',
       'top', 'center', NOW()
FROM `tb_guide` g
WHERE g.`page_key` = 'report_supply'
  AND NOT EXISTS (SELECT 1 FROM `tb_guide_step` x
                  WHERE x.`guide_id` = g.`guide_id` AND x.`step_order` = 7);

INSERT INTO `tb_guide_step`
  (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT g.`guide_id`, 9, '#btnCols', 'เลือกเองว่าจะดูคอลัมน์ไหน',
       'เดือนที่มีหน่วยงานเบิกสิบกว่าหน่วย ตารางจะกว้างสี่สิบกว่าคอลัมน์ ถ้าเปิดมาดูแค่หน่วยงานตัวเองก็ปิดที่เหลือทิ้งได้ ปิดได้ทั้งรายกลุ่ม (ยกมา ซื้อเข้า ราคา/หน่วย รวมเบิก คงเหลือ) และทีละหน่วยงาน มีปุ่มลัด "เฉพาะหน่วยงาน" ไว้ดูว่าใครเบิกอะไรล้วน ๆ ตัวเลขบนปุ่มบอกว่ากำลังซ่อนอยู่กี่คอลัมน์ จะได้ไม่เผลอคิดว่ารายงานแสดงไม่ครบ สิ่งที่ปิดไว้จะไม่ติดไปในไฟล์ Excel ด้วย',
