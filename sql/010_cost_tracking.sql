-- ============================================================
--  010_cost_tracking.sql
--  เก็บต้นทุนของสต๊อก เพื่อออกรายงานค่าใช้จ่ายส่งฝ่ายบัญชี
--
--  ตอนตั้งระบบตกลงกันว่า "นับแค่จำนวน ไม่คิดมูลค่า" ตารางชุด 008 จึงไม่มี
--  คอลัมน์ราคาเลย ไฟล์นี้เติมเข้าไปทีหลังโดยไม่แตะโครงเดิม
--
--  ---------------------------------------------------------------
--  วิธีคิดต้นทุน: ถัวเฉลี่ยเคลื่อนที่ (moving average)
--  ---------------------------------------------------------------
--  ทุกครั้งที่รับของเข้า ต้นทุนเฉลี่ยจะถูกคำนวณใหม่จากมูลค่ารวมหารจำนวนรวม
--      ต้นทุนเฉลี่ยใหม่ = (มูลค่าคงเหลือเดิม + มูลค่าที่รับเข้า) / (จำนวนเดิม + จำนวนที่รับ)
--  ส่วนตอนจ่ายออก ใช้ต้นทุนเฉลี่ย ณ ขณะนั้น และไม่ทำให้ค่าเฉลี่ยเปลี่ยน
--
--  ตัวอย่างที่ต้องได้ถูก: ปากการับเข้า 10 ด้าม@10 แล้วอีก 10 ด้าม@15
--      หลังรับครั้งที่สอง ต้นทุนเฉลี่ย = (100 + 150) / 20 = 12.50
--      เบิกออก 15 ด้าม -> ค่าใช้จ่าย 15 x 12.50 = 187.50
--      คงเหลือ 5 ด้าม  -> มูลค่า 5 x 12.50 = 62.50
--      รวม 187.50 + 62.50 = 250 = เงินที่จ่ายซื้อจริง  (บัญชีลงตัว)
--
--  ---------------------------------------------------------------
--  ทำไมต้องเก็บต้นทุนไว้ในทุกชั้น ไม่ใช่เก็บแค่ที่สินค้า
--  ---------------------------------------------------------------
--    tb_doc_item.unit_cost       รับเข้า = ราคาที่ซื้อจริงของบรรทัดนั้น
--                                จ่ายออก = ต้นทุนเฉลี่ย ณ วินาทีที่จ่าย (แช่แข็งไว้)
--    tb_stock_movement.*_cost    ราคาที่ใช้จริงตอนนั้น + ค่าเฉลี่ยหลังรายการ
--                                รายงานย้อนหลังจึงได้ตัวเลขเดิมเสมอ ไม่เปลี่ยนตามราคาวันนี้
--    tb_stock_balance.avg_cost   ต้นทุนเฉลี่ยปัจจุบัน ใช้คิดตอนจ่ายออกครั้งถัดไป
--
--  ถ้าเก็บแค่ tb_product.unit_cost แล้วคูณตอนออกรายงาน ตัวเลขเดือนที่แล้ว
--  จะเปลี่ยนไปทุกครั้งที่ซื้อของราคาใหม่ ซึ่งบัญชีรับไม่ได้
--
--  DECIMAL ไม่ใช่ FLOAT ทุกช่อง เพราะเป็นจำนวนเงินที่ต้องบวกแล้วไม่มีเศษหลุด
--  ใช้ทศนิยม 4 ตำแหน่งสำหรับราคาต่อหน่วย (ของถูก ๆ อย่างคลิปหนีบราคาสตางค์)
--  และ 2 ตำแหน่งสำหรับยอดรวมที่จะส่งบัญชี
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hr < sql/010_cost_tracking.sql
-- ============================================================

-- ------------------------------------------------------------
--  1) บรรทัดในเอกสาร — ราคาต่อหน่วยและมูลค่ารวมของบรรทัด
-- ------------------------------------------------------------
ALTER TABLE `tb_doc_item`
  ADD COLUMN `unit_cost` DECIMAL(12,4) NOT NULL DEFAULT 0
      COMMENT 'รับเข้า = ราคาซื้อจริง, จ่ายออก = ต้นทุนเฉลี่ยตอนจ่าย' AFTER `qty_issued`,
  ADD COLUMN `total_cost` DECIMAL(14,2) NOT NULL DEFAULT 0
      COMMENT 'qty x unit_cost — เก็บไว้เลยเพื่อไม่ต้องคูณซ้ำทุกครั้งที่ออกรายงาน' AFTER `unit_cost`;


-- ------------------------------------------------------------
--  2) ยอดคงเหลือ — ต้นทุนเฉลี่ยปัจจุบัน
-- ------------------------------------------------------------
ALTER TABLE `tb_stock_balance`
  ADD COLUMN `avg_cost` DECIMAL(12,4) NOT NULL DEFAULT 0
      COMMENT 'ต้นทุนถัวเฉลี่ยเคลื่อนที่ ณ ปัจจุบัน' AFTER `qty`;


-- ------------------------------------------------------------
--  3) ประวัติความเคลื่อนไหว — ราคาที่ใช้จริงในรายการนั้น
-- ------------------------------------------------------------
ALTER TABLE `tb_stock_movement`
  ADD COLUMN `unit_cost` DECIMAL(12,4) NOT NULL DEFAULT 0
      COMMENT 'ราคาต่อหน่วยที่ใช้กับรายการนี้' AFTER `qty_out`,
  ADD COLUMN `total_cost` DECIMAL(14,2) NOT NULL DEFAULT 0
      COMMENT 'มูลค่าของรายการนี้ (บวกเมื่อเข้า ลบเมื่อออก)' AFTER `unit_cost`,
  ADD COLUMN `avg_cost_after` DECIMAL(12,4) NOT NULL DEFAULT 0
      COMMENT 'ต้นทุนเฉลี่ยหลังรายการนี้ — ไว้ตรวจย้อนว่าเฉลี่ยขยับเพราะอะไร' AFTER `balance_after`;

-- รายงานค่าใช้จ่ายกรองตามช่วงเดือนเสมอ และแยกตามประเภทเข้า/ออก
ALTER TABLE `tb_stock_movement`
  ADD KEY `idx_move_type_date` (`move_type`, `move_date`);


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT `TABLE_NAME`, `COLUMN_NAME`, `COLUMN_TYPE`
FROM `information_schema`.`COLUMNS`
WHERE `TABLE_SCHEMA` = DATABASE()
  AND `COLUMN_NAME` IN ('unit_cost', 'total_cost', 'avg_cost', 'avg_cost_after')
ORDER BY `TABLE_NAME`, `ORDINAL_POSITION`;
