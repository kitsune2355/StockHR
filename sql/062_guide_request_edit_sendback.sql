--  062_guide_request_edit_sendback.sql
--  คู่มือหน้ารายการใบเบิก: เพิ่มขั้นของปุ่ม "แก้ไขใบเบิก" และ "ส่งกลับแก้ไข"
--
--  ที่มา: เพิ่มการแก้ไขใบเบิกที่ยัง "รออนุมัติ" (ผู้ทำเบิก/ผู้ดูแลระบบ) และปุ่ม
--  ให้ผู้อนุมัติถอยใบที่ "อนุมัติแล้ว" กลับไปให้ผู้ทำเบิกแก้ พร้อมเก็บไทม์ไลน์
--  เหตุการณ์ไว้ในกล่องรายละเอียด — คู่มือเดิมยังไม่มีสองไอคอนนี้
--
--  ---------------------------------------------------------------
--  เลขลำดับขั้น (ให้ตรงกับลำดับไอคอนบนหน้าจอ)
--  ---------------------------------------------------------------
--  ผังปุ่มปัจจุบัน: ดู · พิมพ์ · คัดลอกลิงก์ · [เปิดลิงก์] · แก้ไข · อนุมัติ ·
--  ไม่อนุมัติ · ส่งกลับ · ยกเลิก · เมล
--
--  ก่อนรัน (จากไฟล์ 044/045):
--    2 ดู  3 พิมพ์  4 คัดลอกลิงก์  5 อนุมัติ  6 ไม่อนุมัติ  7 ยกเลิก  8 เมล  9 ส่งออกรายบรรทัด
--
--  ไฟล์นี้ทำสองรอบ:
--    รอบ 1 — เปิดช่องที่ 5 แล้วแทรก "แก้ไขใบเบิก"
--    รอบ 2 — เปิดช่องที่ 8 แล้วแทรก "ส่งกลับแก้ไข" (อยู่หลังไม่อนุมัติ ก่อนยกเลิก)
--
--  รันซ้ำจะเลื่อนซ้ำและได้ขั้นซ้ำ จึงลบขั้นเดิมของสอง selector นี้ทิ้งก่อนเสมอ
--
--  หมายเหตุ: 042/044/045 ชี้ขั้นตอนด้วย step_order ตามผังก่อนไฟล์นี้
--  ถ้าจะรันไฟล์เหล่านั้นซ้ำหลังรันไฟล์นี้ ต้องเลื่อนเลขตามด้วย
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hr < sql/062_guide_request_edit_sendback.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/062_guide_request_edit_sendback_rollback.sql
-- ============================================================

SET NAMES utf8;

/* ---------- ลบขั้นเดิมก่อน กันรันซ้ำแล้วได้ขั้นซ้ำ ---------- */
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` IN ('.rowact[data-row-act="edit"]', '.rowact[data-row-act="sendback"]');

/* ==========  รอบ 1 — ปุ่มแก้ไขใบเบิก (ขั้นที่ 5)  ========== */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'request_list'
  AND s.`step_order` >= 5;

INSERT INTO `tb_guide_step`
    (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 5, '.rowact[data-row-act="edit"]', 'ไอคอนดินสอ — แก้ไขใบเบิก',
 'เปิดใบที่ยัง "รออนุมัติ" ขึ้นมาแก้ในหน้าทำรายการเบิก เปลี่ยนรายการ จำนวน หรือหมายเหตุได้ บันทึกแล้วใบจะกลับไปให้ผู้อนุมัติพิจารณาใหม่ และลิงก์อนุมัติที่ส่งไปในอีเมลรอบก่อนจะใช้ไม่ได้ทันที เห็นเฉพาะผู้ทำเบิกเจ้าของใบกับผู้ดูแลระบบ และเฉพาะตอนที่ใบยังไม่ถูกตัดสิน',
 'bottom', 'start', NOW()
FROM `tb_guide` WHERE `page_key` = 'request_list';

/* ==========  รอบ 2 — ปุ่มส่งกลับแก้ไข (ขั้นที่ 8 หลังไม่อนุมัติ ก่อนยกเลิก)  ========== */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'request_list'
  AND s.`step_order` >= 8;

INSERT INTO `tb_guide_step`
    (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 8, '.rowact[data-row-act="sendback"]', 'ไอคอนลูกศรย้อน — ส่งกลับแก้ไข',
 'ใช้ตอนใบผ่านอนุมัติแล้วแต่ผู้ทำเบิกแจ้งว่าเบิกของผิด กดถอยใบกลับไปให้ผู้ทำเบิกแก้ สถานะกลับเป็น "รออนุมัติ" ต้องระบุสิ่งที่ต้องแก้เพื่อให้ผู้ทำเบิกรู้ ส่งกลับใบของตัวเองไม่ได้ และถ้าคลังจ่ายของใบนี้ไปบางส่วนแล้วจะส่งกลับไม่ได้ ต้องยกเลิกใบจ่ายก่อน ไอคอนนี้ขึ้นเฉพาะบนใบที่อนุมัติแล้ว จึงไม่โผล่บนแถวตัวอย่างนี้',
 'bottom', 'start', NOW()
FROM `tb_guide` WHERE `page_key` = 'request_list';

/* ---------- ขั้นดูรายละเอียด: บอกว่ามีไทม์ไลน์เหตุการณ์อยู่ในกล่อง ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'เปิดกล่องสรุปทั้งใบ — หัวเอกสาร รายการที่ขอ จำนวนรวม และปุ่มทำงานตามสถานะ ด้านล่างมี "ประวัติเอกสาร" ไล่เหตุการณ์ทั้งหมดของใบนี้ตั้งแต่ยื่น แก้ไข อนุมัติ ส่งกลับ จนถึงจ่ายของครบ พร้อมชื่อผู้ทำและเวลา'
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[data-row-act="open"]';
