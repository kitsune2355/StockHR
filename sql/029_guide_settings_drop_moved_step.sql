SET NAMES utf8;

DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'settings'
  AND s.`title` = 'คู่มือย้ายไปเมนูของตัวเองแล้ว';
