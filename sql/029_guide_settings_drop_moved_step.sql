--  ขั้นนี้เกิดจากการแยกเมนูใน sql/028 ซึ่งตอนนั้นเก็บไว้เพื่อบอกทางว่า
--  ของที่เคยอยู่ตรงนี้ย้ายไปไหน แต่พอมองอีกที มันไม่ใช่วิธีใช้หน้านี้
--  เป็นแค่ประกาศเรื่องการเปลี่ยนแปลง ซึ่งไม่ควรฝังถาวรอยู่ในคู่มือ
--  เพราะคนที่เพิ่งเข้ามาใช้ทีหลังจะไม่รู้ด้วยซ้ำว่าเคยมีของเก่าอยู่ตรงไหน
--
--  เมนู "คู่มือการใช้งาน" อยู่บนแถบซ้ายให้เห็นอยู่แล้ว จึงไม่ต้องมีขั้นชี้ทางให้
--
--  ลบด้วย target_selector ว่างคู่กับชื่อขั้น ไม่ใช่เลขลำดับ
--  เผื่อมีการแทรกขั้นอื่นเข้ามาระหว่างนี้ จะได้ไม่ลบผิดขั้น
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/029_guide_settings_drop_moved_step.sql
