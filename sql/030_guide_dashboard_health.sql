-- ============================================================
--  030_guide_dashboard_health.sql
--  คู่มือของไทล์ "ความพร้อมของข้อมูล" และการแก้ไทล์ที่อ่านผิดได้
--
--  ---------------------------------------------------------------
--  1) ไทล์ใหม่: ความพร้อมของข้อมูล
--  ---------------------------------------------------------------
--  ไทล์นี้ไม่ได้อยู่ถาวร มันโผล่เฉพาะตอนที่ยังกรอกข้อมูลตั้งต้นไม่ครบ
--  และหายไปเองเมื่อกรอกครบแล้ว คู่มือจึงข้ามขั้นนี้ให้เองในวันที่ไม่มีอะไรค้าง
--  (buildSteps ตัดขั้นที่หาเป้าหมายไม่เจอออกอยู่แล้ว)
--
--  แทรกเป็นขั้นที่ 4 คือหลังทางลัด ก่อนกราฟ เพราะต้องรู้ข้อจำกัดของข้อมูล
--  ก่อนที่จะไปอ่านตัวเลขในกราฟและไทล์เงิน
--
--  ---------------------------------------------------------------
--  2) แก้ข้อความขั้น "ต้องสั่งเพิ่ม"
--  ---------------------------------------------------------------
--  ของเดิมเตือนว่าเลข 0 อาจแปลว่ายังไม่ได้ตั้งจุดสั่งซื้อ ซึ่งถูก
--  แต่ตอนนี้ไทล์บอกสัดส่วนความครอบคลุมให้เห็นบนหน้าจอแล้ว
--  คู่มือจึงควรสอนวิธีอ่านบรรทัดนั้น แทนที่จะเตือนเรื่องที่หน้าจอบอกอยู่แล้ว
--
--  ---------------------------------------------------------------
--  3) แก้ข้อความขั้น "เงินของเดือน"
--  ---------------------------------------------------------------
--  เพิ่มเรื่องบรรทัดหมายเหตุใต้ไทล์ ที่บอกว่ายอดคิดจากสินค้ากี่รายการ
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/030_guide_dashboard_health.sql
--
--  ไฟล์นี้ลบขั้นของตัวเองก่อนใส่ใหม่ รันซ้ำได้ปลอดภัย
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/030_guide_dashboard_health_rollback.sql
-- ============================================================

SET NAMES utf8;


-- ============================================================
--  1) ขั้นใหม่ของไทล์ความพร้อมของข้อมูล
-- ============================================================

-- ลบของเดิมก่อน (ถ้าเคยรันมาแล้ว) แล้วดันลำดับกลับ เพื่อให้รันซ้ำได้
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'dashboard' AND s.`target_selector` = '#bnHealth';

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'dashboard' AND s.`step_order` >= 4;

INSERT INTO `tb_guide_step` (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 4, '#bnHealth', 'ความพร้อมของข้อมูล',
 'ไทล์นี้โผล่เฉพาะตอนที่ทะเบียนสินค้ายังกรอกไม่ครบ และหายไปเองเมื่อกรอกครบแล้ว มีไว้เพราะค่าที่ขาดไปไม่ได้ทำให้ระบบพัง แต่ทำให้ตัวเลขในไทล์อื่นเงียบ ๆ ผิดไปจากความจริง สินค้าที่ไม่ได้ตั้งราคาจะถูกคิดเป็นศูนย์ในทุกยอดเงิน ส่วนสินค้าที่ไม่ได้ตั้งจุดสั่งซื้อจะไม่มีวันขึ้นเตือนว่าใกล้หมด แม้ของจะหมดจริงก็ตาม แต่ละบรรทัดบอกทั้งจำนวนที่ยังขาดและผลที่ตามมา พร้อมปุ่มไปยังหน้าที่ใช้แก้ ไม่ต้องแก้ทีเดียวหมดก็ได้ เปอร์เซ็นต์ด้านบนจะขยับขึ้นทุกครั้งที่กรอกเพิ่ม',
 'top', 'center', NOW() FROM `tb_guide` WHERE `page_key`='dashboard';


-- ============================================================
--  2) ปรับข้อความขั้น "ต้องสั่งเพิ่ม"
-- ============================================================

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'รายการที่ยอดคงเหลือถึงหรือต่ำกว่าจุดสั่งซื้อที่ตั้งไว้ในทะเบียนสินค้า สิ่งที่ต้องดูคู่กันเสมอคือบรรทัดเล็กใต้ตัวเลข ซึ่งบอกว่าตัวเลขนี้นับมาจากฐานกว้างแค่ไหน ถ้าขึ้นว่า "นับจากที่ตั้งจุดสั่งซื้อแล้ว 1/313 รายการ" แปลว่าเลขที่เห็นครอบคลุมสินค้าแค่รายการเดียว อีก 312 รายการต่อให้ของหมดก็ไม่ถูกนับ กรณีแบบนี้เลข 0 ไม่ได้แปลว่าของครบ แต่แปลว่ายังไม่ได้ตั้งค่า ไทล์จะเป็นสีส้มเตือนไว้ให้ด้วย',
 s.`title` = 'ต้องสั่งเพิ่ม — ดูฐานที่ใช้นับด้วย'
WHERE g.`page_key` = 'dashboard' AND s.`target_selector` = '#bnLows';


-- ============================================================
--  3) ปรับข้อความขั้น "เงินของเดือน"
-- ============================================================

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'สองตัวเลขนี้คนละเรื่องกัน — "ซื้อเข้า" คือเงินที่จ่ายไปกับของที่รับเข้าคลังเดือนนี้ ส่วน "เบิกไปใช้" คือมูลค่าของที่หน่วยงานเบิกออกไปใช้ ไม่จำเป็นต้องเท่ากัน เพราะของที่ซื้อเดือนนี้อาจถูกเบิกเดือนหน้า ทั้งคู่คิดจากราคาที่ตั้งไว้ในทะเบียนสินค้า ถ้ามีบรรทัดหมายเหตุอยู่ท้ายไทล์ ให้อ่านด้วยเสมอ เพราะมันบอกว่ายอดพวกนี้คิดจากสินค้ากี่รายการจากทั้งหมด สินค้าที่ยังไม่ได้ตั้งราคาถูกนับเป็นศูนย์ ยอดจริงจึงสูงกว่าที่เห็น กดที่ไทล์เพื่อไปดูรายละเอียดแยกตามบริษัทและหน่วยงานได้'
WHERE g.`page_key` = 'dashboard' AND s.`target_selector` = '#bnMoney';
