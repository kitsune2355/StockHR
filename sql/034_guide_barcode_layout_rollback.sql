SET NAMES utf8;

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ทั้งสองแบบเก็บรหัสสินค้าตัวเดียวกันเป๊ะ ต่างกันแค่ใครอ่านได้ บาร์โค้ดใช้กับเครื่องยิงที่เสียบกับคอมพิวเตอร์ ซึ่งเป็นวิธีที่เร็วที่สุดตอนรับเข้าหรือจ่ายของทีละหลายรายการ ส่วน QR ส่องด้วยกล้องมือถือธรรมดาได้ เหมาะกับคนที่ไม่มีเครื่องยิงติดตัว เช่นตอนไปนับของที่ชั้นวางหรือหน้างานนอกห้องคลัง ข้อควรรู้: เครื่องยิงเลเซอร์แบบเส้นตรงส่วนใหญ่อ่าน QR ไม่ได้ ต้องเป็นรุ่นที่เป็นกล้อง (2D imager) เท่านั้น ถ้าไม่แน่ใจว่าเครื่องที่มีอยู่เป็นแบบไหน ให้ลองยิงดูจากตัวอย่างบนหน้าจอนี้ได้เลย'
WHERE g.`page_key` = 'product_barcode' AND s.`target_selector` = '#bcType';

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ฉลากที่เห็นตรงนี้คือฉลากจริงที่จะออกมาบนกระดาษ ขนาดเท่าของจริงทุกมิลลิเมตร เส้นประรอบดวงเป็นแค่รอยตัดสมมติให้ดูว่าเนื้อหาชิดขอบเกินไปหรือเปล่า ไม่ถูกพิมพ์ลงกระดาษจริง ถ้าชื่อสินค้ายาวเกินดวง ระบบจะตัดเหลือสองบรรทัดแล้วเติมจุดไข่ปลาให้ ส่วนบาร์โค้ดกับรหัสจะไม่ถูกย่อไม่ว่ากรณีใด ตอนนี้คู่มือเลือกสินค้าตัวอย่างให้ดูสี่รายการ พอปิดคู่มือจะกลับไปเป็นรายการที่คุณเลือกไว้เดิม'
WHERE g.`page_key` = 'product_barcode' AND s.`target_selector` = '#bcSheet';
