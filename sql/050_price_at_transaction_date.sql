--  เลิกคิดต้นทุนแบบถัวเฉลี่ยเคลื่อนที่ เปลี่ยนเป็น "ราคา ณ วันทำรายการ"
--  (เฉพาะส่วนที่ไม่ลบข้อมูล — การถอดคอลัมน์ทิ้งอยู่ในไฟล์ 051)
--
--  ---------------------------------------------------------------
--  ทำไมถึงเลิก
--  ---------------------------------------------------------------
--  ของตัวเดียวกันที่ซื้อมาคนละราคาถูกเกลี่ยเป็นราคากลางที่ไม่ตรงกับใบเสร็จ
--  ใบไหนเลย เช่นมีของเดิม 7 ขวดที่ซื้อมาขวดละ 300 แล้วซื้อเพิ่ม 1 ขวดที่ 100
--  ตอนเบิกออกระบบจะตัดที่ 275 ซึ่งเป็นตัวเลขที่อธิบายกับคนอ่านรายงานไม่ได้
--  ว่ามาจากไหน ทั้งที่ไม่เคยซื้อของราคานี้สักครั้ง
--
--  กติกาใหม่: ทุกรายการใช้ราคาที่รู้ ณ วินาทีที่ทำรายการ แล้วแช่แข็งลงประวัติ
--    รับเข้า          ราคาที่ซื้อจริงของครั้งนั้น (คนกรอกเป็นคนบอก)
--    เบิกออก          ราคาซื้อล่าสุดของสินค้าตัวนั้น ณ วินาทีที่ตัดสต๊อก
--    ยกเลิกทั้งสองแบบ  ราคาของใบเดิม เพื่อถอนออกเท่าที่ใส่เข้าไป
--
--  รายงานยังอ่านจาก tb_stock_movement.total_cost เหมือนเดิมทุกตัว
--  เดือนที่ปิดไปแล้วจึงยังนิ่ง เปิดดูกี่ครั้งก็ได้ตัวเลขเดิม
--
--  ไฟล์นี้ไม่ลบอะไรทั้งสิ้น แค่แก้คำอธิบายที่ยังบอกผู้ใช้ผิด
--  ตัวโค้ดทำงานได้ทันทีโดยไม่ต้องรันไฟล์นี้ (คอลัมน์ค่าเฉลี่ยแค่ไม่ถูกแตะอีก)
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/050_price_at_transaction_date.sql
