SET NAMES utf8;

-- ------------------------------------------------------------
--  1) คำอธิบายคอลัมน์ให้ตรงกับความหมายใหม่
-- ------------------------------------------------------------
ALTER TABLE `tb_stock_movement`
  MODIFY COLUMN `unit_cost` DECIMAL(12,4) NOT NULL DEFAULT 0
    COMMENT 'ราคาต่อหน่วยที่ใช้กับรายการนี้ — แช่แข็ง ณ วันทำรายการ ไม่ใช่ค่าเฉลี่ย';


-- ------------------------------------------------------------
--  2) คู่มือที่ยังบอกผู้ใช้ว่าระบบคิดแบบถัวเฉลี่ย
-- ------------------------------------------------------------
UPDATE `tb_guide_step` s
  JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'เลือกสินค้าแล้วช่องราคาจะเติมราคาซื้อล่าสุดให้เอง รอบนี้ซื้อได้ราคาอื่นก็แก้ทับได้ ราคาที่กรอกตรงนี้คือราคาที่ระบบใช้คิดมูลค่าของใบนี้ และจะถูกจำไว้เป็นราคาซื้อล่าสุดของสินค้าตัวนั้นต่อไปด้วย ควรกรอกให้ครบทุกบรรทัด ไม่งั้นรายงานค่าใช้จ่ายจะขึ้นศูนย์'
WHERE g.`page_key` = 'receive_new'
  AND s.`description` LIKE '%ถัวเฉลี่ย%';

UPDATE `tb_guide_step` s
  JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'เปิดหน้ากระดาษในแท็บใหม่ ตัดเมนูและปุ่มออกหมด เหลือแต่ตัวเอกสารพร้อมโลโก้บริษัทของหน่วยงานนั้น มีช่องเซ็นผู้ขอเบิกและผู้อนุมัติให้ครบ ราคาบนใบเบิกเป็นราคาประมาณการจากราคาซื้อล่าสุด ไม่ใช่ยอดที่ลงบัญชี ตัวเลขจริงยืนยันอีกครั้งตอนจ่ายของ'
WHERE g.`page_key` = 'request_list'
  AND s.`description` LIKE '%ต้นทุนเฉลี่ย%';


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์ — ต้องไม่เหลือคู่มือที่พูดถึงค่าเฉลี่ย
-- ------------------------------------------------------------
SELECT COUNT(*) AS `คู่มือที่ยังพูดถึงค่าเฉลี่ย`
FROM `tb_guide_step`
WHERE `description` LIKE '%ถัวเฉลี่ย%' OR `description` LIKE '%ต้นทุนเฉลี่ย%';
