-- ---------- ภาพรวม ----------
SELECT 'เอกสารที่จะถูกลบ (ทุกประเภท)' AS `what`, COUNT(*) AS `n` FROM `tb_doc_header`
UNION ALL SELECT 'เอกสารล่าสุดสร้างเมื่อ', MAX(`created_at`) FROM `tb_doc_header`
UNION ALL SELECT 'ประวัติสต๊อกที่จะถูกลบ', COUNT(*) FROM `tb_stock_movement`
UNION ALL SELECT 'สินค้าในฐานตอนนี้', COUNT(*) FROM `tb_product`;
SELECT 'สินค้าที่จะอัปเดต (รหัสตรงกับ Excel)', COUNT(*) FROM `tb_product` WHERE `product_code` IN (SELECT `code` FROM `tmp_import`);
SELECT 'สินค้าที่จะลบ (ไม่อยู่ใน Excel)', COUNT(*) FROM `tb_product` WHERE `product_code` NOT IN (SELECT `code` FROM `tmp_import`);
SELECT 'สินค้าที่จะเพิ่มใหม่', COUNT(*) FROM `tmp_import` t WHERE NOT EXISTS (SELECT 1 FROM `tb_product` p WHERE p.`product_code` = t.`code`);

-- ---------- เอกสารที่จะถูกลบ แยกประเภท/สถานะ ----------
SELECT `doc_type`, `status`, COUNT(*) AS `n`, MIN(`doc_date`) AS `date_from`, MAX(`doc_date`) AS `date_to`
FROM `tb_doc_header` GROUP BY `doc_type`, `status` ORDER BY `doc_type`, `status`;

-- ---------- สินค้าที่จะถูกลบ (ถ้ามี ให้ตรวจว่าไม่ต้องใช้แล้วจริง) ----------
SELECT p.`product_code`, p.`product_name`, COALESCE(b.`qty`, 0) AS `qty_now`
FROM `tb_product` p LEFT JOIN `tb_stock_balance` b ON b.`product_id` = p.`product_id`
WHERE p.`product_code` NOT IN (SELECT `code` FROM `tmp_import`)
ORDER BY p.`product_code`;

-- ---------- หมวดย่อยที่จะเพิ่มใหม่ ----------
SELECT DISTINCT t.`cat` AS `category`, t.`sub` AS `new_sub_category`
FROM `tmp_import` t
WHERE NOT EXISTS (SELECT 1 FROM `tb_sub_category` s WHERE s.`sub_category_name` = t.`sub`);

