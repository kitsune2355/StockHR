--  เปลี่ยนอะไร
--  ------------------------------------------------------------
--    เดิม : super_admin, employer, admin, general
--    ใหม่ : super_admin, admin, approver, general
--
--    + approver  "ผู้อนุมัติ"  สิทธิ์ใหม่
--    - employer  "ผู้ว่าจ้าง"  ตัดออก ไม่ได้ใช้แล้ว
--
--  ตรวจก่อนรันแล้วว่าไม่มีผู้ใช้คนไหนถือสิทธิ์ employer อยู่ (0 แถว)
--  แต่ยังใส่คำสั่งย้ายไป general ไว้กันไว้ก่อน เผื่อรันบนฐานข้อมูลอื่น
--  ที่มีข้อมูลไม่เหมือนกัน ถ้าไม่ย้ายก่อน แถวเหล่านั้นจะกลายเป็นค่าว่าง
--  ทันทีที่ ALTER เพราะ MySQL 5.0 ไม่ได้เปิด strict mode
--
--  ------------------------------------------------------------
--  ข้อกำหนดเพิ่มเติมที่บังคับในโค้ด ไม่ใช่ในฐานข้อมูล
--  ------------------------------------------------------------
--    สิทธิ์ super_admin สงวนไว้ให้ชื่อผู้ใช้ 'admin' เท่านั้น
--    บังคับที่ backend/user.php (ค่าคงที่ SUPER_ADMIN_USERNAME)
--    ไม่ได้บังคับด้วย CHECK constraint เพราะ MySQL 5.0 ยังไม่รองรับ
--    (ประกาศได้แต่ไม่ทำงานจริง ซึ่งอันตรายกว่าไม่ประกาศเลย)
-- ============================================================


-- ------------------------------------------------------------
--  ขั้นที่ 1 : ย้ายคนที่ยังถือสิทธิ์ employer ไปเป็น general
-- ------------------------------------------------------------
UPDATE `tb_user` SET `role` = 'general' WHERE `role` = 'employer';


-- ------------------------------------------------------------
--  ขั้นที่ 2 : เปลี่ยนชุดค่าของคอลัมน์
-- ------------------------------------------------------------
ALTER TABLE `tb_user`
  MODIFY COLUMN `role` ENUM('super_admin','admin','approver','general')
  NOT NULL DEFAULT 'general'
  COMMENT 'ระดับสิทธิ์ — super_admin สงวนให้ username admin เท่านั้น';


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT `COLUMN_TYPE` AS `ชุดสิทธิ์ใหม่`
FROM `information_schema`.`COLUMNS`
WHERE `TABLE_SCHEMA` = DATABASE()
  AND `TABLE_NAME`   = 'tb_user'
  AND `COLUMN_NAME`  = 'role';

SELECT `role` AS `สิทธิ์`, COUNT(*) AS `จำนวนคน`
FROM `tb_user`
GROUP BY `role`;
