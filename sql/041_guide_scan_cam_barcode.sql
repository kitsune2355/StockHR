--
--  ของเดิม (036) เขียนไว้ว่า "กล้องอ่านได้เฉพาะ QR ไม่ใช่บาร์โค้ด"
--  ซึ่งจริงตอนที่เขียน เพราะตัวถอดรหัสสำรองตอนนั้นคือ jsQR ที่อ่าน QR
--  ได้อย่างเดียว
--
--  ตอนนี้กล้องอ่านบาร์โค้ดแท่งได้แล้วทุกเครื่อง:
--    เครื่องที่มี BarcodeDetector ในตัว (Android เป็นหลัก) เปิดรูปแบบ
--    เพิ่มให้ครบ ส่วนเครื่องที่ไม่มี (iPhone) เปลี่ยนตัวสำรองเป็น ZXing
--    ซึ่งอ่านได้ทั้ง QR และ Code 128 ที่ระบบใช้พิมพ์ฉลาก
--    (ดู assets/js/qr-cam.js)
--
--  ข้อความในคู่มือที่บอกข้อจำกัดที่ไม่มีอยู่จริงแล้ว อันตรายกว่าไม่บอกอะไรเลย
--  เพราะคนอ่านจะไม่ลองใช้ความสามารถที่มีอยู่ ทั้งที่ฉลากทุกใบมีบาร์โค้ดอยู่
--
--  ข้อจำกัดเรื่อง http ยังคงอยู่ ไม่ได้แก้ตรงนั้น
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hr < sql/041_guide_scan_cam_barcode.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/041_guide_scan_cam_barcode_rollback.sql
