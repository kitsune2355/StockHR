SET NAMES utf8;

/* ---------- บันทึกรับเข้า ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'กดปุ่มนี้เพื่อเปิดกล้องของเครื่องแล้วส่องฉลากแทนการยิง เหมาะกับตอนเปิดหน้านี้จากมือถือขณะยืนอยู่ที่กองของ ส่องได้ทั้งบาร์โค้ดแท่งและ QR บนฉลากใบเดียวกัน ไม่ต้องเลือกโหมด ไม่ต้องกดถ่าย เล็งให้รหัสอยู่ในกรอบแล้วระบบอ่านเอง ส่องติดแล้วจะเพิ่มบรรทัดให้เหมือนการยิงทุกอย่าง แล้วปิดกล้องให้เองหลังจากโชว์ผลให้อ่านครู่หนึ่ง ถ้าส่องผิดตัวหรือไม่พบรหัส กล้องจะเปิดค้างไว้ให้เล็งตัวใหม่ต่อได้เลย ข้อควรรู้: เบราว์เซอร์จะไม่ยอมเปิดกล้องถ้าระบบยังเข้าผ่าน http ธรรมดา ถ้ากดแล้วขึ้นข้อความสีแดงเรื่องนี้ ให้แจ้งผู้ดูแลระบบ ไม่ใช่ความผิดพลาดของโปรแกรม'
WHERE g.`page_key` = 'receive_new'
  AND s.`target_selector` = '#btnScanCam';

/* ---------- ทำรายการเบิก ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'กดปุ่มนี้เพื่อเปิดกล้องของเครื่องแล้วส่องฉลากแทนการยิง เหมาะกับตอนยืนอยู่หน้าชั้นวางแล้วเปิดหน้านี้จากมือถือ ส่องได้ทั้งบาร์โค้ดแท่งและ QR บนฉลากใบเดียวกัน ไม่ต้องเลือกโหมด ไม่ต้องกดถ่าย เล็งให้รหัสอยู่ในกรอบแล้วระบบอ่านเอง ส่องติดแล้วสินค้าจะไปอยู่ฝั่งขวาเหมือนการยิงทุกอย่าง แล้วปิดกล้องให้เองหลังจากโชว์ผลให้อ่านครู่หนึ่ง ถ้าส่องแล้วไม่พบ กล้องจะเปิดค้างไว้ให้เล็งตัวใหม่ต่อ อย่าลืมว่าต้องเลือกหน่วยงานก่อน เพราะสินค้าที่หน่วยงานนั้นไม่มีสิทธิ์เบิกจะส่องไม่ติด ข้อควรรู้: เบราว์เซอร์จะไม่ยอมเปิดกล้องถ้าระบบยังเข้าผ่าน http ธรรมดา'
WHERE g.`page_key` = 'request_new'
  AND s.`target_selector` = '#btnScanCam';

/* ---------- บันทึกจ่ายออก ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'กดปุ่มนี้เพื่อเปิดกล้องของเครื่องแล้วส่องฉลากแทนการยิง เหมาะกับตอนเดินหยิบของอยู่ในคลังแล้วถือมือถือไปด้วย ส่องได้ทั้งบาร์โค้ดแท่งและ QR บนฉลากใบเดียวกัน ไม่ต้องเลือกโหมด ไม่ต้องกดถ่าย เล็งให้รหัสอยู่ในกรอบแล้วระบบอ่านเอง ส่องติดแล้วจะนับจำนวนที่หยิบให้เหมือนการยิงทุกอย่าง แล้วปิดกล้องให้เองหลังจากโชว์ผลให้อ่านครู่หนึ่ง แต่ถ้าส่องแล้วเจอของที่ไม่มีในใบเบิก หรือหยิบครบตามจำนวนที่ขอแล้ว กล้องจะเปิดค้างไว้พร้อมข้อความเตือน เพราะเป็นจังหวะที่ต้องเล็งตัวใหม่ต่อทันที ข้อควรรู้: เบราว์เซอร์จะไม่ยอมเปิดกล้องถ้าระบบยังเข้าผ่าน http ธรรมดา'
WHERE g.`page_key` = 'issue_new'
  AND s.`target_selector` = '#btnScanCam';
