--  ขั้นที่สั้นและตรงอยู่แล้วไม่แตะ ไฟล์นี้จึงมีเฉพาะขั้นที่ยาวเกินความจำเป็น
--
--  ของแถมที่แก้ไปด้วยเพราะข้อความเดิมไม่ตรงกับระบบแล้ว
--  --------------------------------------------------------------
--    - ขั้นปุ่มกล้องทั้งสามหน้า เดิมบอกว่า "อ่านได้เฉพาะ QR ไม่ใช่บาร์โค้ด"
--      ซึ่งไม่จริงแล้วตั้งแต่เปลี่ยนตัวถอดรหัสเป็น ZXing (ไฟล์นี้ทับ 041)
--    - เลข "313 รายการ" ที่ยกมาเป็นตัวอย่าง ตอนนี้มี 335 รายการแล้ว
--      เปลี่ยนเป็นคำกลาง ๆ จะได้ไม่ต้องตามแก้ทุกครั้งที่สินค้าเพิ่ม
--
--  ข้อควรระวัง: ไฟล์นี้ชี้ขั้นตอนด้วย page_key + step_order ตามที่เป็นอยู่ตอนเขียน
--  ถ้าไปรัน 036 ซ้ำ (ซึ่งเลื่อน step_order ของขั้นหลัง ๆ ขึ้นทีละหนึ่ง) ต้องตรวจใหม่
--  ก่อนรันไฟล์นี้ ไม่งั้นข้อความจะไปลงผิดขั้น
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
