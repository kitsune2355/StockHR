--  --------------------------------------------------------------
--    เก็บ  สิ่งที่ผู้ใช้เดาจากหน้าจอเองไม่ได้ + ผลที่ตามมาถ้าทำผิด
--    ตัด   คำอธิบายเหตุผลเชิงออกแบบ ตัวอย่างซ้ำ และการบรรยายสิ่งที่เห็นอยู่แล้ว
