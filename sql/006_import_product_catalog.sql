-- ---------- ตรวจผลลัพธ์ ----------
SELECT 'tb_unit' AS `ตาราง`, COUNT(*) AS `จำนวนแถว` FROM `tb_unit`
UNION ALL SELECT 'tb_category',     COUNT(*) FROM `tb_category`
UNION ALL SELECT 'tb_sub_category', COUNT(*) FROM `tb_sub_category`
UNION ALL SELECT 'tb_product',      COUNT(*) FROM `tb_product`;

SELECT c.`category_name` AS `หมวดหลัก`, s.`sub_category_code` AS `รหัส`,
       s.`sub_category_name` AS `หมวดย่อย`, COUNT(*) AS `จำนวนรายการ`
FROM `tb_product` p
JOIN `tb_sub_category` s ON s.`sub_category_id` = p.`sub_category_id`
JOIN `tb_category`     c ON c.`category_id`     = s.`category_id`
GROUP BY c.`category_id`, s.`sub_category_id`
ORDER BY c.`category_id`, s.`sub_category_id`;
