--  คืนข้อความคู่มือของปุ่มเปิดกล้องกลับเป็นฉบับของ 036
--
--  ใช้เมื่อย้อนโค้ดฝั่งหน้าจอกลับไปใช้ jsQR ด้วย ไม่ใช่ย้อนแค่ข้อความ
--  เพราะข้อความชุดนี้บอกว่า "อ่านได้เฉพาะ QR" ซึ่งจะผิดทันที
--  ถ้าโค้ดยังเป็นฉบับที่อ่านบาร์โค้ดได้
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hr < sql/041_guide_scan_cam_barcode_rollback.sql
-- ============================================================

SET NAMES utf8;

/* ---------- บันทึกรับเข้า ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'กดปุ่มนี้เพื่อเปิดกล้องของเครื่องแล้วส่อง QR ที่ฉลากแทนการยิง เหมาะกับตอนเปิดหน้านี้จากมือถือขณะยืนอยู่ที่กองของ ไม่ต้องกดถ่าย เล็งให้ QR อยู่ในกรอบแล้วระบบอ่านเอง ส่องติดแล้วจะเพิ่มบรรทัดให้เหมือนการยิงทุกอย่าง แล้วปิดกล้องให้เองหลังจากโชว์ผลให้อ่านครู่หนึ่ง ถ้าส่องผิดตัวหรือไม่พบรหัส กล้องจะเปิดค้างไว้ให้เล็งตัวใหม่ต่อได้เลย ข้อจำกัดสองข้อที่ต้องรู้: กล้องอ่านได้เฉพาะ QR ไม่ใช่บาร์โค้ด และเบราว์เซอร์จะไม่ยอมเปิดกล้องถ้าระบบยังเข้าผ่าน http ธรรมดา ถ้ากดแล้วขึ้นข้อความสีแดงเรื่องนี้ ให้แจ้งผู้ดูแลระบบ ไม่ใช่ความผิดพลาดของโปรแกรม'
WHERE g.`page_key` = 'receive_new'
  AND s.`target_selector` = '#btnScanCam';

/* ---------- ทำรายการเบิก ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'กดปุ่มนี้เพื่อเปิดกล้องของเครื่องแล้วส่อง QR ที่ฉลากแทนการยิง เหมาะกับตอนยืนอยู่หน้าชั้นวางแล้วเปิดหน้านี้จากมือถือ ไม่ต้องกดถ่าย เล็งให้ QR อยู่ในกรอบแล้วระบบอ่านเอง ส่องติดแล้วสินค้าจะไปอยู่ฝั่งขวาเหมือนการยิงทุกอย่าง แล้วปิดกล้องให้เองหลังจากโชว์ผลให้อ่านครู่หนึ่ง ถ้าส่องแล้วไม่พบ กล้องจะเปิดค้างไว้ให้เล็งตัวใหม่ต่อ อย่าลืมว่าต้องเลือกหน่วยงานก่อน เพราะสินค้าที่หน่วยงานนั้นไม่มีสิทธิ์เบิกจะส่องไม่ติด ข้อจำกัดสองข้อ: กล้องอ่านได้เฉพาะ QR ไม่ใช่บาร์โค้ด และเบราว์เซอร์จะไม่ยอมเปิดกล้องถ้าระบบยังเข้าผ่าน http ธรรมดา'
WHERE g.`page_key` = 'request_new'
  AND s.`target_selector` = '#btnScanCam';

/* ---------- บันทึกจ่ายออก ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'กดปุ่มนี้เพื่อเปิดกล้องของเครื่องแล้วส่อง QR ที่ฉลากแทนการยิง เหมาะกับตอนเดินหยิบของอยู่ในคลังแล้วถือมือถือไปด้วย ไม่ต้องกดถ่าย เล็งให้ QR อยู่ในกรอบแล้วระบบอ่านเอง ส่องติดแล้วจะนับจำนวนที่หยิบให้เหมือนการยิงทุกอย่าง แล้วปิดกล้องให้เองหลังจากโชว์ผลให้อ่านครู่หนึ่ง แต่ถ้าส่องแล้วเจอของที่ไม่มีในใบเบิก หรือหยิบครบตามจำนวนที่ขอแล้ว กล้องจะเปิดค้างไว้พร้อมข้อความเตือน เพราะเป็นจังหวะที่ต้องเล็งตัวใหม่ต่อทันที ข้อจำกัดสองข้อ: กล้องอ่านได้เฉพาะ QR ไม่ใช่บาร์โค้ด และเบราว์เซอร์จะไม่ยอมเปิดกล้องถ้าระบบยังเข้าผ่าน http ธรรมดา'
WHERE g.`page_key` = 'issue_new'
  AND s.`target_selector` = '#btnScanCam';
