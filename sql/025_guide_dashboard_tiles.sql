--  ทั้งสามใบมีเฉพาะสิทธิ์ที่เห็นภาพรวมคลัง (และไทล์เงินจำกัดแคบกว่านั้นอีกชั้น)
--  คู่มือจะข้ามขั้นที่ไทล์ไม่มีอยู่ให้เองอยู่แล้ว จึงใส่ได้โดยไม่กระทบผู้ใช้ทั่วไป
--
--  แทรกไว้หลังกราฟ ก่อนไอคอนบนแถบบน ตามลำดับที่ตาไล่อ่านหน้าจริง
