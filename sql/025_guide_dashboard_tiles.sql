SET NAMES utf8;

-- เปิดช่องว่างสามขั้นถัดจากขั้นที่ 6 (ตัวเลือกความละเอียดของกราฟ)
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 3
WHERE g.`page_key` = 'dashboard' AND s.`step_order` >= 7;

INSERT INTO `tb_guide_step` (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 7, '#bnMoney', 'เงินของเดือนนี้',
 'สองตัวเลขนี้คนละเรื่องกัน — "ซื้อเข้า" คือเงินที่จ่ายไปกับของที่รับเข้าคลังเดือนนี้ ส่วน "เบิกไปใช้" คือมูลค่าของที่หน่วยงานเบิกออกไปใช้ ไม่จำเป็นต้องเท่ากัน เพราะของที่ซื้อเดือนนี้อาจถูกเบิกเดือนหน้า ทั้งคู่คิดจากราคาที่กรอกไว้ตอนรับเข้าจริง ใบที่ไม่ได้กรอกราคาจะถูกนับเป็นศูนย์ กดที่ไทล์เพื่อไปดูรายละเอียดแยกตามบริษัทและหน่วยงานได้',
 'top', 'center', NOW() FROM `tb_guide` WHERE `page_key`='dashboard';

