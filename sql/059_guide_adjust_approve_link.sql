-- ============================================================
--  059_guide_adjust_approve_link.sql
--  ปรับคู่มือหน้า "ประวัติการปรับยอด" ให้พูดถึงปุ่มลิงก์อนุมัติ
--  (คัดลอกลิงก์ / เปิดลิงก์) ที่เพิ่งเพิ่มในคอลัมน์จัดการ
--
--  ปุ่มพวกนี้อยู่บนแถวใบที่ "รออนุมัติ" — ผู้ดูแลระบบใช้ส่งลิงก์ให้ผู้อนุมัติ
--  ทางไลน์/แชต หรือเปิดหน้าอนุมัติเองได้เลยโดยไม่ต้องรออีเมล
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hl < sql/059_guide_adjust_approve_link.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/059_guide_adjust_approve_link_rollback.sql
-- ============================================================

SET NAMES utf8;

UPDATE `tb_guide_step`
SET `title`       = 'ปุ่มบนแต่ละแถว',
    `description` = 'บนแถวใบที่ "รออนุมัติ" ผู้ดูแลระบบจะเห็นไอคอน "คัดลอกลิงก์อนุมัติ" กับ "เปิดลิงก์อนุมัติ" ไว้ส่งลิงก์ให้ผู้อนุมัติทางไลน์/แชต หรือเปิดหน้าอนุมัติเองได้เลยโดยไม่ต้องรออีเมล (ต้องตั้งผู้อนุมัติที่หน้า "ตั้งค่าอนุมัติ" ก่อน) ส่วนกด "ดูรายละเอียด" จะเห็นยอดเดิม/นับได้จริง/ส่วนต่างทุกบรรทัด และปุ่ม อนุมัติ / ไม่อนุมัติ (เฉพาะผู้อนุมัติ ห้ามอนุมัติใบที่ตัวเองสร้าง) / ยกเลิก (ผู้ดูแลระบบ) / พิมพ์เอกสาร / ส่งอีเมลซ้ำ'
WHERE `step_order` = 4
  AND `guide_id` = (SELECT `guide_id` FROM `tb_guide` WHERE `page_key` = 'adjust_history');


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT s.`step_order`, s.`target_selector`, s.`title`
FROM `tb_guide_step` s
JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'adjust_history'
ORDER BY s.`step_order`;
