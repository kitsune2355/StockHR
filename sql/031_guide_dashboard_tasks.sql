SET NAMES utf8;

-- ---------- ขั้นที่ 1: ไทล์ใหญ่ ไม่มีรายการเอกสารอยู่ในนั้นแล้ว ----------
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'ตัวเลขใหญ่คือจำนวนเอกสารที่รอ "คุณ" ทำอะไรสักอย่าง ไม่ใช่จำนวนงานทั้งระบบ ถ้าเป็นศูนย์แปลว่าไม่มีอะไรค้างอยู่ที่คุณ บรรทัดใต้ตัวเลขแยกให้ว่าเป็นงานประเภทไหนบ้าง เช่นรออนุมัติกี่ใบ รอเซ็นรับของกี่ใบ ส่วนตัวเลขแถบล่างสุดของไทล์เป็นภาพรวมที่ควรรู้ไว้ แต่ยังไม่ใช่งานที่ต้องทำวันนี้'
WHERE g.`page_key` = 'dashboard' AND s.`target_selector` = '#bnHero';


-- ---------- ขั้นใหม่: กล่องรายการงานที่รออยู่ ----------
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'dashboard' AND s.`target_selector` = '#bnTasks';

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'dashboard' AND s.`step_order` >= 2;

INSERT INTO `tb_guide_step` (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 2, '#bnTasks', 'รายการงานที่รออยู่',
 'กล่องนี้บอกว่างานที่ค้างอยู่คือใบไหนบ้าง ต่างจากไทล์เขียวข้าง ๆ ที่บอกแค่จำนวน กดที่บรรทัดไหนก็ได้เพื่อกระโดดไปที่เอกสารใบนั้นทันที ไม่ต้องไปไล่หาในหน้าประวัติเอง แสดงได้สูงสุดห้าใบเรียงตามความเร่งด่วน คืองานที่มีคนอื่นรออยู่มาก่อน ถ้ามีมากกว่านั้นให้กดดูใบเบิกทั้งหมดที่มุมขวาบนของกล่อง',
 'left', 'start', NOW() FROM `tb_guide` WHERE `page_key`='dashboard';
