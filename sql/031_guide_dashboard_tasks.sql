--  "กดที่รายการด้านล่าง" ซึ่งตอนนี้ชี้ผิดที่ เพราะรายการย้ายไปอยู่กล่องขวามือ
--
--  แยกเป็นสองขั้นตามที่ตอบคนละคำถาม
