-- ============================================================
--  049_guide_report_supply.sql
--  คู่มือการใช้งานของหน้า "สั่งซื้อ-เบิกใช้รายเดือน"
--
--  ทุกหน้าในระบบมีคู่มือของตัวเอง หน้าที่เพิ่มใหม่จึงต้องมีด้วย
--  ไม่งั้นปุ่มเครื่องหมายคำถามบนแถบบนจะหายไปเฉพาะหน้านี้
--  ซึ่งดูเหมือนระบบทำงานไม่สม่ำเสมอมากกว่าดูเหมือนตั้งใจ
--
--  ---------------------------------------------------------------
--  เนื้อหาเน้นสามเรื่องที่คนเข้าใจผิดได้ง่ายที่สุด
--  ---------------------------------------------------------------
--  1. อ่านตารางตามแนวนอน ไม่ใช่ไล่ทีละคอลัมน์
--     ทั้งแถวคือเรื่องของสินค้าตัวเดียว เรียงตามเวลา: ยกมา -> ซื้อ -> เบิก -> คงเหลือ
--     คนที่อ่านทีละคอลัมน์จะไม่เห็นว่าตัวเลขทั้งแถวบวกลบกันลงตัว
--
--  2. คอลัมน์หน่วยงานไม่คงที่ กางเฉพาะหน่วยที่เบิกจริงในเดือนนั้น
--     ถ้าไม่บอก จะมีคนคิดว่าหน่วยงานของตัวเองหายไปจากระบบ
--     ทั้งที่แค่เดือนนั้นไม่ได้เบิกอะไรเลย
--
--  3. ยอดยกมาเป็นยอดตามบัญชี ไม่ใช่ยอดที่เดินไปนับของจริง
--     ระบบยังไม่มีขั้นตอนตรวจนับ ตัวเลขจึงมาจากเอกสารที่บันทึกไว้ล้วน ๆ
--     ต้นแบบที่ใช้กันอยู่พาดหัวคอลัมน์นี้ว่า "คงเหลือนับจริง" ซึ่งคนละเรื่องกัน
--
--  ---------------------------------------------------------------
--  selector ที่ชี้
--  ---------------------------------------------------------------
--  ใช้ id ที่ตั้งไว้ใน pages/report_supply.php
--  (spMonth / spCount / spWrap / spMovedOnly / spSearch / btnExport / btnPrint)
--  ไม่ชี้ด้วยคลาสหรือลำดับ ซึ่งพังทันทีที่มีคนจัดหน้าใหม่
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hr < sql/049_guide_report_supply.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/049_guide_report_supply_rollback.sql
-- ============================================================

