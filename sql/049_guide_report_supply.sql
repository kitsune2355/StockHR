/* ---------- ตรวจผลลัพธ์ ---------- */
SELECT g.`page_key`, g.`title`, COUNT(s.`step_id`) AS `steps`
FROM `tb_guide` g
LEFT JOIN `tb_guide_step` s ON s.`guide_id` = g.`guide_id`
WHERE g.`page_key` = 'report_supply'
GROUP BY g.`guide_id`, g.`page_key`, g.`title`;
