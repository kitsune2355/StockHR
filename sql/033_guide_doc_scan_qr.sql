--  คู่มือหน้ารับเข้า / เบิก / จ่ายออก: ช่องยิงรับได้ทั้งบาร์โค้ดและ QR
--
--  ตัวโปรแกรมรองรับ QR อยู่แล้วโดยไม่ต้องแก้อะไร เพราะเครื่องอ่านถอดรหัส
--  ให้เสร็จก่อนส่งออกมาเป็นการกดปุ่ม ช่องยิงจึงได้รับแค่ตัวอักษรเหมือนกัน
--  ที่ต้องแก้คือคู่มือ ซึ่งเดิมพูดถึงบาร์โค้ดอย่างเดียว คนอ่านจะเข้าใจว่า
--  ยิง QR ไม่ได้ ทั้งที่ยิงได้
--
--  ข้อแม้ที่ต้องบอกให้ชัดคือเรื่องตัวเครื่อง ไม่ใช่เรื่องโปรแกรม
--  เครื่องเลเซอร์แบบเส้นตรงอ่าน QR ไม่ได้ ต้องเป็นรุ่นที่เป็นกล้อง (2D imager)
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/033_guide_doc_scan_qr.sql
--
--  ไฟล์นี้เขียนทับข้อความเดิมทั้งก้อน รันซ้ำได้ปลอดภัย
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/033_guide_doc_scan_qr_rollback.sql
-- ============================================================

SET NAMES utf8;

/* ---------- บันทึกรับเข้า ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title` = 'ยิงรหัสแทนการค้นหา',
    s.`description` = 'ถ้าของที่รับเข้ามามีฉลากแปะอยู่ ให้คลิกที่ช่องนี้แล้วยิงได้เลย ระบบจะเพิ่มบรรทัดพร้อมสินค้าและราคาให้ทันที ยิงซ้ำสินค้าตัวเดิมจะบวกจำนวนขึ้นทีละหนึ่ง ไม่ได้สร้างบรรทัดซ้ำ จึงเดินยิงของทีละชิ้นได้เลยโดยไม่ต้องนับก่อน ยิงถูกจะได้ยินเสียงสูงสั้น ยิงไม่เจอจะได้เสียงต่ำยาว ฟังได้โดยไม่ต้องละสายตาจากของ ช่องนี้รับได้ทั้งฉลากแบบบาร์โค้ดและแบบ QR โดยไม่ต้องสลับโหมด เพราะทั้งสองแบบเก็บรหัสสินค้าตัวเดียวกัน แต่ต้องดูที่ตัวเครื่องด้วย เครื่องยิงเลเซอร์แบบเส้นตรงอ่านได้แต่บาร์โค้ด ถ้าจะยิง QR ต้องเป็นรุ่นที่เป็นกล้อง ฉลากทั้งสองแบบพิมพ์ได้จากเมนู ข้อมูลสินค้า > บาร์โค้ดสินค้า'
WHERE g.`page_key` = 'receive_new' AND s.`target_selector` = '#scanInput';

/* ---------- ทำรายการเบิก ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`title` = 'ยิงรหัสถ้ามีของอยู่ตรงหน้า',
    s.`description` = 'ถ้ากำลังยืนอยู่หน้าชั้นวางและเห็นของจริง ยิงฉลากที่ติดอยู่ได้เลย เร็วกว่าไล่หาชื่อในรายการ ยิงแล้วสินค้าจะไปอยู่ฝั่งขวาทันที ยิงซ้ำตัวเดิมจะบวกจำนวนขึ้นทีละหนึ่ง ช่องนี้รับได้ทั้งฉลากแบบบาร์โค้ดและแบบ QR โดยไม่ต้องสลับโหมด ถ้ายิงแล้วขึ้นว่าไม่พบ ให้ดูก่อนว่าเลือกหน่วยงานถูกหรือยัง เพราะแต่ละหน่วยงานเบิกสินค้าได้ไม่เหมือนกัน สินค้าที่หน่วยงานนี้ไม่มีสิทธิ์เบิกจะยิงไม่ติด แต่ถ้ายิง QR แล้วไม่มีอะไรขึ้นในช่องเลยแม้แต่ตัวอักษรเดียว แปลว่าเครื่องยิงที่ใช้อยู่เป็นรุ่นเลเซอร์เส้นตรงซึ่งอ่าน QR ไม่ได้ ให้ใช้ฉลากแบบบาร์โค้ดแทน'
WHERE g.`page_key` = 'request_new' AND s.`target_selector` = '#scanInput';

/* ---------- บันทึกจ่ายออก ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'หน้านี้เพิ่มบรรทัดเองไม่ได้ รายการทั้งหมดมาจากใบเบิกที่เลือกไว้ การยิงตรงนี้จึงไม่ใช่การเพิ่มสินค้า แต่เป็นการนับของที่หยิบใส่กล่องไปแล้ว หยิบของหนึ่งชิ้นก็ยิงหนึ่งครั้ง ระบบจะบวกจำนวนในบรรทัดของสินค้านั้นให้ทีละหนึ่ง แล้วขึ้นข้อความบอกความคืบหน้า เช่น "หยิบแล้ว 2 จาก 5 ม้วน" หมายถึงหยิบไปแล้ว 2 ม้วน จากที่ใบเบิกขอมา 5 ม้วน เมื่อหยิบครบตามจำนวนที่ขอ ระบบจะเตือนว่าไม่ต้องหยิบเพิ่มแล้ว ประโยชน์ที่สำคัญที่สุดคือการจับว่าหยิบผิดตัว ถ้ายิงสินค้าที่ไม่มีอยู่ในใบเบิกใบนี้ ระบบจะเตือนพร้อมเสียงต่ำทันที ตอนที่ของยังอยู่ในมือ ไม่ใช่ตอนที่ส่งไปถึงหน่วยงานแล้ว ช่องนี้รับได้ทั้งฉลากแบบบาร์โค้ดและแบบ QR โดยไม่ต้องสลับโหมด'
WHERE g.`page_key` = 'issue_new' AND s.`target_selector` = '#scanInput';
