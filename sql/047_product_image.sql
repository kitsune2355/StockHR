-- ============================================================
--  047_product_image.sql
--  รูปสินค้า ได้สูงสุด 3 รูปต่อหนึ่งรายการ
--
--  ที่มา: คนเบิกของส่วนใหญ่ไม่ใช่คนคลัง จำรหัสสินค้าไม่ได้ และชื่อสินค้า
--  หลายตัวก็ใกล้กันจนแยกไม่ออกจากตัวหนังสืออย่างเดียว
--  ("ปากกาลูกลื่น 0.5" กับ "ปากกาเจล 0.5") เบิกผิดตัวแล้วต้องเดินมาเปลี่ยน
--  รูปเดียวตัดปัญหานี้ได้เกือบหมด
--
--  ---------------------------------------------------------------
--  ทำไมเป็นตารางลูก ไม่ใช่ 3 คอลัมน์ใน tb_product
--  ---------------------------------------------------------------
--  3 คอลัมน์ (image1/image2/image3) ดูง่ายกว่าตอนเริ่ม แต่พอผู้ใช้ลบรูปกลาง
--  จะเหลือช่องว่างคั่น ต้องมีโค้ดเลื่อนรูปที่เหลือขึ้นมาปิดรู และทุกที่ที่อ่าน
--  ต้องวนเช็คทีละคอลัมน์ว่าว่างไหม
--
--  ตารางลูกจัดการเรื่องนี้ด้วย sort_no ตัวเดียว ลบแถวไหนก็ได้โดยไม่เหลือรู
--  และถ้าวันหนึ่งอยากได้มากกว่า 3 รูป ก็แก้แค่ตัวเลขในโค้ด ไม่ต้อง ALTER TABLE
--
--  ---------------------------------------------------------------
--  เก็บ "ชื่อไฟล์" ไม่ใช่ตัวรูป
--  ---------------------------------------------------------------
--  เหตุผลเดียวกับโลโก้บริษัทที่ sql/014 — เก็บรูปเป็น BLOB ทำให้ไฟล์สำรอง
--  ฐานข้อมูลบวมขึ้นหลายเท่า และทุก query ที่เผลอ SELECT * จะลากรูปมาด้วย
--  ไฟล์จริงอยู่ที่ assets/img/product/ ให้เว็บเซิร์ฟเวอร์ส่งเองและเบราว์เซอร์แคชได้
--
--  ---------------------------------------------------------------
--  ทำไมไม่จำกัด 3 รูปด้วยฐานข้อมูล
--  ---------------------------------------------------------------
--  MySQL 5.0 ไม่มี CHECK constraint ที่บังคับใช้จริง และ trigger ก็เกินจำเป็น
--  UNIQUE (product_id, sort_no) กันรูปซ้ำช่องแล้ว ส่วนเพดาน 3 บังคับที่
--  product_image_save() ใน backend/product_image.php ที่เดียว
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hl < sql/047_product_image.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/047_product_image_rollback.sql
-- ============================================================

SET NAMES utf8;

CREATE TABLE IF NOT EXISTS `tb_product_image` (

    `image_id`   INT(10) UNSIGNED NOT NULL AUTO_INCREMENT,

    `product_id` INT(10) UNSIGNED NOT NULL
                 COMMENT 'สินค้าที่รูปนี้เป็นของ',

    `sort_no`    TINYINT(3) UNSIGNED NOT NULL DEFAULT 1
                 COMMENT 'ลำดับการแสดง 1-3 รูปที่ 1 คือรูปที่เอาไปโชว์เป็นรูปหลัก',

    `image_file` VARCHAR(255) NOT NULL
                 COMMENT 'ชื่อไฟล์ใน assets/img/product/ ตั้งชื่อโดยระบบเท่านั้น',

    /* ---------- คอลัมน์ตรวจสอบย้อนหลัง ครบสี่ตัวตามมาตรฐานของระบบ ---------- */
    `created_at` DATETIME NOT NULL,
    `created_by` VARCHAR(50) NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_by` VARCHAR(50) NULL DEFAULT NULL,

    PRIMARY KEY (`image_id`),

    /* หนึ่งช่องมีรูปเดียว กันสองคนกดอัปโหลดพร้อมกันแล้วได้ช่องเดียวกันสองแถว */
    UNIQUE KEY `uq_product_image_slot` (`product_id`, `sort_no`),

    /* หน้าเบิกกับหน้าทะเบียนสินค้าดึงรูปของสินค้าทีละหลายรายการพร้อมกัน
       จึงค้นด้วย product_id เสมอ และเรียงด้วย sort_no ต่อทันที */
    KEY `ix_product_image_sort` (`product_id`, `sort_no`),

    /* ลบสินค้าแล้วรูปต้องหายตาม ไม่ปล่อยให้เป็นแถวกำพร้าที่ชี้ไปยังสินค้าที่ไม่มีแล้ว
       (ไฟล์บนดิสก์ต้องเก็บกวาดเองในโค้ด ฐานข้อมูลลบไฟล์ให้ไม่ได้) */
    CONSTRAINT `fk_product_image_product`
        FOREIGN KEY (`product_id`) REFERENCES `tb_product` (`product_id`) ON DELETE CASCADE

) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci
  COMMENT='รูปสินค้า สูงสุด 3 รูปต่อรายการ เพดานบังคับที่ backend/product_image.php';


-- ------------------------------------------------------------
--  ตรวจผลลัพธ์
-- ------------------------------------------------------------
SELECT COUNT(*) AS `จำนวนรูปทั้งหมด` FROM `tb_product_image`;
