--
--  ข้อความเดิมมีประโยคว่า "จำนวนในบรรทัดนั้นจะเดินขึ้นเองพร้อมบอกว่าหยิบไปแล้วกี่จากกี่"
--  ซึ่งอ่านแล้วงง เพราะ "กี่จากกี่" เป็นการย่อที่ไม่ได้บอกว่าเลขสองตัวนั้นคืออะไร
--  แก้เป็นยกตัวอย่างตัวเลขจริงให้เห็นภาพ แล้วอธิบายว่าเลขแต่ละตัวหมายถึงอะไร
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hl < sql/027b_guide_issue_scan_wording.sql
--
--  ไฟล์ 027 ถูกแก้ให้มีข้อความชุดใหม่แล้วเช่นกัน ติดตั้งใหม่จากศูนย์จึงได้ผลเดียวกัน
-- ============================================================

SET NAMES utf8;

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'หน้านี้เพิ่มบรรทัดเองไม่ได้ รายการทั้งหมดมาจากใบเบิกที่เลือกไว้ การยิงตรงนี้จึงไม่ใช่การเพิ่มสินค้า แต่เป็นการนับของที่หยิบใส่กล่องไปแล้ว หยิบของหนึ่งชิ้นก็ยิงหนึ่งครั้ง ระบบจะบวกจำนวนในบรรทัดของสินค้านั้นให้ทีละหนึ่ง แล้วขึ้นข้อความบอกความคืบหน้า เช่น "หยิบแล้ว 2 จาก 5 ม้วน" หมายถึงหยิบไปแล้ว 2 ม้วน จากที่ใบเบิกขอมา 5 ม้วน เมื่อหยิบครบตามจำนวนที่ขอ ระบบจะเตือนว่าไม่ต้องหยิบเพิ่มแล้ว ประโยชน์ที่สำคัญที่สุดคือการจับว่าหยิบผิดตัว ถ้ายิงสินค้าที่ไม่มีอยู่ในใบเบิกใบนี้ ระบบจะเตือนพร้อมเสียงต่ำทันที ตอนที่ของยังอยู่ในมือ ไม่ใช่ตอนที่ส่งไปถึงหน่วยงานแล้ว'
WHERE g.`page_key` = 'issue_new' AND s.`target_selector` = '#scanInput';
