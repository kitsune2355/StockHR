-- ============================================================
--  032_guide_barcode_qr.sql
--  คู่มือหน้าบาร์โค้ดสินค้า: เพิ่มเรื่องการเลือกชนิดรหัส (บาร์โค้ด / QR)
--
--  หน้านี้เดิมทำได้อย่างเดียวคือ Code 128 ตอนนี้เลือก QR ได้ด้วย
--  เนื้อหาในรหัสเป็น product_code ตัวเดียวกันทั้งคู่ ต่างกันที่วิธีอ่าน
--
--  เรื่องที่ต้องอธิบายมากที่สุดคือ "เลือกอันไหนเมื่อไร" เพราะเดาเองไม่ได้
--  และเกณฑ์ขนาดต่ำสุดของสองแบบไม่เท่ากัน (0.25 กับ 0.40 มม.)
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hl < sql/032_guide_barcode_qr.sql
--
--  ไฟล์นี้ลบขั้นของตัวเองก่อนใส่ใหม่ รันซ้ำได้ปลอดภัย
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hl < sql/032_guide_barcode_qr_rollback.sql
-- ============================================================

SET NAMES utf8;

DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'product_barcode' AND s.`target_selector` = '#bcType';

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'product_barcode' AND s.`step_order` >= 3;

INSERT INTO `tb_guide_step` (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 3, '#bcType', 'เลือกบาร์โค้ดหรือ QR',
 'ทั้งสองแบบเก็บรหัสสินค้าตัวเดียวกันเป๊ะ ต่างกันแค่ใครอ่านได้ บาร์โค้ดใช้กับเครื่องยิงที่เสียบกับคอมพิวเตอร์ ซึ่งเป็นวิธีที่เร็วที่สุดตอนรับเข้าหรือจ่ายของทีละหลายรายการ ส่วน QR ส่องด้วยกล้องมือถือธรรมดาได้ เหมาะกับคนที่ไม่มีเครื่องยิงติดตัว เช่นตอนไปนับของที่ชั้นวางหรือหน้างานนอกห้องคลัง ข้อควรรู้: เครื่องยิงเลเซอร์แบบเส้นตรงส่วนใหญ่อ่าน QR ไม่ได้ ต้องเป็นรุ่นที่เป็นกล้อง (2D imager) เท่านั้น ถ้าไม่แน่ใจว่าเครื่องที่มีอยู่เป็นแบบไหน ให้ลองยิงดูจากตัวอย่างบนหน้าจอนี้ได้เลย',
 'left', 'center', NOW() FROM `tb_guide` WHERE `page_key`='product_barcode';

UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`description` = 'นี่คือขนาดของส่วนที่เล็กที่สุดในรหัส เป็นตัวชี้ขาดว่าเครื่องอ่านจะอ่านติดหรือไม่ ตัวเลขและเกณฑ์เปลี่ยนตามชนิดรหัสที่เลือกไว้ แบบบาร์โค้ดวัดความกว้างแท่งที่แคบที่สุด ต้องได้อย่างน้อย 0.25 มม. ส่วนแบบ QR วัดความกว้างของช่องสี่เหลี่ยมเล็กที่สุด ต้องได้อย่างน้อย 0.40 มม. ซึ่งมากกว่าเพราะกล้องมือถือไม่ได้เล็งเป็นเส้นตรงเหมือนเลเซอร์ และมักถ่ายเอียงกับสั่นด้วย ถ้าต่ำกว่าเกณฑ์จะมีกล่องเตือนสีเหลืองขึ้นมา แก้ได้โดยเลือกดวงสติกเกอร์ที่ใหญ่ขึ้น ควรดูตัวเลขนี้ก่อนกดพิมพ์ทุกครั้ง เพราะถ้ารู้ตอนตัดสติกเกอร์ไปแปะของหมดแล้วจะแก้ไม่ทัน',
 s.`title` = 'ตัวเลขที่ต้องดูก่อนพิมพ์ทุกครั้ง'
WHERE g.`page_key` = 'product_barcode' AND s.`target_selector` = '#bcQuality';
