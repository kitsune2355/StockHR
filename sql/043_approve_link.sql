-- ============================================================
--  043_approve_link.sql
--  ลิงก์อนุมัติใบเบิกแบบไม่ต้องล็อกอิน
--
--  ที่มา: เมล "ใบเบิกรอคุณอนุมัติ" ส่งไปหาผู้อนุมัติ พร้อมปุ่มที่ชี้ไป
--  main.php?page=request_list ซึ่งอยู่หลังหน้าล็อกอิน ผู้อนุมัติหลายคน
--  อ่านเมลจากมือถือ กดปุ่มแล้วต้องพิมพ์รหัสผ่านบนจอเล็ก ๆ ก่อนถึงจะกดอนุมัติได้
--  ใบเบิกเลยค้างสถานะ "รออนุมัติ" ข้ามวันทั้งที่ผู้อนุมัติเห็นเมลตั้งแต่เช้า
--
--  ทำแบบเดียวกับลิงก์เซ็นรับของ (019_sign_link.sql) แต่โครงเก็บต่างกัน
--  ด้วยเหตุผลข้างล่าง
--
--  ---------------------------------------------------------------
--  ทำไมเป็นตารางใหม่ ไม่ใช่คอลัมน์ใน tb_doc_header แบบลิงก์เซ็นรับ
--  ---------------------------------------------------------------
--  ลิงก์เซ็นรับเป็น 1:1 — ใบจ่ายหนึ่งใบมีผู้รับของคนเดียว เก็บเป็นคอลัมน์ได้
--
--  แต่ใบเบิกหนึ่งใบส่งเมลหาผู้อนุมัติ "ทุกคน" ของหน่วยงานนั้น
--  (ดู user_approvers_for_dept) ซึ่งมีได้หลายคน จึงเป็น 1:N
--
--  และแต่ละคนต้องได้กุญแจคนละดอก ไม่ใช่ดอกเดียวกัน เพราะ:
--
--    1. ต้องรู้ว่า "ใครอนุมัติ" — คอลัมน์ approved_by มี foreign key ไป
--       tb_user.username ใส่ค่าที่ไม่ใช่ชื่อผู้ใช้จริงจะล้มทั้งคำสั่งด้วย error 1452
--       (บทเรียนเดียวกับที่เขียนไว้ใน backend/sign_link.php)
--
--    2. กฎ "ห้ามอนุมัติใบของตัวเอง" กับกฎ "อนุมัติได้เฉพาะหน่วยงานตัวเอง"
--       ใน request_decide() ตัดสินจากตัวตนของผู้อนุมัติ ถ้าไม่รู้ว่าใครกด
--       ก็บังคับสองกฎนี้ไม่ได้เลย
--
--    3. กุญแจดอกเดียวที่ใช้ร่วมกันแปลว่าใครก็ตามที่ได้รับเมลฉบับนั้น
--       อนุมัติในนามคนอื่นได้ ซึ่งทำให้ประวัติการอนุมัติเชื่อถือไม่ได้
--
--  ---------------------------------------------------------------
--  อายุ 3 วัน สั้นกว่าลิงก์เซ็นรับที่ให้ 7 วัน
--  ---------------------------------------------------------------
--  การอนุมัติเป็นอำนาจที่แรงกว่าการเซ็นรับของ เพราะเป็นการอนุญาตให้ของ
--  ออกจากคลัง ใครถือลิงก์ก็อนุมัติในนามผู้อนุมัติคนนั้นได้
--
--  ใบเบิกที่ค้างเกินสามวันควรถูกตามอยู่แล้ว ไม่ใช่ปล่อยให้ลิงก์รออีกสัปดาห์
--  หมดอายุแล้วกดส่งเมลซ้ำหรือคัดลอกลิงก์ใหม่ ระบบจะออกกุญแจใหม่ให้
--
--  ---------------------------------------------------------------
--  used_at — กดได้ครั้งเดียวจริง ๆ
--  ---------------------------------------------------------------
--  ประทับเวลาไว้ตอนตัดสินสำเร็จ กุญแจที่ถูกใช้แล้วจะเปิดหน้าอนุมัติไม่ได้อีก
--  ไม่ได้พึ่งสถานะเอกสารอย่างเดียว เพราะอยากให้หน้าจอบอกได้ว่า
--  "ลิงก์นี้ถูกใช้ไปแล้ว" ต่างจาก "ใบนี้ถูกคนอื่นตัดสินไปแล้ว" ซึ่งคนละเรื่องกัน
--
--  ---------------------------------------------------------------
--  ไม่ผูก foreign key ที่ created_by / updated_by
--  ---------------------------------------------------------------
--  ตั้งใจ ตารางอื่นที่ผูกไว้ทำให้เขียนจากเส้นทางที่ไม่มีผู้กระทำจริง
--  (ระบบส่งเมลเอง / cron) ล้มด้วย error 1452 แบบเงียบ ๆ
--  ที่นี่จึงเก็บเป็นข้อความเปล่า ๆ ไว้ดูย้อนหลังอย่างเดียว
--
--  วิธีรัน:
--      mysql -u root -p1234 stock_hr < sql/043_approve_link.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/043_approve_link_rollback.sql
--
--  รองรับ MySQL 5.0.51b
-- ============================================================

SET NAMES utf8;

CREATE TABLE IF NOT EXISTS `tb_approve_link` (

    `link_id`    INT(10) UNSIGNED NOT NULL AUTO_INCREMENT,

    `doc_id`     INT(10) UNSIGNED NOT NULL
                 COMMENT 'ใบเบิกที่ลิงก์นี้ใช้ตัดสินได้ ใบเดียวเท่านั้น',

    `username`   VARCHAR(50) NOT NULL
                 COMMENT 'ออกให้ผู้อนุมัติคนไหน ชื่อนี้คือคนที่จะถูกบันทึกเป็นผู้ตัดสิน',

    `token`      CHAR(40) NOT NULL
                 COMMENT 'กุญแจสุ่ม 40 ตัวอักษร คือสิทธิ์ทั้งหมดที่ลิงก์นี้มี',

    `expires_at` DATETIME NOT NULL
                 COMMENT 'เลยเวลานี้แล้วเปิดไม่ได้ ต้องขอลิงก์ใหม่',

    `used_at`    DATETIME NULL DEFAULT NULL
                 COMMENT 'ตัดสินไปแล้วเมื่อไหร่ ไม่ว่างแปลว่ากุญแจถูกใช้ไปแล้ว',

    /* ---------- คอลัมน์ตรวจสอบย้อนหลัง ครบสี่ตัวตามมาตรฐานของระบบ ---------- */
    `created_at` DATETIME NOT NULL,
    `created_by` VARCHAR(50) NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_by` VARCHAR(50) NULL DEFAULT NULL,

    PRIMARY KEY (`link_id`),

    /* ค้นด้วยกุญแจอย่างเดียวทุกครั้งที่เปิดหน้าอนุมัติ จึงต้องมี index
       UNIQUE เพื่อกันกุญแจซ้ำในระดับฐานข้อมูล ไม่ใช่แค่หวังว่าตัวสุ่มจะไม่ชน */
    UNIQUE KEY `uq_approve_token` (`token`),

    /* หนึ่งคนได้กุญแจดอกเดียวต่อหนึ่งใบ กดส่งเมลซ้ำคือเขียนทับดอกเดิม
       ซึ่งเป็นการเพิกถอนของเก่าไปในตัว เหมือนพฤติกรรมของลิงก์เซ็นรับ */
    UNIQUE KEY `uq_approve_doc_user` (`doc_id`, `username`),

    KEY `ix_approve_doc` (`doc_id`),

    /* ลบเอกสารหรือลบผู้ใช้แล้วกุญแจต้องหายตาม ไม่ปล่อยให้เป็นแถวกำพร้า
       ที่ยังเปิดลิงก์ได้อยู่ */
    CONSTRAINT `fk_approve_link_doc`
        FOREIGN KEY (`doc_id`) REFERENCES `tb_doc_header` (`doc_id`) ON DELETE CASCADE,
    CONSTRAINT `fk_approve_link_user`
        FOREIGN KEY (`username`) REFERENCES `tb_user` (`username`) ON DELETE CASCADE

) ENGINE=InnoDB DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci
  COMMENT='กุญแจลิงก์อนุมัติใบเบิกแบบไม่ต้องล็อกอิน หนึ่งดอกต่อผู้อนุมัติหนึ่งคนต่อใบ';
