-- ============================================================
--  045_guide_request_print.sql
--  คู่มือหน้ารายการใบเบิก: เพิ่มขั้นของปุ่มพิมพ์เอกสารที่ขาดหายไป
--
--  ที่มา: คู่มือหน้าประวัติการรับเข้าและประวัติการจ่ายออกมีขั้นของไอคอน
--  เครื่องพิมพ์ทั้งคู่ แต่หน้ารายการใบเบิกไม่มี ทั้งที่ปุ่มอยู่ตำแหน่งเดียวกัน
--  และทำงานเหมือนกัน คนที่เปิดคู่มือหน้านี้จึงถูกข้ามไอคอนที่สองไปเฉย ๆ
--
--  ---------------------------------------------------------------
--  ทำไม selector ไม่ใช่ .rowact[data-row-act="print"]
--  ---------------------------------------------------------------
--  ปุ่มพิมพ์ถูกวาดเป็น <a href="print_doc.php?..."> ไม่ใช่ <button>
--  เพราะต้องเปิดแท็บใหม่ (ดูเหตุผลใน rowActionHtml ที่ assets/js/doc-list.js)
--  จึงไม่มี attribute data-row-act ให้ชี้
--
--  ใช้ .rowact[href^="print_doc.php"] ซึ่งเป็นตัวเดียวกับที่หน้าประวัติ
--  ทั้งสองหน้าใช้อยู่แล้ว จะได้ไม่มีสองวิธีชี้ปุ่มเดียวกัน
--
--  ---------------------------------------------------------------
--  เรื่องที่ต้องบอกและเป็นเรื่องเฉพาะของใบเบิก
--  ---------------------------------------------------------------
--  ราคาบนใบเบิกที่พิมพ์ออกมาเป็น "ราคาประมาณการ" จากต้นทุนเฉลี่ยปัจจุบัน
--  ไม่ใช่ยอดที่ลงบัญชี เพราะใบเบิกยังไม่เคยแตะสต๊อก บรรทัดจึงไม่มีราคาแช่แข็ง
--  (ดู $is_estimate ใน print_doc.php) ฝ่ายบัญชีที่ได้กระดาษไปต้องรู้ข้อนี้
--
--  ---------------------------------------------------------------
--  เลขลำดับขั้น
--  ---------------------------------------------------------------
--  แทรกเป็นขั้นที่ 3 ให้ตรงลำดับปุ่มบนหน้าจอ (ดู · พิมพ์ · ลิงก์ · อนุมัติ ...)
--  แล้วเลื่อนขั้น 3 เป็นต้นไปลงหนึ่งช่อง — ตำแหน่งเดียวกับที่หน้าประวัติใช้
--
--  รันซ้ำจะเลื่อนซ้ำและได้ขั้นซ้ำ จึงลบขั้นเดิมทิ้งก่อนเสมอ
--
--  หมายเหตุ: 042 กับ 044 ชี้ขั้นตอนด้วย step_order ตามผังก่อนไฟล์นี้
--  ถ้าจะรันสองไฟล์นั้นซ้ำหลังรันไฟล์นี้ ต้องเลื่อนเลขตามด้วย
--
--  วิธีรัน (ต้องส่งเป็นไฟล์ ไม่ใช่ mysql -e ไม่งั้นภาษาไทยจะเพี้ยน):
--      mysql -u root -p1234 stock_hr < sql/045_guide_request_print.sql
--
--  ย้อนกลับ:
--      mysql -u root -p1234 stock_hr < sql/045_guide_request_print_rollback.sql
-- ============================================================

SET NAMES utf8;

/* ---------- ลบขั้นเดิมก่อน กันรันซ้ำแล้วได้ขั้นซ้ำ ---------- */
DELETE s FROM `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
WHERE g.`page_key` = 'request_list'
  AND s.`target_selector` = '.rowact[href^="print_doc.php"]';

/* ---------- เปิดช่องที่ 3 ---------- */
UPDATE `tb_guide_step` s
INNER JOIN `tb_guide` g ON g.`guide_id` = s.`guide_id`
SET s.`step_order` = s.`step_order` + 1
WHERE g.`page_key` = 'request_list'
  AND s.`step_order` >= 3;

/* ---------- ขั้นใหม่: ปุ่มพิมพ์เอกสาร ---------- */
INSERT INTO `tb_guide_step`
    (`guide_id`, `step_order`, `target_selector`, `title`, `description`, `side`, `align`, `created_at`)
SELECT `guide_id`, 3, '.rowact[href^="print_doc.php"]', 'ไอคอนเครื่องพิมพ์',
 'เปิดหน้ากระดาษในแท็บใหม่ ตัดเมนูและปุ่มออกหมด เหลือแต่ตัวเอกสารพร้อมโลโก้บริษัทของหน่วยงานนั้น มีช่องเซ็นผู้ขอเบิกและผู้อนุมัติให้ครบ ราคาบนใบเบิกเป็นราคาประมาณการจากต้นทุนเฉลี่ยปัจจุบัน ไม่ใช่ยอดที่ลงบัญชี ตัวเลขจริงยืนยันอีกครั้งตอนจ่ายของ',
 'bottom', 'start', NOW()
FROM `tb_guide` WHERE `page_key` = 'request_list';
