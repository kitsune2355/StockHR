<?php
/* ============================================================
 *  backend/after_response.php — ฝากงานช้าไว้ทำหลังตอบผู้ใช้ไปแล้ว
 *
 *  ---------------------------------------------------------------
 *  ปัญหาที่ไฟล์นี้แก้
 *  ---------------------------------------------------------------
 *  หน้าที่เปิดจากลิงก์ในเมล (approve.php, sign.php) ไม่ได้วิ่งผ่าน
 *  api/_bootstrap.php จึงไม่มี api_after_response ให้ฝากงาน เมลแจ้งผลจึงถูกส่ง
 *  คาอยู่ในคำขอเดียวกับที่ผู้ใช้กดปุ่ม (ดู notify_deliver ใน notify_events.php)
 *
 *  ผลคือคนกด "อนุมัติ" ต้องนั่งรอ SMTP ต่อสายออกไปข้างนอกทีละฉบับ
 *  ทั้งที่ใบเบิกถูกบันทึกเสร็จตั้งแต่วินาทีแรก บนมือถือที่สัญญาณไม่ดี
 *  ปุ่มค้างหลายวินาทีแบบนี้ทำให้คนกดซ้ำ ซึ่งเป็นสิ่งที่ไม่ควรต้องเจอเลย
 *  เพราะงานของเขาเสร็จไปแล้ว เหลือแค่เรื่องของระบบที่ยังทำไม่จบ
 *
 *  ---------------------------------------------------------------
 *  วิธีทำงาน
 *  ---------------------------------------------------------------
 *  include ไว้บนสุดของหน้า (ก่อนมีอะไรถูกพิมพ์ออกไป) แล้วฝากงานด้วย
 *      after_response('ชื่อฟังก์ชัน')
 *
 *  ไม่ต้องเรียกอะไรปิดท้าย ตัวมันผูกกับ register_shutdown_function ไว้เอง
 *  ซึ่งจำเป็นกับหน้าพวกนี้ เพราะมี exit กระจายอยู่หลายจุด (redirect หลังบันทึก,
 *  ทางลัดตอนกุญแจใช้ไม่ได้) ถ้าต้องไปเรียกปิดท้ายให้ครบทุกทางออกเอง
 *  วันหนึ่งจะมีทางออกใหม่ที่ลืมเรียก แล้วเมลจะค้างคิวโดยไม่มีใครรู้
 *
 *  ตอนสคริปต์จบ: บอกความยาวคำตอบแล้วสั่งปิดการเชื่อมต่อ เบราว์เซอร์รู้ว่า
 *  ได้ครบแล้วและเลิกรอ ส่วน PHP ยังทำงานที่ฝากไว้ต่อจนจบ
 *
 *  ---------------------------------------------------------------
 *  ข้อจำกัดที่รู้อยู่แล้ว
 *  ---------------------------------------------------------------
 *  ลูกเล่นปิดการเชื่อมต่อนี้ใช้ได้เพราะเซิร์ฟเวอร์ทั้งสองที่ไม่ได้บีบอัดคำตอบ
 *  ถ้าวันหนึ่งเปิดบีบอัด ความยาวที่บอกไปจะไม่ตรงกับที่ส่งจริง เบราว์เซอร์จะค้าง
 *  รอส่วนที่เหลือ — ตรงนั้นให้เอา header Content-Length ออก ผลคือผู้ใช้รอ
 *  เท่าเดิมเหมือนก่อนมีไฟล์นี้ ไม่มีอะไรพัง
 *
 *  โฮสต์ที่เป็น PHP-FPM จะได้ fastcgi_finish_request ซึ่งตรงไปตรงมากว่า
 *  และไม่มีปัญหาเรื่องบีบอัดเลย (ตรงกับกลไกใน api/_bootstrap.php)
 *
 *  เขียนให้รองรับ PHP 5.2.6
 * ============================================================ */

if (!defined('AFTER_RESPONSE_READY')) {

    define('AFTER_RESPONSE_READY', 1);

    $GLOBALS['after_response_tasks'] = array();

    function after_response($fn)
    {
        $GLOBALS['after_response_tasks'][] = $fn;
    }

    function after_response_shutdown()
    {
        $tasks = $GLOBALS['after_response_tasks'];
        $GLOBALS['after_response_tasks'] = array();

        /* ยุบบัฟเฟอร์ที่หน้าเปิดซ้อนเข้ามา ให้เหลือก้อนเดียวแล้วดึงออกมาทั้งหมด
           ต้องรู้ความยาวรวมก่อน ถึงจะบอกเบราว์เซอร์ได้ว่าคำตอบจบแค่นี้ */
        $body = '';
        if (ob_get_level() > 0) {
            while (ob_get_level() > 1) { @ob_end_flush(); }
            $body = ob_get_clean();
            if ($body === false) { $body = ''; }
        }

        /* ไม่มีงานฝากไว้ = ไม่ต้องเล่นลูกเล่นอะไรทั้งนั้น พิมพ์คำตอบตามปกติ */
        if (count($tasks) === 0) { echo $body; return; }

        /* ผู้ใช้ปิดหน้าไปแล้วก็ต้องทำงานที่ฝากไว้ให้จบ ไม่งั้นเมลค้างคิวรอ cron รอบหน้า */
        ignore_user_abort(true);
        @set_time_limit(120);

        if (!headers_sent()) {
            header('Content-Length: ' . strlen($body));
            header('Connection: close');
        }

        echo $body;
        while (ob_get_level() > 0) { @ob_end_flush(); }
        @flush();
        if (function_exists('fastcgi_finish_request')) { @fastcgi_finish_request(); }

        /* คำตอบถูกส่งไปแล้ว งานเบื้องหลังพังยังไงก็ห้ามมีอะไรโผล่กลับไปหาผู้ใช้ */
        for ($i = 0; $i < count($tasks); $i++) {
            if (is_callable($tasks[$i])) { @call_user_func($tasks[$i]); }
        }
    }

    register_shutdown_function('after_response_shutdown');

    /* เก็บคำตอบไว้ในมือตั้งแต่บรรทัดนี้ จะได้นับความยาวได้ตอนจบ
       ต้องอยู่หลัง register_shutdown_function เพื่อให้แน่ใจว่ามีคนมาเก็บกวาดแน่ */
    ob_start();
}
