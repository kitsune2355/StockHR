 *  ใบเบิกพนักงานใหม่ (NRQ) และใบจ่ายที่อ้างใบเบิกนั้น พนักงานต้องเซ็นรับทราบเงื่อนไข
 *  การหักค่าชุด/คืนชุด แทนเงื่อนไขการเบิกวัสดุทั่วไป
 *
 *  ใช้สองที่ ข้อความต้องตรงกันเสมอจึงเก็บไว้ที่นี่ที่เดียว
 *    - print_doc.php  พิมพ์เป็นหมายเหตุข้อ 2-4 ของแบบฟอร์ม
