require_once dirname(__FILE__) . '/document.php';
require_once dirname(__FILE__) . '/setting.php';

/* ---------- เอกสารนี้เป็นเอกสารรับชุดเครื่องแบบไหม ----------
 * คืนข้อมูลพนักงานใหม่ (employee_name / employee_code / position_name / start_date)
 * หรือ null ถ้าเป็นเอกสารทั่วไป
 *   - ใบเบิกพนักงานใหม่เอง (มีแถวใน tb_doc_new_staff)
 *   - ใบจ่ายที่อ้างใบเบิกพนักงานใหม่ (ข้อมูลพนักงานผูกกับใบเบิก ไม่ใช่ใบจ่าย)
 * $ref_doc ส่งมาได้ถ้าหาใบต้นทางไว้แล้ว จะได้ไม่ต้อง query ซ้ำ */
function uniform_receipt_for_doc($doc, $ref_doc = null)
{
    if (!empty($doc['new_staff'])) {
        return $doc['new_staff'];
    }
    if ($doc['doc_type'] !== 'issue' || (int)$doc['ref_doc_id'] <= 0) {
        return null;
    }
    if ($ref_doc === null) {
        $ref_doc = doc_find($doc['ref_doc_id']);
    }
    return ($ref_doc !== null && !empty($ref_doc['new_staff'])) ? $ref_doc['new_staff'] : null;
}

/* ---------- เงื่อนไขที่พนักงานรับทราบ (ข้อ 2-4 ของแบบฟอร์ม) ----------
 * แก้ได้ที่ tb_app_setting คีย์ uniform_receipt_terms บรรทัดละข้อ
 * ไม่ตั้ง = ใช้ข้อความตามแบบฟอร์มกระดาษ 019-HRM : Rev.01 */
function uniform_receipt_terms()
{
    $default =
          "กรณีพนักงานลาออก หรือพ้นสภาพเนื่องจากทำผิดระเบียบ ข้อบังคับของบริษัทในช่วงระยะเวลาทดลองงาน หรือพนักงานได้รับการประเมินไม่ผ่านทดลองงาน หรือปฏิบัติงานไม่ถึง 120 วันนับจากวันที่รับชุด พนักงานยินยอมให้บริษัทฯ หักค่าชุดเครื่องแบบที่พนักงานได้รับในการจ่ายค่าจ้างงวดสุดท้าย โดยไม่มีข้อโต้แย้งใดๆ\n"
        . "กรณีที่พนักงานลาออก หรือพ้นสภาพเนื่องจากทำผิดระเบียบ ข้อบังคับของบริษัท หลังจากผ่านทดลองงานแล้ว หรือปฏิบัติงานเกิน 120 วันนับจากวันที่รับชุด บริษัทจะถือว่าเครื่องแบบเป็นสวัสดิการสำหรับพนักงาน จะไม่มีการหักค่าใช้จ่ายใดๆ\n"
        . "กรณีพนักงานได้รับชุดเครื่องแบบก่อนเริ่มงาน และไม่มาเริ่มงานตามกำหนด พนักงานตกลงและยินยอมที่จะนำชุดเครื่องแบบมาคืนให้แก่บริษัทฯ ในสภาพเดิม โดยพนักงานเป็นผู้รับผิดชอบค่าใช้จ่ายในการนำส่งคืน ทั้งนี้จะต้องนำส่งถึงบริษัทฯ ภายใน 3 วันนับแต่บริษัททราบถึงการผิดนัดไม่มาเริ่มงานตามกำหนด หากพนักงานไม่ดำเนินการ พนักงานทราบดีว่าการกระทำดังกล่าวเป็นการครอบครองทรัพย์สินของบริษัทฯ โดยไม่ได้รับอนุญาต";

    $text = trim(setting_get('uniform_receipt_terms', ''));
    if ($text === '') { $text = $default; }

    $out = array();
    foreach (explode("\n", $text) as $ln) {
        if (trim($ln) !== '') { $out[] = trim($ln); }
    }
    return $out;
}

/* ---------- รหัสแบบฟอร์มมุมล่าง ----------
 * เป็นแบบฟอร์มของ HR ไม่ใช่รหัสใบเบิก/ใบจ่ายของบริษัท (tb_company.form_code) */
function uniform_receipt_form_code()
{
    $code = trim(setting_get('uniform_receipt_form_code', ''));
    return ($code !== '') ? $code : '019-HRM : Rev.01 :08/04/2569';
}
