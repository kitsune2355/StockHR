/* ============================================================
 *  backend/thai_date.php — รูปแบบวันที่แบบไทยของทั้งระบบ
 *
 *      thai_date('2026-08-13')            -> 13 ส.ค. 69
 *      thai_date_long('2026-08-13')       -> 13 สิงหาคม 2569
 *      thai_date_time('2026-08-13 14:32') -> 13 ส.ค. 69 14:32
 *      thai_month('2026-08')              -> สิงหาคม 2569
 *      thai_day_label('2026-08-13')       -> วันนี้ / เมื่อวาน / 13 ส.ค. 2569
 *      thai_now()                         -> 13 ส.ค. 2569 เวลา 14:32
 *
 *  ---------- แก้รูปแบบวันที่ที่เดียว เปลี่ยนทั้งระบบ ----------
 *  ทุกอย่างที่กำหนดหน้าตาของวันที่อยู่ใน thai_date_config() ข้างล่างนี้ที่เดียว
 *  ทั้งชื่อเดือน ชื่อวัน ปีพุทธ และรูปแบบของแต่ละที่ที่เอาไปแสดง
 *
 *  ฝั่งหน้าจอ (assets/js/thai-date.js) ไม่ได้เก็บค่าพวกนี้ซ้ำอีกชุด
 *  แต่รับค่าจากฟังก์ชันนี้ผ่าน window.THAI_DATE_CONFIG ที่ includes/head_assets.php
 *  พ่นลงหน้าให้ ดังนั้นแก้ที่นี่แล้วทั้ง PHP และ JavaScript เปลี่ยนตามพร้อมกัน
 *  ไม่มีทางที่สองฝั่งจะแสดงคนละแบบเพราะลืมแก้อีกที่
 *
 *  ---------- ใช้แสดงผลเท่านั้น ----------
 *  ห้ามเอาผลลัพธ์กลับไปเก็บ — ฐานข้อมูลต้องเป็น ค.ศ. เหมือนเดิม
 *  ไม่งั้น MySQL จะเรียงตามตัวอักษรแล้วรายงานย้อนหลังผิดโดยไม่มีอะไรฟ้อง
 *
 *  เขียนให้รองรับ PHP 5.2.6
 * ============================================================ */


/* ============================================================
 *  จุดเดียวที่คุมรูปแบบวันที่ของทั้งระบบ
 *
 *  ตัวอักษรในช่อง formats ใช้ความหมายเดียวกับ date() ของ PHP
 *  เพื่อไม่ต้องจำชุดใหม่ ต่างกันแค่ปีที่เป็น พ.ศ. แล้ว
 *
 *      j  วันที่ (1-31)          d  วันที่สองหลัก (01-31)
 *      n  เดือน (1-12)           m  เดือนสองหลัก (01-12)
 *      M  ชื่อเดือนย่อ (ส.ค.)     F  ชื่อเดือนเต็ม (สิงหาคม)
 *      Y  ปี พ.ศ. เต็ม (2569)    y  ปี พ.ศ. สองหลัก (69)
 *      G  ชั่วโมง (0-23)          H  ชั่วโมงสองหลัก (00-23)
 *      i  นาทีสองหลัก            s  วินาทีสองหลัก
 *      D  ชื่อวันย่อ (พฤ)
 *
 *  ตัวอักษรอื่นและข้อความไทยผ่านไปตรง ๆ ถ้าต้องการตัวอักษรข้างบน
 *  แบบตรงตัวให้ใส่ \ นำหน้า
 * ============================================================ */
function thai_date_config()
{
    static $cfg = null;
    if ($cfg !== null) { return $cfg; }

    $cfg = array(

        /* ส่วนต่างของปี — ตั้ง 0 เมื่อไหร่ทั้งระบบกลับไปใช้ ค.ศ. ทันที */
        'era' => 543,

        /* index 1-12 ตรงกับเลขเดือนจริง ช่อง 0 เว้นว่างไว้ จะได้ไม่ต้องลบหนึ่งทุกครั้ง */
        'months_short' => array('', 'ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.',
                                    'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.'),

        'months_long'  => array('', 'มกราคม', 'กุมภาพันธ์', 'มีนาคม', 'เมษายน', 'พฤษภาคม', 'มิถุนายน',
                                    'กรกฎาคม', 'สิงหาคม', 'กันยายน', 'ตุลาคม', 'พฤศจิกายน', 'ธันวาคม'),

        /* index 0-6 ตรงกับ date('w') คือ อาทิตย์ = 0 */
        'days_short'   => array('อา', 'จ', 'อ', 'พ', 'พฤ', 'ศ', 'ส'),

        'formats' => array(

            /* รูปแบบหลักของระบบ ใช้ในตาราง กล่องรายละเอียด และการ์ดสรุป
               ปีสองหลักเพราะตารางมีวันที่เรียงกันหลายบรรทัด คนอ่านรู้ปีจากบริบทอยู่แล้ว */
            'short'     => 'j M y',

            /* เอกสารที่พิมพ์เป็นหลักฐาน ต้องอ่านได้โดยไม่ต้องเดาปี */
            'long'      => 'j F Y',

            /* วันที่พร้อมเวลา — ตัดวินาทีทิ้ง ไม่มีใครใช้ตัดสินอะไร
               แต่กินที่ในคอลัมน์และดึงสายตาไปจากตัวเลขที่มีความหมาย */
            'date_time' => 'j M y H:i',

            /* เวลาอย่างเดียว ใช้ในรายการที่รู้อยู่แล้วว่าเป็นของวันนี้ */
            'time'      => 'H:i',

            /* หัวรายงาน "ข้อมูล ณ ..." และท้ายอีเมล */
            'stamp'     => 'j M Y เวลา H:i',

            /* เดือนของรายงานรายเดือน */
            'month'     => 'F Y',

            /* หัวกลุ่มของรายการที่จัดตามวัน — ปีเต็มเพราะหัวกลุ่มมีอันเดียว
               คุมหลายรายการ จึงไม่ได้เบียดที่ และเป็นจุดอ้างอิงปีของทั้งกลุ่ม */
            'day_label' => 'j M Y',

            /* ป้ายแกนนอนของกราฟหน้าแรก แยกตามหน่วยที่เลือกดู */
            'axis_day'         => 'j M',
            'axis_day_short'   => 'D',
            'axis_month'       => 'M y',
            'axis_month_short' => 'M',
            'axis_year'        => 'Y'
        ),

        /* สิ่งที่แสดงเมื่อไม่มีวันที่ — ช่องว่างเปล่า ๆ ในตารางดูเหมือนหน้าจอโหลดไม่เสร็จ */
        'empty' => '—',

        /* สองวันล่าสุดใช้คำแทนตัวเลข เพราะเป็นช่วงที่คนอ่านต้องรู้ว่า "เพิ่งเกิด"
           ส่วนที่เก่ากว่านั้นใช้วันที่จริง เพราะ "3 วันที่แล้ว" ต้องนั่งนับย้อนเอง */
        'today'     => 'วันนี้',
        'yesterday' => 'เมื่อวาน'
    );

    return $cfg;
}


/* ชื่อเดือน — เปิดให้เรียกตรง ๆ สำหรับที่ที่ต้องการรายชื่อทั้งชุด เช่น ตัวเลือกเดือน */
function thai_month_names($short = true)
{
    $cfg = thai_date_config();
    return $short ? $cfg['months_short'] : $cfg['months_long'];
}

function thai_day_names()
{
    $cfg = thai_date_config();
    return $cfg['days_short'];
}


/* คืน 0 ถ้าแปลงไม่ได้ ให้ผู้เรียกตัดสินใจเองว่าจะแสดงอะไรแทน
 * ดัก '0000-00-00' แยก เพราะ strtotime จะได้ปี 1970 แล้วหน้าจอขึ้นวันที่
 * ที่ดูเหมือนของจริงทั้งที่ไม่มีข้อมูล ซึ่งอันตรายกว่าเว้นว่าง */
function thai_ts($value)
{
    $value = trim((string)$value);

    if ($value === '' || $value === null)          { return 0; }
    if (substr($value, 0, 10) === '0000-00-00')    { return 0; }
    if (substr($value, 0, 10) === '1000-01-01')    { return 0; }   // ค่าเริ่มต้นของ created_at ในสคีมานี้

    $ts = @strtotime($value);
    return $ts ? $ts : 0;
}


/* ---------- ตัวแปลงกลาง: วันที่ + รูปแบบ -> ข้อความ ----------
 * $format รับได้ทั้งชื่อรูปแบบใน config ('short', 'long', ...) และตัวรูปแบบเอง ('j/n/Y')
 * รับชื่อได้ด้วยเพราะที่เรียกใช้ส่วนใหญ่ควรอ้างชื่อ ไม่ใช่เขียนรูปแบบซ้ำ ๆ กระจายทั้งระบบ
 *
 * $empty เป็น null แปลว่าใช้ค่าจาก config ไม่ใช่ "ไม่แสดงอะไรเลย"
 * ที่ที่ต้องการช่องว่างจริง ๆ (เช่นเอกสารพิมพ์ที่มีเส้นประให้เซ็น) ส่ง '' มาเอง
 */
function thai_date_format($value, $format = 'short', $empty = null)
{
    $cfg = thai_date_config();

    if ($empty === null) { $empty = $cfg['empty']; }

    $ts = thai_ts($value);
    if ($ts === 0) { return $empty; }

    $pattern = isset($cfg['formats'][$format]) ? $cfg['formats'][$format] : $format;

    $year = (int)date('Y', $ts) + (int)$cfg['era'];
    $mon  = (int)date('n', $ts);

    $out = '';
    $len = strlen($pattern);

    /* ไล่ทีละไบต์ได้เพราะตัวอักษรที่เป็นรหัสเป็น ASCII ทั้งหมด
       ส่วนข้อความไทยในรูปแบบเป็นไบต์ที่มีบิตสูง จึงไม่ชนกันและต่อกลับได้ครบ */
    for ($i = 0; $i < $len; $i++) {
        $c = substr($pattern, $i, 1);

        if ($c === '\\') {                                  // \ นำหน้า = เอาตัวถัดไปตรงตัว
            $i++;
            if ($i < $len) { $out .= substr($pattern, $i, 1); }
            continue;
        }

        switch ($c) {
            case 'j': $out .= (int)date('j', $ts);                    break;
            case 'd': $out .= date('d', $ts);                         break;
            case 'n': $out .= $mon;                                   break;
            case 'm': $out .= date('m', $ts);                         break;
            case 'M': $out .= $cfg['months_short'][$mon];             break;
            case 'F': $out .= $cfg['months_long'][$mon];              break;
            case 'Y': $out .= $year;                                  break;
            case 'y': $out .= substr((string)$year, -2);              break;
            case 'G': $out .= (int)date('G', $ts);                    break;
            case 'H': $out .= date('H', $ts);                         break;
            case 'i': $out .= date('i', $ts);                         break;
            case 's': $out .= date('s', $ts);                         break;
            case 'D': $out .= $cfg['days_short'][(int)date('w', $ts)]; break;
            default:  $out .= $c;
        }
    }

    return $out;
}


/* ---------- 13 ส.ค. 69 ---------- */
function thai_date($value, $empty = null)
{
    return thai_date_format($value, 'short', $empty);
}


/* ---------- 13 สิงหาคม 2569 ----------
 * ค่าว่างเป็นข้อความเปล่าไม่ใช่ขีดกลาง เพราะที่ใช้คือเอกสารพิมพ์
 * ซึ่งมีเส้นประไว้ให้เขียนมือแทนอยู่แล้ว
 */
function thai_date_long($value, $empty = '')
{
    return thai_date_format($value, 'long', $empty);
}


/* ---------- 13 ส.ค. 69 14:32 ----------
 * ค่าที่ไม่มีเวลาติดมา (คอลัมน์ DATE) ไม่เติม 00:00 ให้ เพราะเป็นการแต่งข้อมูล
 * คนอ่านจะนึกว่าเอกสารถูกบันทึกตอนเที่ยงคืน
 *
 * ดูจากข้อความต้นทาง ไม่ใช่จาก timestamp เพราะ strtotime เติมเที่ยงคืนให้เสมอ
 */
function thai_date_time($value, $empty = null)
{
    $has_time = preg_match('/\d{1,2}:\d{2}/', (string)$value);

    return thai_date_format($value, $has_time ? 'date_time' : 'short', $empty);
}


/* ---------- เวลาตอนนี้ ----------
 * ใช้กับหัวรายงาน "ข้อมูล ณ ..." และท้ายอีเมล ที่เดิมเขียน date('d/m/Y H:i') กระจายกันเอง
 */
function thai_now($format = 'stamp')
{
    return thai_date_format(date('Y-m-d H:i:s'), $format);
}


/* ---------- ป้ายหัวกลุ่มของรายการที่จัดตามวัน ----------
 * 'วันนี้' / 'เมื่อวาน' / '21 ก.ค. 2569'
 * คู่แฝดฝั่งหน้าจอคือ ThaiDate.dayLabel()
 */
function thai_day_label($value, $empty = null)
{
    $cfg = thai_date_config();
    $ts  = thai_ts($value);

    if ($ts === 0) { return ($empty === null) ? $cfg['empty'] : $empty; }

    /* เทียบเป็น "วันตามปฏิทิน" ไม่ใช่ส่วนต่างของเวลา
       ไม่งั้นตอนตีหนึ่งของวันใหม่ ของเมื่อวานสี่ทุ่มจะยังนับเป็น "วันนี้" */
    $day = date('Y-m-d', $ts);

    if ($day === date('Y-m-d'))                          { return $cfg['today']; }
    if ($day === date('Y-m-d', strtotime('-1 day')))     { return $cfg['yesterday']; }

    return thai_date_format($value, 'day_label', $empty);
}


/* ---------- สิงหาคม 2569 ----------
 * รับได้ทั้ง '2026-08' และ '2026-08-13' เพราะหน้ารายงานส่งมาคนละแบบ
 * เติมวันที่ 1 ให้เองเมื่อไม่มี เพราะ '2026-08' เฉย ๆ strtotime ตีความได้หลายอย่าง
 * แล้วแต่เวอร์ชัน PHP
 *
 * เติมศูนย์หน้าเลขเดือนด้วย เพราะบางที่ส่ง '2026-8' มา
 * (ฝั่ง JavaScript ต้องเติมเหมือนกัน ไม่งั้นสองฝั่งรับค่าไม่เท่ากัน)
 */
function thai_month($value, $empty = null)
{
    $parts = explode('-', trim((string)$value));

    if (count($parts) >= 2 && (int)$parts[0] > 0) {
        $value = sprintf('%04d-%02d-%02d',
                         (int)$parts[0],
                         (int)$parts[1],
                         isset($parts[2]) ? (int)$parts[2] : 1);
    }

    return thai_date_format($value, 'month', $empty);
}
