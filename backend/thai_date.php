/* ============================================================
 *  backend/thai_date.php — แปลงวันที่เป็นรูปแบบไทยสำหรับ "แสดงผล" เท่านั้น
 *
 *      thai_date('2026-08-13')            -> 13 ส.ค. 69
 *      thai_date_long('2026-08-13')       -> 13 สิงหาคม 2569
 *      thai_date_time('2026-08-13 14:32') -> 13 ส.ค. 69 14:32
 *      thai_month('2026-08')              -> สิงหาคม 2569
 *
 *  ห้ามเอาผลลัพธ์กลับไปเก็บ — ฐานข้อมูลต้องเป็น ค.ศ. เหมือนเดิม
 *  ไม่งั้น MySQL จะเรียงตามตัวอักษรแล้วรายงานย้อนหลังผิดโดยไม่มีอะไรฟ้อง
 *
 *  ฝั่งหน้าจอมีคู่แฝดที่ assets/js/thai-date.js แก้ที่ไหนต้องแก้อีกที่ให้ตรงกัน
 *
 *  ปีสองหลักใช้ในตารางที่มีวันที่เรียงกันหลายบรรทัด ซึ่งคนอ่านรู้ปีจากบริบทแล้ว
 *  ส่วนเอกสารที่พิมพ์เป็นหลักฐานใช้ thai_date_long() ที่มีปีเต็ม
 *
 *  เขียนให้รองรับ PHP 5.2.6
 * ============================================================ */

/* index 1-12 ตรงกับเลขเดือนจริง ช่อง 0 เว้นว่างไว้ จะได้ไม่ต้องลบหนึ่งทุกครั้ง */
function thai_month_names($short = true)
{
    if ($short) {
        return array('', 'ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.',
                         'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.');
    }
    return array('', 'มกราคม', 'กุมภาพันธ์', 'มีนาคม', 'เมษายน', 'พฤษภาคม', 'มิถุนายน',
                     'กรกฎาคม', 'สิงหาคม', 'กันยายน', 'ตุลาคม', 'พฤศจิกายน', 'ธันวาคม');
}


/* คืน 0 ถ้าแปลงไม่ได้ ให้ผู้เรียกตัดสินใจเองว่าจะแสดงอะไรแทน
 * ดัก '0000-00-00' แยก เพราะ strtotime จะได้ปี 1970 แล้วหน้าจอขึ้นวันที่
 * ที่ดูเหมือนของจริงทั้งที่ไม่มีข้อมูล ซึ่งอันตรายกว่าเว้นว่าง */
function thai_ts($value)
{
    $value = trim((string)$value);

    if ($value === '' || $value === null)          { return 0; }
    if (substr($value, 0, 10) === '0000-00-00')    { return 0; }
    if (substr($value, 0, 10) === '1000-01-01')    { return 0; }   // ค่าเริ่มต้นของ created_at ในสคีมานี้

    $ts = @strtotime($value);
    return $ts ? $ts : 0;
}


/* ---------- 13 ส.ค. 69 ----------
 * รูปแบบหลักของระบบ ใช้ในตาราง กล่องรายละเอียด และการ์ดสรุป
 * $empty คือสิ่งที่จะแสดงเมื่อไม่มีวันที่ ตั้งเป็นขีดกลางไว้
 * เพราะช่องว่างเปล่า ๆ ในตารางดูเหมือนหน้าจอโหลดไม่เสร็จ
 */
function thai_date($value, $empty = '—')
{
    $ts = thai_ts($value);
    if ($ts === 0) { return $empty; }

    $m = thai_month_names(true);
    $y = (int)date('Y', $ts) + 543;

    return (int)date('j', $ts) . ' ' . $m[(int)date('n', $ts)] . ' ' . substr((string)$y, -2);
}


/* ---------- 13 สิงหาคม 2569 ----------
 * สำหรับเอกสารที่พิมพ์ออกไปเป็นหลักฐาน ต้องอ่านได้โดยไม่ต้องเดาปี
 */
function thai_date_long($value, $empty = '')
{
    $ts = thai_ts($value);
    if ($ts === 0) { return $empty; }

    $m = thai_month_names(false);

    return (int)date('j', $ts) . ' ' . $m[(int)date('n', $ts)]
         . ' ' . ((int)date('Y', $ts) + 543);
}


/* ---------- 13 ส.ค. 69 14:32 ----------
 * ตัดวินาทีทิ้ง ไม่มีใครใช้ตัดสินอะไร
 * ค่าที่ไม่มีเวลาติดมา (คอลัมน์ DATE) ไม่เติม 00:00 ให้ เพราะเป็นการแต่งข้อมูล
 * คนอ่านจะนึกว่าเอกสารถูกบันทึกตอนเที่ยงคืน */
function thai_date_time($value, $empty = '—')
{
    $ts = thai_ts($value);
    if ($ts === 0) { return $empty; }

    $out = thai_date($value, $empty);

    /* มีเวลาติดมาก็ต่อเมื่อข้อความมีส่วนของเวลาจริง ๆ ไม่ใช่ดูจาก timestamp
       เพราะ strtotime เติมเที่ยงคืนให้เสมออยู่แล้วเมื่อไม่มีเวลา */
    $has_time = preg_match('/\d{2}:\d{2}/', (string)$value);

    return $has_time ? ($out . ' ' . date('H:i', $ts)) : $out;
}


/* ---------- ป้ายหัวกลุ่มของรายการที่จัดตามวัน ----------
 * 'วันนี้' / 'เมื่อวาน' / '21 ก.ค. 2569'
 * สองวันล่าสุดใช้คำแทนตัวเลข ที่เก่ากว่านั้นใช้วันที่จริง เพราะ "3 วันที่แล้ว"
 * ต้องนั่งนับย้อนเอง ใช้ปีเต็มเพราะหัวกลุ่มเป็นจุดอ้างอิงเดียวของทั้งกลุ่ม
 * คู่แฝดฝั่งหน้าจอคือ ThaiDate.dayLabel() */
function thai_day_label($value, $empty = '—')
{
    $ts = thai_ts($value);
    if ($ts === 0) { return $empty; }

    /* เทียบเป็น "วันตามปฏิทิน" ไม่ใช่ส่วนต่างของเวลา
       ไม่งั้นตอนตีหนึ่งของวันใหม่ ของเมื่อวานสี่ทุ่มจะยังนับเป็น "วันนี้" */
    $day   = date('Y-m-d', $ts);
    $today = date('Y-m-d');
    $yest  = date('Y-m-d', strtotime('-1 day'));

    if ($day === $today) { return 'วันนี้'; }
    if ($day === $yest)  { return 'เมื่อวาน'; }

    $m = thai_month_names(true);
    return (int)date('j', $ts) . ' ' . $m[(int)date('n', $ts)]
         . ' ' . ((int)date('Y', $ts) + 543);
}


/* ---------- สิงหาคม 2569 ----------
 * รับได้ทั้ง '2026-08' และ '2026-08-13' เพราะหน้ารายงานส่งมาคนละแบบ
 * ไม่พึ่ง strtotime เพราะ '2026-08' เฉย ๆ ตีความได้หลายอย่างแล้วแต่เวอร์ชัน PHP
 */
function thai_month($value, $empty = '—')
{
    $parts = explode('-', trim((string)$value));
    if (count($parts) < 2) { return $empty; }

    $y = (int)$parts[0];
    $m = (int)$parts[1];
    if ($y <= 0 || $m < 1 || $m > 12) { return $empty; }

    $names = thai_month_names(false);
    return $names[$m] . ' ' . ($y + 543);
}
